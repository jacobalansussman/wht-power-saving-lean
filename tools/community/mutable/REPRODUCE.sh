#!/bin/bash
# Mutable sources: the exact checks and prices behind community/c588m, and the two generated engine files.
# Python only (exact rational arithmetic); a few minutes. The Lean side is built on the Colab with the package
# (VERIFY.md, section 11); XMut/ here holds the seven engine files as written (import XMut.X; the package's
# copies under Work/XMut differ only in the import prefix, see tools/community/c588m-gen/relocate_xmut.py).
#
# usage: SHEA=<clone of github.com/shea256/fourier-transform-below-nlogn at 5239484> tools/community/mutable/REPRODUCE.sh [work dir]
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd); ROOT=$(cd "$HERE/../../.." && pwd)
: "${SHEA:?set SHEA to a clone of github.com/shea256/fourier-transform-below-nlogn at 5239484}"
C=$SHEA/lean/complex588
W=${1:-$HERE/out}; mkdir -p "$W/sa"
RT=$ROOT/tools/community/route
PY="python3 -I"
# 1. Shea's certificate with its 112 source copies, read back from his generated Lean data (text parse only);
#    must equal inputs/c588-shea-copies.raw.json.gz
$PY "$HERE/lean_raw_to_gcert.py" "$C/Work/GCert/Data/Gen/C588/S0.lean" "$W/c588-shea-copies.raw.json.gz"
# 2. exact checks: the control (Shea's certificate), the word with the copies folded back (mutable sources), and
#    two counterexample controls; writes c588-no-copies.gcert.json.gz (= tools/community/c588m-gen/inputs/)
$PY "$HERE/run_checks.py" "$ROOT/tools/gx/gx.py" "$W/c588-shea-copies.raw.json.gz" "$W" > "$W/run_checks.log"
# 3. prices through Shea's route (cyclic banks); the control 12331685 comes first
$PY "$RT/route_price.py" "$HERE/inputs/price-spec.json" "$W/price-cyclic.json"
# 4. annealed bank packings (simulated annealing, seeded) and their model prices
$PY "$RT/price_sa.py" "$HERE/inputs/sa-588.json" "$W/sa" 56,57 4000000
# 5. the packed-replay mirror of the new kernel scalar check (units and digit width for the Lean data)
$PY "$HERE/gsmirrorZ.py" "$W/c588-no-copies.gcert.json.gz" > "$W/gsmirrorZ.log"
# 6. the two engine files generated by text substitution from Nil Mamano's gauged files in Shea's tree
$PY "$HERE/make_labelsZ.py" "$C/Work/Gauge/Labels.lean" "$W/Labels.lean"
$PY "$HERE/make_echeckZ.py" "$C/Work/Gauge/ECheck.lean" "$W/ECheckZ.lean"
# 7. compare
for p in "c588-shea-copies.raw.json.gz:$HERE/inputs/c588-shea-copies.raw.json.gz" \
         "c588-no-copies.gcert.json.gz:$ROOT/tools/community/c588m-gen/inputs/c588-no-copies.gcert.json.gz" \
         "sa/588atm3_mutable_sources_no_copies.schedule.json.gz:$ROOT/tools/community/c588m-gen/inputs/588atm3_mutable_sources_no_copies.schedule.json.gz" \
         "Labels.lean:$HERE/XMut/Labels.lean" "ECheckZ.lean:$HERE/XMut/ECheckZ.lean"; do
  a=${p%%:*}; b=${p#*:}
  if cmp -s "$W/$a" "$b"; then echo "same: $a"
  elif [ "${a%.json.gz}" != "$a" ] && $PY -c 'import gzip,json,sys
x=json.load(gzip.open(sys.argv[1])); y=json.load(gzip.open(sys.argv[2]))
sys.exit(0 if all(x[k]==y.get(k) for k in x) else 1)' "$W/$a" "$b"; then
    echo "same circuit: $a (every field of the regenerated file is equal in the published one, which may carry extra notes)"
  else echo "DIFFERS: $a"; fi
done
