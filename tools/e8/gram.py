"""gram.py -- (1) grammar(): greedy hierarchical sharing of partial sums ('Re-Pair' on the 120 need lists),
optionally applied by whole orbits of a group; (2) compile(): the grammar -> e8.Design with register allocation;
(3) evaluate with e8.quick.  Standard library only."""
