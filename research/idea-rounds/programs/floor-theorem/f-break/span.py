#!/usr/bin/env python3
"""span.py m f prime [bim]: finite-f test of the floor, exact modulo a prime p = 1 mod 4 (i -> a square root of -1 mod p). Pure Python.
B = group generated by the engine's free maps on one m-bit address column (shifts, linear address maps, phases 1/i).
A_f = complex span of { b^(tensor f) : b in B }  = everything a zero-block program can do to one array with f digit columns.
(1) is K^(tensor f) in A_f ?  (zero blocks serve an array at this f)
(2) dim(A_f + A_f K^f) against 2 dim A_f. If equal, the counting lemma holds AT THIS f alone: blocks >= W.
(3) bim, m>=2: G = dir(e1)^(tensor f); is K^f in A + A G A (one layer of rank-1 blocks, any number of them)?
A rank computed mod p is at most the rank over Q(i); 'in span' answers are checked with two primes by the caller.
"""
import sys, itertools, time
m = int(sys.argv[1]); f = int(sys.argv[2]); p = int(sys.argv[3])
d = 2**m; n = d**f; L = n*n
I = next(x for x in range(2, p) if x*x % p == p-1)
inv2 = pow(2, p-2, p); ipow = [1, I, p-1, (p-I) % p]
t0 = time.time()
def comp(a, b):
    pa, ha = a; pb, hb = b
    return (tuple(pa[pb[x]] for x in range(d)), tuple((hb[x] + ha[pb[x]]) % 4 for x in range(d)))
gens = []
for z in range(1, d): gens.append((tuple(x ^ z for x in range(d)), (0,)*d))
for i in range(m):
    for j in range(m):
        if i != j: gens.append((tuple(x ^ (((x >> j) & 1) << i) for x in range(d)), (0,)*d))
for z in range(d):
    for c in range(2):
        if z == 0 and c == 0: continue
        gens.append((tuple(range(d)), tuple((bin(z & x).count('1') + c) % 2 for x in range(d))))
ident = (tuple(range(d)), (0,)*d)
seen = {ident}; frontier = [ident]
while frontier:
    nxt = []
    for a in frontier:
        for g in gens:
            c = comp(g, a)
            if c not in seen: seen.add(c); nxt.append(c)
    frontier = nxt
reps = sorted({(pm, tuple((h - ph[0]) % 4 for h in ph)) for pm, ph in seen})
print(f"m={m} f={f} p={p} sqrt(-1)={I} |B|={len(seen)} |B/scalars|={len(reps)} dim End(V)={L}", flush=True)
cols = list(itertools.product(range(d), repeat=f)); colidx = {c: k for k, c in enumerate(cols)}
def tpow(b):
    pm, ph = b
    return ([colidx[tuple(pm[x] for x in c)] for c in cols], [ipow[sum(ph[x] for x in c) % 4] for c in cols])
class Span:
    def __init__(s): s.rows = {}; s.order = []
    def reduce(s, v):
        v = list(v)
        for k in s.order:
            c = v[k]
            if c:
                r = s.rows[k]
                v = [(a - c*b) % p for a, b in zip(v, r)]
        return v
    def add(s, v):
        v = s.reduce(v)
        k = next((j for j, a in enumerate(v) if a), None)
        if k is None: return False
        iv = pow(v[k], p-2, p); v = [a*iv % p for a in v]
        s.rows[k] = v; s.order.append(k); return True
    def has(s, v): return not any(s.reduce(v))
    def dim(s): return len(s.order)
    def copy(s):
        t = Span(); t.rows = dict(s.rows); t.order = list(s.order); return t
def kron(A, Bm):
    ra, rb = len(A), len(Bm)
    return [[A[i][j]*Bm[k][l] % p for j in range(ra) for l in range(rb)] for i in range(ra) for k in range(rb)]
a, bb = (1 + I)*inv2 % p, (1 - I)*inv2 % p
C = [[a, bb], [bb, a]]
def kpow(M, e):
    R = [[1]]
    for _ in range(e): R = kron(R, M)
    return R
K1 = kpow(C, m); Kf = kpow(K1, f)
flat = lambda M: [x for row in M for x in row]
A = Span(); tp = [tpow(b) for b in reps]
for rows, vals in tp:
    v = [0]*L
    for c in range(n): v[rows[c]*n + c] = vals[c]
    A.add(v)
dA = A.dim()
print(f"(1) dim A_f = {dA}   K^f in A_f: {A.has(flat(Kf))}   [{time.time()-t0:.1f}s]", flush=True)
S2 = A.copy(); cnt = 0
for rows, vals in tp:
    M = [None]*n
    for c in range(n):
        vc = vals[c]; M[rows[c]] = [vc*x % p for x in Kf[c]]
    if S2.add(flat(M)): cnt += 1
print(f"(2) dim(A_f + A_f K^f) = {S2.dim()} = dim A_f + {cnt};  2 dim A_f = {2*dA};  dim(A K^f ∩ A) = {2*dA - S2.dim()};"
      f"  finite-f count: blocks >= W * {cnt}/{dA}   [{time.time()-t0:.1f}s]", flush=True)
if m >= 2 and len(sys.argv) > 4:
    def dense(b):
        rows, vals = tpow(b); M = [[0]*n for _ in range(n)]
        for c in range(n): M[rows[c]][c] = vals[c]
        return rows, vals
    D1 = kron(C, [[int(i == j) for j in range(d//2)] for i in range(d//2)])
    G = kpow(D1, f)
    gm = [tpow(g) for g in gens]
    def lmul(g, X):   # g^f X : row rows[c] = vals[c] * X[c]
        rows, vals = g; M = [None]*n
        for c in range(n): M[rows[c]] = [vals[c]*x % p for x in X[c]]
        return M
    def rmul(X, g):   # X g^f : column c of result = vals[c] * column rows[c] of X
        rows, vals = g
        return [[vals[c]*Xr[rows[c]] % p for c in range(n)] for Xr in X]
    S3 = A.copy(); queue = [G]; S3.add(flat(G))
    while queue:
        X = queue.pop()
        for g in gm:
            for Y in (lmul(g, X), rmul(X, g)):
                if S3.add(flat(Y)): queue.append(Y)
    print(f"(3) dim(A + A G A) = {S3.dim()} (G = dir(e)^f, a rank-1 block)   K^f in A + A G A: {S3.has(flat(Kf))}   [{time.time()-t0:.1f}s]", flush=True)
