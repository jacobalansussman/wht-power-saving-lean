# f-model, hatch H2: with ONE address map that mixes two digit columns, the kernel on two columns (m = 1, f = 2,
# array length 4) needs no block at all.  Exact: Python complex with dyadic parts.
I = 1j
a, b = (1 + I) / 2, (1 - I) / 2
C = [[a, b], [b, a]]
idx = [(0, 0), (0, 1), (1, 0), (1, 1)]                       # address = (digit 1, digit 2)
U = [[C[x[0]][y[0]] * C[x[1]][y[1]] for y in idx] for x in idx]   # kernel on both columns
def mm(A, B): return [[sum(A[i][k] * B[k][j] for k in range(4)) for j in range(4)] for i in range(4)]
def lin(images):                                             # matrix from images of basis vectors e00,e01,e10,e11
    return [[images[j][i] for j in range(4)] for i in range(4)]
e = lambda k: [1 if j == k else 0 for j in range(4)]
add = lambda u, v, c=1: [x + c * y for x, y in zip(u, v)]
half = lambda u: [x / 2 for x in u]
# F2: (e00+e11) -> e11, (e00-e11) -> e00, (e01+e10) -> e10, (e01-e10) -> e01   (keeps the sets {00,11} and {01,10})
F2 = lin([half(add(e(3), e(0))), half(add(e(2), e(1))), half(add(e(2), e(1), -1)), half(add(e(3), e(0), -1))])
# P: the address map  digit2 <- digit2 + digit1 : swaps entries 10 and 11
P = lin([e(0), e(1), e(3), e(2)])
# F1: e10 -> (e01+e10)/1 scaled, e11 -> (e00+e11), e00 -> i(e00-e11), e01 -> i(e01-e10), with the scalings that make U
sD, aD, sO, aO = add(e(0), e(3)), add(e(0), e(3), -1), add(e(1), e(2)), add(e(1), e(2), -1)
F1 = lin([[I * x for x in aD], [I * x for x in aO], sO, sD])
ok = mm(F1, mm(P, F2)) == [[complex(z) for z in row] for row in U]
blind = lambda M: all(M[i][j] == 0 for i in range(4) for j in range(4) if (i in (0, 3)) != (j in (0, 3)))
print("kernel on two columns (n = 4) = F1 * (digit2 <- digit2 + digit1) * F2 exactly:", ok)
print("F1 and F2 keep the sets {00,11} and {01,10} (blind to the witness):", blind(F1), blind(F2), "; the address map does not:", blind(P))
# F1, F2 are combinations of column-uniform steps: on {00,11} and on {01,10} they are 2x2 maps, and
# the algebra generated by (shift both digits) and (entrywise scalings) is all such block maps (dimension 8).
