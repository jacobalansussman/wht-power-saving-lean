def kron(A,B):
    return [[A[i][j]*B[k][l] for j in range(len(A[0])) for l in range(len(B[0]))] for i in range(len(A)) for k in range(len(B))]
def eye(n): return [[ONE if i==j else ZERO for j in range(n)] for i in range(n)]
def flat(A): return [x for r in A for x in r]
def mkey(A): return tuple(x.key() for r in A for x in r)
def rank(vs):
    vs=[list(v) for v in vs]; r=0; ncol=len(vs[0]) if vs else 0
    for c in range(ncol):
        p=None
        for i in range(r,len(vs)):
            if vs[i][c].nz(): p=i;break
        if p is None: continue
        vs[r],vs[p]=vs[p],vs[r]; iv=vs[r][c].inv()
        vs[r]=[x*iv for x in vs[r]]
        for i in range(len(vs)):
            if i!=r and vs[i][c].nz():
                f=vs[i][c]; vs[i]=[x-f*y for x,y in zip(vs[i],vs[r])]
        r+=1
        if r==len(vs): break
    return r
