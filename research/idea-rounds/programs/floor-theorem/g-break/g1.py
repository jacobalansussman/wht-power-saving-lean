class Z:
    __slots__=("a","b")
    def __init__(s,a=0,b=0): s.a=Fr(a); s.b=Fr(b)
    def __add__(s,o): return Z(s.a+o.a,s.b+o.b)
    def __sub__(s,o): return Z(s.a-o.a,s.b-o.b)
    def __mul__(s,o): return Z(s.a*o.a-s.b*o.b,s.a*o.b+s.b*o.a)
    def inv(s):
        n=s.a*s.a+s.b*s.b; return Z(s.a/n,-s.b/n)
    def nz(s): return s.a!=0 or s.b!=0
    def key(s): return (s.a,s.b)
ZERO=Z(0,0); ONE=Z(1,0); I_=Z(0,1)
def mat(rows): return [[x if isinstance(x,Z) else Z(x) for x in r] for r in rows]
def mm(A,B):
    n=len(A); m=len(B[0]); k=len(B)
    return [[sum_((A[i][t]*B[t][j] for t in range(k))) for j in range(m)] for i in range(n)]
