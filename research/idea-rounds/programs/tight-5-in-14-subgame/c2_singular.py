# c2_singular.py -- are Lemma C's 30 admissible positions the 30 maximal totally singular subspaces of q0 = x.z ?
# Checks: the 135 Lagrangians, the q0-singular ones, their distances to L_Z and L_X (Lemma C's labels), the
# adjacency graph among them (7-regular bipartite = point-plane incidence of PG(3,2)?), and that h, K and the Levi
# preserve q0, |O(q0)| = 40320, |B cap O(q0)| = 1344.
import itertools, numpy as np
from lib514 import *
lag = set()
for vs in itertools.combinations(range(1, NV), 3):
    S = span(vs)
    if len(S) == 8 and all(BTAB[a, b] == 0 for a in S for b in S): lag.add(S)
lag = sorted(lag, key=lambda S: sorted(S)); print('Lagrangians:', len(lag))
def dist(F1, F2): return 3 - {1: 0, 2: 1, 4: 2, 8: 3}[len(F1 & F2)]
sing = [F for F in lag if all(q0(v) == 0 for v in F)]
print('q0-singular Lagrangians:', len(sing))
from collections import Counter
lab = Counter((dist(LZ, F), dist(LX, F)) for F in sing)
print('(dist to L_Z, dist to L_X) of the singular ones:', sorted(lab.items()))
laball = Counter((dist(LZ, F), dist(LX, F)) for F in lag)
print('same for all 135:', sorted(laball.items()))
# adjacency among singular ones
adj = {i: [j for j in range(30) if dist(sing[i], sing[j]) == 1] for i in range(30)}
print('degrees in the singular subgraph:', Counter(len(v) for v in adj.values()))
# bipartition by parity of distance from L_Z
part = [dist(LZ, F) % 2 for F in sing]
print('bipartite:', all(part[i] != part[j] for i in adj for j in adj[i]), ' part sizes', Counter(part))
# intersection pattern same family / different family
same = Counter(len(sing[i] & sing[j]) for i in range(30) for j in range(30) if i < j and part[i] == part[j])
diff = Counter(len(sing[i] & sing[j]) for i in range(30) for j in range(30) if part[i] != part[j])
print('|F1 cap F2| same part:', dict(same), ' different parts:', dict(diff))
# group facts
def preserves_q0(g): return all(q0(int(g[v])) == q0(v) for v in range(NV))
print('h preserves q0:', preserves_q0(h1), ' K:', preserves_q0(K), ' all Levi:', all(preserves_q0(l) for l in LEVI))
print('radical elements preserving q0:', sum(preserves_q0(a) for a in gen_closure(A_GENS)))
# O(q0) generated by the 28 reflections t_v, q0(v) = 1
refl = [TRANS[v] for v in range(1, NV) if q0(v) == 1]
Oq = gen_closure(refl); print('|O(q0)| =', len(Oq), '(expect 40320 = |S8|)')
Bp = [g for g in Oq if frozenset(int(g[v]) for v in LZ) == LZ]
print('|B cap O(q0)| =', len(Bp), '(expect 1344 = |AGL(3,2)|)')
# positions of O(q0)/B' = singular Lagrangians: orbit of L_Z under O(q0)
orb = {frozenset(int(g[v]) for v in LZ) for g in Oq}
print('O(q0)-orbit of L_Z:', len(orb), ' equals the singular set:', orb == set(sing))
np.save('singular_lag.npy', np.array([sorted(F) for F in sing]))
