# Emit the certificate data of cert*.json as a Lean file (Dem3Data.lean).
import json, sys
c=json.load(open(sys.argv[1])); p=c["p"]; I=c["I"]
assert p==65537 and I==256
rows=c["rows"]; cols=c["cols"]
def L(xs): return "[" + ", ".join(xs) + "]"
R=[]; C=[]; B=[]
for blk in c["blocks"]:
    R.append(L([L([str(u) for u in rows[r][1:]]) for r in blk["rsel"]]))
    C.append(L([L([str(t) for t in cols[cc][2:]]) for cc in blk["csel"]]))
    B.append(L([L([str(x) for x in row]) for row in blk["B"]]))
out = []
out.append("import Mathlib\n")
out.append("/-! Certificate data for the block-3 hook demand (px-lean, 14 Oct 2026). Generated by py/emit_lean.py")
out.append("from py/blocks.py; untrusted: every use is checked by the kernel. -/\n")
out.append("namespace OAI.PowerSaving.PfLean.Dem3Data\n")
out.append("/-- Selected row representatives `(0, u1, u2, u3, u4)` per character block: the `u`s. -/")
out.append("def rowsD : List (List (List ℕ)) := " + L(R) + "\n")
out.append("/-- Selected column representatives `(0, 0, t1, t2, t3)` per character block: the `t`s. -/")
out.append("def colsD : List (List (List ℕ)) := " + L(C) + "\n")
out.append("/-- Inverses mod 65537 of the selected 28 x 28 blocks. -/")
out.append("def invD : List (List (List ℕ)) := " + L(B) + "\n")
out.append("end OAI.PowerSaving.PfLean.Dem3Data\n")
open(sys.argv[2],"w").write("\n".join(out))
