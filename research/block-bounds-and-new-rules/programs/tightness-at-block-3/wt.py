def _isprime(q):
    if q < 2: return False
    d = 2
    while d * d <= q:
        if q % d == 0: return False
        d += 1
    return True
def prime_below(b, skip=0):
    q = b - 1
    while True:
        if q % 4 == 1 and _isprime(q):
            if skip == 0: return q
            skip -= 1
        q -= 1

n = 8
SUB = {k: list(itertools.combinations(range(n), k)) for k in range(n + 1)}

class Field:
    """mod-p (exact) or complex-float arithmetic for 8x8 letters and module matrices."""
    def __init__(self, p=None):
        self.p = p
        if p:
            self.I = next(pow(g, (p - 1) // 4, p) for g in range(2, 200) if pow(g, (p - 1) // 2, p) == p - 1)
            assert self.I * self.I % p == p - 1
            self.h = pow(2, p - 2, p)
    # 8x8 letters --------------------------------------------------------------------------------------------
    def zeros8(self):
        return np.zeros((n, n), dtype=np.int64 if self.p else complex)
    def ipow(self, q):
        q %= 4
        if self.p: return pow(self.I, q, self.p)
        return 1j ** q
    def dir(self, z):
        M = self.zeros8()
        if self.p:
            a = (1 + self.I) * self.h % self.p; b = (1 - self.I) * self.h % self.p
        else:
            a = (1 + 1j) / 2; b = (1 - 1j) / 2
        for x in range(n):
            M[x, x] = (M[x, x] + a); M[x ^ z, x] = (M[x ^ z, x] + b)
        return self.red(M)
    def perm(self, pi, q=None):
        """monomial letter: e_x -> i^q(x) e_{pi(x)}"""
        M = self.zeros8()
        for x in range(n):
            M[pi[x], x] = self.ipow(q[x] if q is not None else 0)
        return M
    def red(self, M):
        return M % self.p if self.p else M
    def mul(self, A, B):
        if not self.p: return A @ B
        return mulp(A, B, self.p)
    # exterior powers ------------------------------------------------------------------------------------------
    def wedge(self, g, k):
        S = SUB[k]; L = len(S)
        if self.p:
            W = np.zeros((L, L), dtype=np.int64)
            for j, T in enumerate(S):
                for i, U in enumerate(S):
                    W[i, j] = detp([[int(g[u, t]) for t in T] for u in U], self.p) if k else 1
        else:
            W = np.zeros((L, L), complex)
            for j, T in enumerate(S):
                cols = g[:, list(T)]
                for i, U in enumerate(S):
                    W[i, j] = np.linalg.det(cols[list(U), :]) if k else 1
        return W

def detp(a, p):
    a = [row[:] for row in a]; L = len(a); d = 1
    for c in range(L):
        piv = next((r for r in range(c, L) if a[r][c] % p), None)
        if piv is None: return 0
        if piv != c: a[c], a[piv] = a[piv], a[c]; d = -d
        d = d * a[c][c] % p; inv = pow(a[c][c], p - 2, p)
        for r in range(c + 1, L):
            if a[r][c] % p:
                fac = a[r][c] * inv % p
                a[r] = [(a[r][j] - fac * a[c][j]) % p for j in range(L)]
    return d % p

def mulp(A, B, p):
    """exact (A @ B) mod p for p < 2^26: 13-bit splitting, float64 BLAS (sums < 2^37 + log2(k) < 2^53)."""
    A = np.asarray(A, dtype=np.int64) % p; B = np.asarray(B, dtype=np.int64) % p
    A1, A0 = (A >> 13).astype(np.float64), (A & 8191).astype(np.float64)
    B1, B0 = (B >> 13).astype(np.float64), (B & 8191).astype(np.float64)
    hh = np.rint(A1 @ B1).astype(np.int64) % p
    mid = (np.rint(A1 @ B0).astype(np.int64) + np.rint(A0 @ B1).astype(np.int64)) % p
    ll = np.rint(A0 @ B0).astype(np.int64) % p
    return ((hh * (1 << 26)) % p + (mid * (1 << 13)) % p + ll) % p

def rank_p(A, p):
    A = np.ascontiguousarray(np.asarray(A, dtype=np.int64) % p)
    if A.size == 0: return 0
    return int(_LIB.rank_modp(A.ctypes.data_as(ctypes.POINTER(ctypes.c_int64)), A.shape[0], A.shape[1], p))

def rank_f(A, tol=1e-7):
    if A.size == 0: return 0, None
    s = np.linalg.svd(A, compute_uv=False)
    if s[0] == 0: return 0, None
    s = s / max(1.0, s[0])
    r = int((s > tol).sum())
    gap = (s[r - 1] if r else None, s[r] if r < len(s) else None)
    return r, gap

class Module:
    def __init__(self, F, a, b, J):
        self.F, self.a, self.b, self.J = F, a, b, set(J)
        Sa, Sb = SUB[a], SUB[b]
        self.basis = [(T1, T2) for T1 in Sa for T2 in Sb]
        inN = np.array([len(set(T1) & set(T2)) in self.J for (T1, T2) in self.basis])
        self.Nidx = np.nonzero(inN)[0]; self.Cidx = np.nonzero(~inN)[0]
        self.D, self.dN = len(self.basis), len(self.Nidx)
        self.cache = {}
    def rho(self, g, key=None):
        if key is not None and key in self.cache: return self.cache[key]
        F = self.F
        Wa, Wb = F.wedge(g, self.a), F.wedge(g, self.b)
        R = np.kron(Wa, Wb)
        R = R % F.p if F.p else R
        if key is not None: self.cache[key] = R
        return R
    def apply(self, R, X):
        return self.F.mul(R, X)
    def rank(self, A):
        if self.F.p: return rank_p(A, self.F.p)
        return rank_f(A)[0]
    def ident_N(self):
        X = np.zeros((self.D, self.dN), dtype=np.int64 if self.F.p else complex)
        X[self.Nidx, np.arange(self.dN)] = 1
        return X
    def f(self, R):
        """f(g) = rank of pi g |_N"""
        return self.rank(R[np.ix_(self.Cidx, self.Nidx)])

class State:
    """registers x inputs; blk[r][l] = rho(A[r][l]) restricted to N columns (D x dN) or None."""
    def __init__(self, mod, W, R):
        self.m, self.W, self.R = mod, W, R
        self.blk = [[None] * W for _ in range(R)]
        for l in range(W): self.blk[l][l] = mod.ident_N()
    def copy(self):
        s = State.__new__(State); s.m, s.W, s.R = self.m, self.W, self.R
        s.blk = [[None if X is None else X.copy() for X in row] for row in self.blk]
        return s
    def act(self, r, Rg):
        self.blk[r] = [None if X is None else self.m.apply(Rg, X) for X in self.blk[r]]
        return self
    def mix(self, r, coeffs):
        """register r <- sum_s coeffs[s] * register s  (coeffs: dict s -> scalar (int or complex))"""
        F = self.m.F; new = []
        for l in range(self.W):
            acc = None
            for s, c in coeffs.items():
                X = self.blk[s][l]
                if X is None: continue
                if F.p: c = c % F.p
                term = (X * c) % F.p if F.p else X * c
                acc = term if acc is None else ((acc + term) % F.p if F.p else acc + term)
            new.append(acc)
        self.blk[r] = new
        return self
    def phi_matrix(self, regs=None, inputs=None):
        regs = range(self.R) if regs is None else regs
        inputs = range(self.W) if inputs is None else inputs
        C = self.m.Cidx; dt = np.int64 if self.m.F.p else complex
        rows = []
        for r in regs:
            if all(self.blk[r][l] is None for l in inputs): continue
            row = [self.blk[r][l][C, :] if self.blk[r][l] is not None else np.zeros((len(C), self.m.dN), dt)
                   for l in inputs]
            rows.append(np.hstack(row))
        if not rows: return np.zeros((0, 0), dt)
        return np.vstack(rows)
    def phi(self, regs=None, inputs=None):
        return self.m.rank(self.phi_matrix(regs, inputs))

def letters(F):
    """named 8x8 letters: directions, and a sample of free (monomial) letters."""
    L = {}
    for z in range(1, 8): L['d%d' % z] = F.dir(z)
    ident = list(range(n))
    L['id'] = F.perm(ident)
    for z in range(1, 8): L['X%d' % z] = F.perm([x ^ z for x in range(n)])
    # linear maps: CNOTs  x_t ^= x_c
    for c in range(3):
        for t in range(3):
            if c != t: L['CX%d%d' % (c, t)] = F.perm([x ^ ((((x >> c) & 1) << t)) for x in range(n)])
    # Toffoli x_t ^= x_a x_b
    for t in range(3):
        a, b = [u for u in range(3) if u != t]
        L['TOF%d' % t] = F.perm([x ^ (((x >> a) & (x >> b) & 1) << t) for x in range(n)])
    # phases: S on bit j, CZ, CS, CCZ, T-like not available (Z/4 only)
    for j in range(3): L['S%d' % j] = F.perm(ident, [((x >> j) & 1) for x in range(n)])
    for j in range(3): L['Z%d' % j] = F.perm(ident, [2 * ((x >> j) & 1) for x in range(n)])
    L['CZ01'] = F.perm(ident, [2 * ((x & 1) & ((x >> 1) & 1)) for x in range(n)])
    L['CZ12'] = F.perm(ident, [2 * (((x >> 1) & 1) & ((x >> 2) & 1)) for x in range(n)])
    L['CS01'] = F.perm(ident, [((x & 1) & ((x >> 1) & 1)) for x in range(n)])
    L['CS12'] = F.perm(ident, [(((x >> 1) & 1) & ((x >> 2) & 1)) for x in range(n)])
    L['CCZ'] = F.perm(ident, [2 * ((x & 1) & ((x >> 1) & 1) & ((x >> 2) & 1)) for x in range(n)])
    return L

def word(F, L, names):
    """product of letters: names applied right to left as written left to right in time order:
    word(['d1','d2']) = d2 @ d1 (first d1, then d2)."""
    M = L['id']
    for nm in names: M = F.mul(L[nm], M) if F.p else L[nm] @ M
    return M
