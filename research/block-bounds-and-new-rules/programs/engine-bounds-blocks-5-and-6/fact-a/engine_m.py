# v-b56-methods engine_m.py: the Averaging-Lemma hypotheses at block size m (4, 5) by matrices, letters as in
# w-bounds/engine_m3.py (copied from the Lean definitions there): shift z = X^z; dir z = ca*1 + cb*X^z
# (ca=(1+i)/2, cb=(1-i)/2); permMat G for additive bijections G; phaseMat z c = diag i^((z.x) xor c);
# kernel = littleC^{(x)m}.  Checks: every letter is Clifford (conjugates each generator Pauli to a Pauli up to a
# scalar) with a symplectic action; free letters keep L0 = diagonal Paulis; dir z = transvection along (z|0);
# kernel = dir e1...dir em and sends L0 to an opposite Lagrangian; the group generated by the FREE letters has
# exactly m+1 orbits on Lagrangians (the distance spheres around L0) and all letters are transitive on Lagrangians
# => the generated group is distance-transitive (orbit-stabiliser).  Address maps: a generating set of GL(m,2)
# (elementary transvections x_j += x_k and coordinate swaps) instead of all of them.
import sys, itertools
# pure Python (no numpy on this Mac): matrices as lists of lists of complex; all letters are unitary
class Mat:
    def __init__(self, a): self.a = a
    def __matmul__(self, o):
        A, B = self.a, o.a; N = len(A)
        Bt = list(zip(*B))
        return Mat([[sum(x * y for x, y in zip(A[i], Bt[j])) for j in range(N)] for i in range(N)])
    def H(self): return Mat([[self.a[j][i].conjugate() for j in range(len(self.a))] for i in range(len(self.a))])
def zeros(N): return Mat([[0j] * N for _ in range(N)])
def eye(N): M = zeros(N); [M.a[i].__setitem__(i, 1 + 0j) for i in range(N)]; return M
def diag(d): M = zeros(len(d)); [M.a[i].__setitem__(i, complex(d[i])) for i in range(len(d))]; return M
def lin(ca, A, cb, B): return Mat([[ca * x + cb * y for x, y in zip(ra, rb)] for ra, rb in zip(A.a, B.a)])
def kron(A, B):
    a, b = A.a, B.a; na, nb = len(a), len(b)
    return Mat([[a[i // nb][j // nb] * b[i % nb][j % nb] for j in range(na * nb)] for i in range(na * nb)])
def close(A, B): return all(abs(x - y) < 1e-9 for ra, rb in zip(A.a, B.a) for x, y in zip(ra, rb))
m = int(sys.argv[1]); n = 1 << m
def dot(a, b): return bin(a & b).count('1') & 1
def Xm(a):
    M = zeros(n)
    for i in range(n): M.a[i][i ^ a] = 1 + 0j
    return M
def Zm(b): return diag([(-1) ** dot(b, x) for x in range(n)])
def pauli(a, b): return Xm(a) @ Zm(b)
ca, cb = (1 + 1j) / 2, (1 - 1j) / 2
def dirm(z): return lin(ca, eye(n), cb, Xm(z))
def perm(G):
    M = zeros(n)
    for x in range(n): M.a[x][G(x)] = 1 + 0j
    return M
def phase(z, c): return diag([1j ** (dot(z, x) ^ c) for x in range(n)])
lc = Mat([[ca, cb], [cb, ca]]); K = Mat([[1 + 0j]])
for _ in range(m): K = kron(K, lc)
def ident(P):
    # P = s * X^a Z^b ?  return (a, b) or None
    nz = [j for j in range(n) if abs(P.a[0][j]) > 1e-9]
    if len(nz) != 1: return None
    a = nz[0]
    D = Xm(a) @ P          # P = s X^a Z^b  ->  X^a P = s Z^b
    if any(abs(D.a[i][j]) > 1e-9 for i in range(n) for j in range(n) if i != j): return None
    d = [D.a[i][i] for i in range(n)]; s = d[0]
    if abs(abs(s) - 1) > 1e-9: return None
    sig = [x / s for x in d]
    b = 0
    for j in range(m):
        if abs(sig[1 << j] + 1) < 1e-9: b |= 1 << j
        elif abs(sig[1 << j] - 1) > 1e-9: return None
    if not close(D, lin(s, Zm(b), 0, Zm(b))): return None
    return a, b
def sym_action(g):
    gi = g.H(); assert close(g @ gi, eye(n)), 'not unitary'; cols = []
    for j in range(2 * m):
        a, b = (1 << j, 0) if j < m else (0, 1 << (j - m))
        r = ident(g @ pauli(a, b) @ gi)
        assert r is not None, "not Clifford"
        cols.append(r[0] | (r[1] << m))
    return cols  # image of basis vector j
def apply(cols, v):
    w = 0
    for j in range(2 * m):
        if v >> j & 1: w ^= cols[j]
    return w
def omega(u, v):
    mask = (1 << m) - 1
    return (bin((u & mask) & (v >> m)).count('1') + bin((v & mask) & (u >> m)).count('1')) & 1
def is_symp(cols):
    return all(omega(cols[i], cols[j]) == omega(1 << i, 1 << j) for i in range(2 * m) for j in range(2 * m))
def canon(basis):
    piv = {}
    for v in basis:
        for h in sorted(piv, reverse=True):
            if v >> h & 1: v ^= piv[h]
        if v:
            h = v.bit_length() - 1
            for k in list(piv):
                if piv[k] >> h & 1: piv[k] ^= v
            piv[h] = v
    return tuple(sorted(piv.values()))
L0 = canon([1 << (m + j) for j in range(m)])
# free letters
free = [('shift', Xm(1 << j)) for j in range(m)]
for j in range(m):
    for k in range(m):
        if j != k:
            free.append(('add', perm(lambda x, j=j, k=k: x ^ ((x >> k & 1) << j))))
            free.append(('swap', perm(lambda x, j=j, k=k: x ^ (((x >> j ^ x >> k) & 1) * ((1 << j) | (1 << k))))))
for z in range(n):
    for c in (0, 1): free.append(('phase', phase(z, c)))
ok = True; facts = []
fa = []
for name, g in free:
    cols = sym_action(g); ok &= is_symp(cols)
    ok &= canon([apply(cols, v) for v in L0]) == L0
    fa.append(cols)
facts.append(f"free letters ({len(free)}): Clifford, symplectic, keep L0: {ok}")
ok1 = True; da = []
for z in range(1, n):
    cols = sym_action(dirm(z)); ok1 &= is_symp(cols)
    ok1 &= all(apply(cols, 1 << j) == ((1 << j) ^ (z if omega(1 << j, z) else 0)) for j in range(2 * m))
    da.append(cols)
facts.append(f"dir z ({n-1}): transvection along (z|0): {ok1}")
prod = eye(n)
for j in range(m): prod = prod @ dirm(1 << j)
kc = sym_action(K); img = canon([apply(kc, v) for v in L0])
inter = len(set(img) & set(L0))
def dimint(A, B):
    return len(A) + len(B) - len(canon(list(A) + list(B)))
facts.append(f"kernel = dir e1..dir em: {close(prod, K)}; dim(K L0 cap L0) = {dimint(img, L0)} (opposite iff 0)")
# orbits on Lagrangians
def orbit(start, gens):
    seen = {start: 0}; st = [start]
    while st:
        L = st.pop()
        for cols in gens:
            M2 = canon([apply(cols, v) for v in L])
            if M2 not in seen: seen[M2] = 1; st.append(M2)
    return seen
allL = orbit(L0, fa + da)
expect = 1
for i in range(1, m + 1): expect *= 2 ** i + 1
facts.append(f"orbit of L0 under all letters: {len(allL)} Lagrangians (all: {expect})")
# free-letter orbits on all Lagrangians, compared with distance spheres
rem = set(allL); orbs = []
while rem:
    s = next(iter(rem)); o = orbit(s, fa); rem -= set(o)
    dists = {m - dimint(L, L0) for L in o}
    orbs.append((sorted(dists), len(o)))
facts.append(f"free-letter orbits (distances, size): {sorted(orbs)}")
for f_ in facts: print(f_)
