    Kmat = [[1 if c == (r + 3) % 6 else 0 for c in range(6)] for r in range(6)]
    def img(M, i): return jidx[frozenset(enc(matvec(M, dec(s))) for s in FJ[i])]
    rep(f"direction moves L0 to distance {DJ[L0, img(Dz, L0)]} (want 1); K to distance {DJ[L0, img(Kmat, L0)]} (want 3)",
        DJ[L0, img(Dz, L0)] == 1 and DJ[L0, img(Kmat, L0)] == 3)
    with open("frames891.json", "w") as fh:
        json.dump({"frames_D": [sorted(S) for S in FD], "phi_J_to_D": phimap, "L0_J": L0}, fh)
    np.save("dist891.npy", Dm)
