#!/usr/bin/env python3
"""hb.py (theory-guide): the two-sided HALVING BUDGET for words of the engine game (Clifford letters), exact.

Model (w-bounds section 1; ut-direct section 1): registers hold formal contents sum_l c_l y_l, c_l in C[G], G the group
generated by the engine letters at block m (dir z = ca*1 + cb*X^z, shifts X^z, address maps, phase letters).  A word is
a list of steps
    ("move", r, z)            paid: c_r := [dir z] c_r                       (rank 1)
    ("move2", r, z1, z2)      paid: c_r := [dir z1 dir z2] c_r              (rank 2)
    ("free", r, name)         free letter on register r (name from LETTERS)
    ("mix", r, [(s, mu), ..]) c_r := sum_s mu_s c_s (old values; mu Gaussian rationals; r may be among the s)
Coefficients mu are exact Gaussian rationals (pairs of Fractions).  Group elements are matrices (complex floats with
entries in Z[i][1/2], keyed after rounding; the group is finite, so this is exact in practice).

Halving budget (RULES.md H1).  pi = 1 - i; v = pi-adic valuation (v(a+bi) = v_2(a^2+b^2)); residue field F_2 (a+bi -> a+b
mod 2).  The NORMALISED reduced content of c is: keep the terms of minimal valuation, map each to F_2 (always 1), sum
their symplectic images in End(F_2^{2m}).  Phi = F_2-rank of the x-parts (V2/L0) of the reduced contents on L0^W.
A mix is a DIVISION EVENT when v(result) > min_s (v(mu_s) + v(c_s)) (cancellation in the leading pi-adic digit).
Step bounds: move: dPhi <= rank; free letter or non-division mix: dPhi <= 0; division: dPhi <= gain(result), where
gain(c) = rank of x-part of reduced c on L0^W (<= m).  End: Phi_end >= sum over delivering registers of their own gain
(= m each when they hold K y_l).  Transposition: reversed word, mixes transposed, letters transposed, same moves.
"""
import itertools, random, sys
from fractions import Fraction as Fr
import numpy as np

# ---------------------------------------------------------------- Gaussian rationals
class GQ:
    __slots__ = ("a", "b")
    def __init__(s, a, b=0):
        s.a = Fr(a); s.b = Fr(b)
    def __add__(s, o): return GQ(s.a + o.a, s.b + o.b)
    def __sub__(s, o): return GQ(s.a - o.a, s.b - o.b)
    def __mul__(s, o): return GQ(s.a * o.a - s.b * o.b, s.a * o.b + s.b * o.a)
    def __neg__(s): return GQ(-s.a, -s.b)
    def iszero(s): return s.a == 0 and s.b == 0
    def __repr__(s): return "(%s%+si)" % (s.a, s.b) if s.b else str(s.a)
    def inv(s):
        n = s.a * s.a + s.b * s.b
        return GQ(s.a / n, -s.b / n)
    def cx(s): return complex(float(s.a), float(s.b))
def v2(q):
    q = Fr(q)
    if q == 0: return 10 ** 9
    n, d, k = q.numerator, q.denominator, 0
    while n % 2 == 0: n //= 2; k += 1
    while d % 2 == 0: d //= 2; k -= 1
    return k
def vpi(z):
    """pi-adic valuation of a Gaussian rational (pi = 1 - i): v_2 of the norm."""
    if z.iszero(): return 10 ** 9
    return v2(z.a * z.a + z.b * z.b)
PI = GQ(1, -1)
def pipow(k):
    r = GQ(1)
    if k >= 0:
        for _ in range(k): r = r * PI
    else:
        ip = PI.inv()
        for _ in range(-k): r = r * ip
    return r

# ---------------------------------------------------------------- the engine at block m
class Engine:
    def __init__(s, m, lazy=False):
        s.m = m; s.N = N = 1 << m; s.lazy = lazy
        I = np.eye(N, dtype=complex)
        def X(a):
            M = np.zeros((N, N), dtype=complex)
            for x in range(N): M[x, x ^ a] = 1
            return M
        def Z(b): return np.diag([(-1) ** (bin(b & x).count("1") & 1) for x in range(N)]).astype(complex)
        s.X, s.Z = X, Z
        s.PAULI = {}
        ca, cb = (1 + 1j) / 2, (1 - 1j) / 2
        s.dir = {z: ca * I + cb * X(z) for z in range(1, N)}
        s.K = I
        for j in range(m): s.K = s.K @ s.dir[1 << j]
        # free letters: shifts, address maps (all of GL(m,2)), phase letters i^{(z.x + c) mod 2}
        L = {}
        for z in range(1, N): L["X%d" % z] = X(z)
        gl = []
        for cols in ([] if lazy else itertools.product(range(1, N), repeat=m)):
            img = []
            for x in range(N):
                y = 0
                for k in range(m):
                    if (x >> k) & 1: y ^= cols[k]
                img.append(y)
            if len(set(img)) == N: gl.append(tuple(img))
        s.GL = gl
        for G in gl:
            M = np.zeros((N, N), dtype=complex)
            for x in range(N): M[G[x], x] = 1          # entry at x moves to Gx
            L["G" + "".join("%x" % t for t in G)] = M
        for z in range(N):
            for c in (0, 1):
                L["P%d_%d" % (z, c)] = np.diag([1j ** ((bin(z & x).count("1") + c) & 1) for x in range(N)])
        s.LETTERS = L
        s.keys = {}            # key -> (matrix, symplectic 2m x 2m over F_2 as numpy int)
    def letter(s, name):
        if name not in s.LETTERS and name.startswith("G"):
            img = [int(ch, 16) for ch in name[1:]] if s.N <= 16 else [int(t) for t in name[1:].split(",")]
            M = np.zeros((s.N, s.N), dtype=complex)
            for x in range(s.N): M[img[x], x] = 1
            s.LETTERS[name] = M
        return s.LETTERS[name]
    def key(s, M):
        k = tuple(np.round(M.flatten() * 64).astype(np.complex128).round().tolist())
        # entries are in Z[i][1/2] with small denominators at small m; scaled by 64 then rounded
        k = tuple((int(round(z.real)), int(round(z.imag))) for z in k)
        if k not in s.keys:
            s.keys[k] = (M, s.symp(M))
        return k
    def symp(s, g):
        """F_2-linear map on Pauli labels (a|b) induced by conjugation: g P g^-1 = phase * P'. Columns = images of
        basis labels; label vector = a bits (0..m-1) then b bits (m..2m-1)."""
        m, N = s.m, s.N
        gi = np.linalg.inv(g)
        S = np.zeros((2 * m, 2 * m), dtype=np.int64)
        for j in range(2 * m):
            a, b = (1 << j, 0) if j < m else (0, 1 << (j - m))
            Q = g @ (s.X(a) @ s.Z(b)) @ gi
            hit = None
            # Q = phase * X^a2 Z^b2: row 0 has its non-zero entry at column a2; the entries' signs give b2
            a2 = int(np.argmax(np.abs(Q[0])))
            if abs(abs(Q[0, a2]) - 1) < 1e-6:
                ph = Q[0, a2]
                b2 = 0
                for k in range(m):
                    # entry (x, x^a2) of X^a2 Z^b2 is (-1)^(b2 . (x ^ a2)); compare x = 0 and x = 2^k
                    xk = 1 << k
                    val = Q[xk, xk ^ a2] / ph
                    # (-1)^(b2.(xk^a2)) / (-1)^(b2.a2) = (-1)^(b2.xk)
                    if abs(val + 1) < 1e-6: b2 |= xk
                P = s.X(a2) @ s.Z(b2)
                ph = Q[0, a2] / P[0, a2]
                if np.allclose(Q, ph * P, atol=1e-6): hit = (a2, b2)
            assert hit is not None, "not Clifford"
            a2, b2 = hit
            for k in range(m):
                S[k, j] = (a2 >> k) & 1
                S[m + k, j] = (b2 >> k) & 1
        return S

def rank2(M):
    """rank over F_2 of an integer numpy matrix."""
    A = (np.array(M, dtype=np.int64) % 2).astype(np.uint8)
    A = A.copy(); r = 0; rows, cols = A.shape
    for c in range(cols):
        p = None
        for i in range(r, rows):
            if A[i, c]: p = i; break
        if p is None: continue
        A[[r, p]] = A[[p, r]]
        for i in range(rows):
            if i != r and A[i, c]: A[i] ^= A[r]
        r += 1
        if r == rows: break
    return r

# ---------------------------------------------------------------- contents
class Word:
    def __init__(s, E, W, R):
        s.E, s.W, s.R = E, W, R
    def run(s, steps, start=None, record=False):
        """returns list of per-step records and final contents.  start: dict r -> l (register r holds y_l)."""
        E, W, R, m = s.E, s.W, s.R, s.E.m
        I = np.eye(E.N, dtype=complex); kI = E.key(I)
        C = [dict() for _ in range(R)]
        if start is None: start = {l: l for l in range(W)}
        for r, l in start.items(): C[r] = {(l, kI): GQ(1)}
        recs = []
        phi = s.phi(C)
        for st in steps:
            kind = st[0]
            if kind in ("move", "move2", "free"):
                r = st[1]
                if kind == "move": g = E.dir[st[2]]; rk = 1
                elif kind == "move2": g = E.dir[st[2]] @ E.dir[st[3]]; rk = 2
                else: g = E.letter(st[2]); rk = 0
                new = {}
                for (l, k), co in C[r].items():
                    k2 = E.key(g @ E.keys[k][0])
                    new[(l, k2)] = new.get((l, k2), GQ(0)) + co
                C[r] = {kk: c for kk, c in new.items() if not c.iszero()}
                ph2 = s.phi(C)
                recs.append(dict(kind=kind, r=r, rank=rk, dphi=ph2 - phi, div=False, gain=0))
                phi = ph2
            elif kind == "mix":
                r, terms = st[1], st[2]
                vterms = min((vpi(mu) + s.val(C[t])) for t, mu in terms) if terms else 10 ** 9
                new = {}
                for t, mu in terms:
                    for kk, co in C[t].items():
                        new[kk] = new.get(kk, GQ(0)) + mu * co
                new = {kk: c for kk, c in new.items() if not c.iszero()}
                C[r] = new
                vnew = s.val(new)
                div = bool(new) and vnew > vterms
                gain = s.gain(new) if div else 0
                ph2 = s.phi(C)
                recs.append(dict(kind=kind, r=r, rank=0, dphi=ph2 - phi, div=div, gain=gain, vjump=(vnew - vterms) if div else 0))
                phi = ph2
            else:
                raise ValueError(kind)
        return recs, C, phi
    def val(s, c):
        return min((vpi(co) for co in c.values()), default=10 ** 9)
    def reduced(s, c):
        """normalised reduced content: per input l, the F_2 sum of symplectic images of the minimal-valuation terms."""
        m = s.E.m
        v = s.val(c)
        out = {}
        for (l, k), co in c.items():
            if vpi(co) == v:
                out[l] = (out.get(l, np.zeros((2 * m, 2 * m), dtype=np.int64)) + s.E.keys[k][1]) % 2
        return out
    def xblock(s, c):
        """x-part (rows 0..m-1) of the reduced content on L0 (columns m..2m-1), as an m x (mW) matrix"""
        m, W = s.E.m, s.W
        red = s.reduced(c)
        B = np.zeros((m, m * W), dtype=np.int64)
        for l, S in red.items():
            B[:, l * m:(l + 1) * m] = S[:m, m:]
        return B
    def gain(s, c):
        return rank2(s.xblock(c)) if c else 0
    def phi(s, C):
        m, W = s.E.m, s.W
        rows = [s.xblock(c) if c else np.zeros((m, m * W), dtype=np.int64) for c in C]
        return rank2(np.vstack(rows))

def transpose_word(E, steps):
    """transposition principle: reverse order; moves unchanged (dir z symmetric, rank-2 blocks commute); free letters
    replaced by their transposes; a mix c_r := sum mu_s c_s becomes: c_s += mu_s c_r (s != r), then c_r := mu_r c_r."""
    out = []
    names = {E.key(M): n for n, M in E.LETTERS.items()}
    for st in reversed(steps):
        if st[0] in ("move", "move2"):
            out.append(st)
        elif st[0] == "free":
            Mt = E.LETTERS[st[2]].T
            out.append(("free", st[1], names[E.key(Mt)]))
        else:
            r, terms = st[1], st[2]
            mur = GQ(0)
            for s_, mu in terms:
                if s_ == r: mur = mur + mu
                else: out.append(("mix", s_, [(s_, GQ(1)), (r, mu)]))
            out.append(("mix", r, [(r, mur)]))
    return out

def summary(recs):
    mv = sum(x["rank"] for x in recs)
    gains = [x["gain"] for x in recs if x["div"]]
    return mv, gains

def check_bounds(recs):
    bad = []
    for i, x in enumerate(recs):
        lim = x["rank"] if x["kind"] in ("move", "move2") else (x["gain"] if x["div"] else 0)
        if x["dphi"] > lim: bad.append((i, x))
    return bad
