#!/usr/bin/env python3
"""v_frames.py (skeptic v-e3-engineE): independent rebuild of the frame module from the ACTUAL N x N letter matrices.
No code of e3-engineE is imported.  Steps:
 1. Letters at block m as complex matrices: shifts X^z, address maps A in GL(m,2), phase letters P_{z,c} =
    diag(i^{(z.x+c) mod 2}), paid dir z = ca I + cb X^z, target K = dir e_1 ... dir e_m.
 2. Symplectic image of a letter g: conjugate every Pauli X^a Z^b and read off the label of g X^a Z^b g^-1.
    Label int = a | (b << m) (a = X part, b = Z part) -- e3-engineE's (x, b) convention, to be CONFIRMED here:
    image of dir e_1 must equal the transvection u -> u + om(u,(e1,0)) (e1,0), image of K must be (x,b)->(x+b,b).
 3. Lagrangians by brute force over all m-dim subspaces (not by an orbit); sort them by sorted(L) as e3-engineE does.
 4. P = image of the free group, generated by the images of the actual free letters, enumerated (m <= 3) by BFS.
    Orbits of P on frames; frame permutations of every element of P (m <= 3).
 5. Hecke operators on the P-invariants: E M(t) E and E M(K) E; joint eigenvalues = (omega_j(1), omega_j(m)).
usage: v_frames.py m"""
import sys, itertools
import numpy as np

def build(m):
    N = 1 << m
    ca, cb = (1 + 1j) / 2, (1 - 1j) / 2
    def X(z):
        M = np.zeros((N, N), complex)
        for x in range(N): M[x ^ z, x] = 1        # (X^z y)(x) = y(x ^ z)  (involution, so either convention)
        return M
    def Zp(b):
        return np.diag([(-1) ** bin(b & x).count("1") for x in range(N)]).astype(complex)
    def dirz(z): return ca * np.eye(N) + cb * X(z)
    def phase(z, c): return np.diag([1j ** ((bin(z & x).count("1") + c) % 2) for x in range(N)])
    def addr(A):  # A: list of m column images (ints); (g y)(x) = y(A^-1 x) i.e. g e_x = e_{A x}
        def Ax(x):
            out = 0
            for j in range(m):
                if (x >> j) & 1: out ^= A[j]
            return out
        M = np.zeros((N, N), complex)
        for x in range(N): M[Ax(x), x] = 1
        return M
    return dict(N=N, X=X, Zp=Zp, dirz=dirz, phase=phase, addr=addr)

def pauli(L, m, lab):
    a, b = lab & ((1 << m) - 1), lab >> m
    return L["X"](a) @ L["Zp"](b)

def symp_image(L, m, g):
    """images of the 2m basis labels under conjugation by g; checks g P g^-1 is a scalar multiple of a Pauli."""
    N = L["N"]; gi = np.linalg.inv(g)
    imgs = []
    for j in range(2 * m):
        Q = g @ pauli(L, m, 1 << j) @ gi
        found = None
        for lab in range(1 << (2 * m)):
            Pm = pauli(L, m, lab)
            c = np.trace(Pm.conj().T @ Q) / N
            if abs(abs(c) - 1) < 1e-9:
                assert np.allclose(Q, c * Pm, atol=1e-9); found = lab; break
        assert found is not None, "not Clifford"
        imgs.append(found)
    return tuple(imgs)

def app(Mt, v):
    out = 0
    for j in range(len(Mt)):
        if (v >> j) & 1: out ^= Mt[j]
    return out

def om(u, v, m):
    mx = (1 << m) - 1
    return (bin((u & mx) & (v >> m)).count("1") + bin((u >> m) & (v & mx)).count("1")) & 1

def lagrangians(m):
    """all m-dim totally isotropic subspaces of F_2^{2m}, by brute force over spanning sets in RREF-free form:
    enumerate subspaces as frozensets, generated by choosing m independent vectors greedily (dedup by set)."""
    n = 2 * m
    seen = set()
    vecs = list(range(1, 1 << n))
    # recursive: extend isotropic subspaces one vector at a time
    def rec(S, k):
        if k == m:
            seen.add(S); return
        mn = max(S) if len(S) > 1 else 0
        for v in vecs:
            if v in S: continue
            if any(om(v, s, m) for s in S): continue
            S2 = frozenset(S | {x ^ v for x in S})
            # canonical: only extend with v = the smallest element of S2 \ S  to limit duplicates
            if v != min(S2 - S): continue
            rec(S2, k + 1)
    rec(frozenset({0}), 0)
    return sorted(seen, key=lambda L: sorted(L))

def main(m):
    L = build(m)
    mx = (1 << m) - 1
    e = [1 << j for j in range(m)]
    t = L["dirz"](e[0])
    K = np.eye(L["N"], dtype=complex)
    for j in range(m): K = K @ L["dirz"](e[j])
    It = symp_image(L, m, t); IK = symp_image(L, m, K)
    trans = tuple((1 << j) ^ ((1) if om(1 << j, 1, m) else 0) for j in range(2 * m))
    Kb = tuple(((1 << j) if j < m else ((1 << j) ^ (1 << (j - m)))) for j in range(2 * m))
    print("m=%d: image of dir e1 == transvection T_(e1,0): %s ; image of K == (x,b)->(x+b,b): %s" % (m, It == trans, IK == Kb))
    # free letters: shifts, phases, address maps (elementary + permutations)
    free = []
    for z in range(1, 1 << m): free.append(("X", z, L["X"](z)))
    for z in range(1 << m):
        for c in (0, 1): free.append(("P", (z, c), L["phase"](z, c)))
    for i in range(m):
        for j in range(m):
            if i != j:
                A = [e[k] ^ (e[i] if k == j else 0) for k in range(m)]   # x_i += x_j
                free.append(("A", (i, j), L["addr"](A)))
    imgs = {}
    for name, par, g in free:
        imgs[(name, par)] = symp_image(L, m, g)
    F = lagrangians(m)
    idx = {Lg: i for i, Lg in enumerate(F)}
    L0 = frozenset(v << m for v in range(1 << m))
    print("   Lagrangians by brute force: %d (prod(2^j+1) = %d); L0 = Z-type labels is one: %s"
          % (len(F), int(np.prod([2 ** j + 1 for j in range(1, m + 1)])), L0 in idx))
    # free letters fix L0?
    fixes = all(frozenset(app(Mt, x) for x in L0) == L0 for Mt in imgs.values())
    print("   every free letter's image fixes L0: %s" % fixes)
    def perm(Mt): return np.array([idx[frozenset(app(Mt, x) for x in Lg)] for Lg in F])
    gens = [perm(Mt) for Mt in set(imgs.values())]
    pt, pK = perm(It), perm(IK)
    i0 = idx[L0]
    dist = np.array([m - (len(Lg & L0).bit_length() - 1) for Lg in F])
    print("   t maps L0 to distance %d, K maps L0 to distance %d" % (dist[pt[i0]], dist[pK[i0]]))
    # orbits of P on frames
    n = len(F); orb = -np.ones(n, int); no = 0
    for s in range(n):
        if orb[s] >= 0: continue
        orb[s] = no; st = [s]
        while st:
            a = st.pop()
            for g in gens:
                if orb[g[a]] < 0: orb[g[a]] = no; st.append(g[a])
        no += 1
    same = all(((orb == orb[s]) == (dist == dist[s])).all() for s in range(n))
    print("   P-orbits on frames: %d (m+1 = %d); orbits are the distance classes: %s; sizes %s"
          % (no, m + 1, same, [int((dist == d).sum()) for d in range(m + 1)]))
    # Hecke operators on P-invariants (basis: orbit indicators)
    Ind = np.array([(dist == d).astype(float) for d in range(m + 1)]).T   # n x (m+1)
    Pr = Ind / Ind.sum(0)                                                 # averaging
    def Mperm(p):
        Mm = np.zeros((n, n)); Mm[p, np.arange(n)] = 1; return Mm
    Ht = Pr.T @ Mperm(pt) @ Ind / 1.0   # not used directly
    # operator E M(g) E on invariants, in basis Ind: coefficients c with E M(g) Ind = Ind c
    def hecke(p):
        Mg = Mperm(p) @ Ind
        Eg = Ind @ (Pr.T @ Mg)  # project back: average over orbits
        c = np.linalg.lstsq(Ind, Eg, rcond=None)[0]
        return c
    Ct, CK = hecke(pt), hecke(pK)
    print("   E M(t) E and E M(K) E commute: %s" % np.allclose(Ct @ CK, CK @ Ct))
    w, V = np.linalg.eig(Ct)
    ordr = np.argsort(-w.real); w = w[ordr].real; V = V[:, ordr]
    wK = np.array([(np.linalg.lstsq(V[:, [j]], CK @ V[:, [j]], rcond=None)[0][0, 0]).real for j in range(m + 1)])
    print("   joint eigenvalues (omega_j(1), omega_j(m)):", [(round(a, 6), round(b, 6)) for a, b in zip(w, wK)])
    mu = w - 1; c = wK - 1
    r1, rm = c[1] / mu[1], c[m] / mu[m]
    print("   c_1/mu_1 = %.10f (claimed 2 - 2^(1-m) = %.10f); c_m/mu_m = %.10f (claimed (2/3)(1-(-1/2)^m) = %.10f)"
          % (r1, 2 - 2 ** (1 - m), rm, (2 / 3) * (1 - (-0.5) ** m)))
    prop = np.linalg.matrix_rank(np.vstack([mu[1:], c[1:]]), tol=1e-9)
    print("   rank of [mu; c] over characters j>=1: %d (2 => not proportional, Theorem E2(ii) applies)" % prop)
    return dict(F=F, idx=idx, i0=i0, pt=pt, pK=pK, dist=dist, gens=gens, n=n, imgs=imgs, L=L)

if __name__ == "__main__":
    main(int(sys.argv[1]))
