#!/usr/bin/env python3
"""v_thmA.py (v-e3-slice6): my own check of Theorem A on the U_3 = 2 in 7 order-2 solution.
I build the register program myself from (A, B, Gam) by Lemma 1's converse (rank-one moves I + c u_i v_i^T with
v_i.u_i = 1, v_j.u_i = Gam_ji/2 for i < j), evaluate the ORDERED PRODUCT of explicit (W+M)x(W+M) operator matrices,
and test it at the characters that actually occur for f digit columns: psi_y(z) = sum_c [z . y_c] mod 4, for EVERY
y in (F_2^3)^f, f = 1..4 (this is the diagonal of t_z = diag_x(i^<z,x>) on f columns, i.e. all raw basis inputs).
Target per array: K = t_e1 t_e2 t_e3, value i^(sum_j psi(e_j)). X^a = t_a^2 acts as (-1)^psi(a).
Variants: (L) literal (no shifts), (C) with corrections u_z = ((1-i)+(1+i)X^z)/2 after each move and
v = prod_j ((1+i)+(1-i)X^ej)/2 on outputs.  Also checks the order-2 equations (*) directly.
"""
import numpy as np, itertools
import sys
d = np.load(sys.argv[1] if len(sys.argv) > 1 else '../u3/u3_solution.npz')
A, B, Gam = d['A'], d['B'], d['Gam']; dirs = [int(z) for z in d['dirs']]; W = int(d['W']); m = int(d['m']); M = len(dirs)
print("W", W, "M", M, "dirs", dirs, "; Gam strictly lower:", np.allclose(np.triu(Gam), 0), " strictly upper:", np.allclose(np.tril(Gam), 0))
lower = np.allclose(np.triu(Gam), 0)
G = Gam if lower else Gam.T     # want G[j,i] (j > i) = coefficient for i before j
# --- order-2 equations (*) at all 64 binary forms
mons = [(j, k) for j in range(m) for k in range(j, m)]
def Qval(q, z): return sum(q[t] * ((z >> j) & 1) * ((z >> k) & 1) for t, (j, k) in enumerate(mons)) % 2
err = 0
for q in itertools.product([0, 1], repeat=len(mons)):
    D = [i for i in range(M) if Qval(q, dirs[i])]
    tr = sum(q[t] for t, (j, k) in enumerate(mons) if j == k) % 2
    X = A[:, D] @ np.linalg.solve(np.eye(len(D)) + G[np.ix_(D, D)], B[D, :]) if D else np.zeros((W, W))
    err = max(err, np.abs(X - tr * np.eye(W)).max())
print("order-2 system (*) max error over 64 forms:", err)
# --- build u_i, v_i
U = np.zeros((W + M, M), complex); V = np.zeros((W + M, M), complex)
for i in range(M):
    U[:W, i] = A[:, i]; U[W + i, i] = 1
    V[:W, i] = B[i, :]
for j in range(M):
    for i in range(M):
        if i < j: V[W + i, j] = G[j, i] / 2 - B[j, :] @ A[:, i]
        elif i == j: V[W + i, j] = 1 - B[j, :] @ A[:, j]
P = V.T @ U   # P[j,i] = v_j . u_i
print("check v_i.u_i = 1:", np.abs(np.diag(P) - 1).max(), "; v_j.u_i = G_ji/2 (i<j):", max(abs(P[j, i] - G[j, i] / 2) for j in range(M) for i in range(j)))
def run(psi, corrected):
    """psi: dict z -> value mod 4 for z in 1..7."""
    Op = np.eye(W + M, dtype=complex)
    for i in range(M):
        z = dirs[i]; t = 1j ** psi[z]
        if corrected:
            X = (-1) ** psi[z]; t = t * ((1 - 1j) + (1 + 1j) * X) / 2
        Op = (np.eye(W + M) + (t - 1) * np.outer(U[:, i], V[:, i])) @ Op
    out = Op[:W, :W]
    if corrected:
        for j in range(m):
            X = (-1) ** psi[1 << j]; out = out * ((1 + 1j) + (1 - 1j) * X) / 2
    return out
for f in range(1, 5):
    errL = errC = 0; badL = badC = 0; n = 0; chars = set()
    for ys in itertools.product(range(8), repeat=f):
        psi = {z: sum(bin(z & y).count('1') % 2 for y in ys) % 4 for z in range(1, 8)}
        target = 1j ** (sum(psi[1 << j] for j in range(m)) % 4)
        eL = np.abs(run(psi, False) - target * np.eye(W)).max(); eC = np.abs(run(psi, True) - target * np.eye(W)).max()
        errL = max(errL, eL); errC = max(errC, eC); badL += eL > 1e-8; badC += eC > 1e-8; n += 1
        chars.add(tuple(psi[z] for z in range(1, 8)))
    print("f=%d: %5d inputs y, %3d distinct characters; literal: max err %.3g, wrong at %d; corrected: max err %.3g, wrong at %d"
          % (f, n, len(chars), errL, badL, errC, badC))
# --- the whole character group reached by any number of columns: subgroup of Z_4^7 generated by the psi_y
gens = [tuple(bin(z & y).count('1') % 2 for z in range(1, 8)) for y in range(8)]
S = {tuple([0] * 7)}
while True:
    S2 = S | {tuple((a + b) % 4 for a, b in zip(s, g)) for s in S for g in gens}
    if S2 == S: break
    S = S2
errL = errC = 0; badL = badC = 0
for ch in S:
    psi = {z: ch[z - 1] for z in range(1, 8)}
    target = 1j ** (sum(psi[1 << j] for j in range(m)) % 4)
    eL = np.abs(run(psi, False) - target * np.eye(W)).max(); eC = np.abs(run(psi, True) - target * np.eye(W)).max()
    errL = max(errL, eL); errC = max(errC, eC); badL += eL > 1e-8; badC += eC > 1e-8
print("all %d characters reachable with some f: literal wrong at %d (max err %.3g); corrected wrong at %d (max err %.3g)"
      % (len(S), badL, errL, badC, errC))
