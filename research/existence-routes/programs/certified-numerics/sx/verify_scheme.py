# verify_scheme.py scheme_WinS.json -- second, independent exact check of a stand-in scheme (no sympy, no adapted basis):
# (i) every mixing matrix lies in A = span{g (x) g : g in B} (exact rank over Q(i), realified, python-flint fmpq_mat);
# (ii) the program, evaluated exactly with Fractions in the original 16-dim coordinates, outputs rho(D1 D0) in block t.
import sys, json, itertools
from fractions import Fraction as Fr
from flint import fmpq_mat, fmpq
z = json.load(open(sys.argv[1])); W, s = z['W'], z['s']
G = lambda pair: (Fr(pair[0]), Fr(pair[1]))
def gm(a, b): return (a[0] * b[0] - a[1] * b[1], a[0] * b[1] + a[1] * b[0])
def ga(a, b): return (a[0] + b[0], a[1] + b[1])
Z0 = (Fr(0), Fr(0)); ONE = (Fr(1), Fr(0)); II = (Fr(0), Fr(1))
def mat(M): return [[G(x) for x in row] for row in M]
def mmul(A, B):
    n, k, m = len(A), len(B), len(B[0]); out = [[Z0] * m for _ in range(n)]
    for i in range(n):
        for l in range(k):
            a = A[i][l]
            if a == Z0: continue
            Bl = B[l]; oi = out[i]
            for j in range(m):
                if Bl[j] != Z0: oi[j] = ga(oi[j], gm(a, Bl[j]))
    return out
def madd(A, B): return [[ga(x, y) for x, y in zip(r, q)] for r, q in zip(A, B)]
def zeros(n, m): return [[Z0] * m for _ in range(n)]
def kron(A, B):
    return [[gm(A[i // len(B)][j // len(B[0])], B[i % len(B)][j % len(B[0])]) for j in range(len(A[0]) * len(B[0]))] for i in range(len(A) * len(B))]
# C^4, basis index x; group B generated by X0, X1, CNOTs, S0, S1, i
def perm(f): return [[ONE if f(x) == y else Z0 for x in range(4)] for y in range(4)]
X0 = perm(lambda x: x ^ 1); X1 = perm(lambda x: x ^ 2)
gens = [X0, X1, perm(lambda x: x ^ ((x & 1) << 1)), perm(lambda x: x ^ ((x >> 1) & 1)),
        [[(II if (x & 1) else ONE) if x == y else Z0 for x in range(4)] for y in range(4)],
        [[(II if (x & 2) else ONE) if x == y else Z0 for x in range(4)] for y in range(4)],
        [[II if x == y else Z0 for x in range(4)] for y in range(4)]]
key = lambda M: tuple(tuple(r) for r in M)
I4 = [[ONE if x == y else Z0 for x in range(4)] for y in range(4)]
seen = {key(I4): I4}; fr = [I4]
while fr:
    nf = []
    for g in fr:
        for h in gens:
            M = mmul(h, g); k = key(M)
            if k not in seen: seen[k] = M; nf.append(M)
    fr = nf
print('|B| =', len(seen), flush=True)
Avecs = {}
for g in seen.values():
    v = tuple(x for row in kron(g, g) for x in row); Avecs[v] = 1
Avecs = list(Avecs)
def realify(vecs):
    rows = []
    for v in vecs:
        rows.append([x[0] for x in v] + [x[1] for x in v]); rows.append([-x[1] for x in v] + [x[0] for x in v])
    M = fmpq_mat(len(rows), len(rows[0]))
    for i, r in enumerate(rows):
        for j, x in enumerate(r):
            if x: M[i, j] = fmpq(x.numerator, x.denominator)
    return M
basis = []; r_ = 0
for v in Avecs:                      # greedy basis of A among the rho(b) (exact ranks)
    r2 = realify(basis + [v]).rank()
    if r2 > r_: basis.append(v); r_ = r2
    if len(basis) == 88: break
rA = realify(Avecs).rank()
assert rA == realify(basis).rank()
Avecs = basis
print('dim_C A =', rA // 2, flush=True)
def inA(M):
    v = tuple(x for row in M for x in row)
    return realify(Avecs + [v]).rank() == rA
ca, cb = (Fr(1, 2), Fr(1, 2)), (Fr(1, 2), Fr(-1, 2))
D0 = [[ga(gm(ca, I4[i][j]), gm(cb, X0[i][j])) for j in range(4)] for i in range(4)]
D1 = [[ga(gm(ca, I4[i][j]), gm(cb, X1[i][j])) for j in range(4)] for i in range(4)]
R = kron(D0, D0); Kr = kron(mmul(D1, D0), mmul(D1, D0))
moves = [[mat(M) for M in row] for row in z['moves']]; outs = [[mat(M) for M in row] for row in z['outputs']]
allm = [M for row in moves + outs for M in row]
nonzero = [M for M in allm if any(x != Z0 for r in M for x in r)]
okA = all(inA(M) for M in nonzero)
print('mixing matrices: %d, nonzero %d, all in A: %s' % (len(allm), len(nonzero), okA), flush=True)
srcs = []
for l in range(W):
    E = zeros(16, 16 * W)
    for i in range(16): E[i][l * 16 + i] = ONE
    srcs.append(E)
for j in range(s):
    c = zeros(16, 16 * W)
    for i, M in enumerate(moves[j]): c = madd(c, mmul(M, srcs[i]))
    srcs.append(mmul(R, c))
ok = okA
for t in range(W):
    o = zeros(16, 16 * W)
    for i, M in enumerate(outs[t]): o = madd(o, mmul(M, srcs[i]))
    T = zeros(16, 16 * W)
    for i in range(16):
        for j in range(16): T[i][t * 16 + j] = Kr[i][j]
    bad = sum(1 for i in range(16) for j in range(16 * W) if o[i][j] != T[i][j])
    print('output %d: %d entries differ' % (t, bad), flush=True); ok &= bad == 0
print('INDEPENDENT EXACT CHECK: %s' % ('PASS (%d in %d)' % (W, s) if ok else 'FAIL'), flush=True)
