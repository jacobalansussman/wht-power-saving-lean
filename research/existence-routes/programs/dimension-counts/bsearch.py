# meta-border, 14 Oct 2026.  Border ("approximate") unit search in the engine game, module form, in a chosen
# representation rho of the engine group G (engine letters typed from proofs/ladder/ladder_check.py).
#
# Model (ladder PROOF.md Lemma 0, module form): every paid move is D = dir e1 (all directions are conjugate under
# free address maps); a move's content is any S-combination of the inputs and of earlier move outputs, S = C[F]
# (F = free letters); live output l must equal K e_l.  In rho, an S-coefficient is any element of rho(S), the
# algebra spanned by rho(F).  So, in rho:
#     R_t  = sum_l a[t,l] E_l + sum_{s<t} b[t,s] Q_s,     Q_s = rho(D) R_s,        (a, b in rho(S))
#     Out_l = sum_l' al[l,l'] E_l' + sum_s be[l,s] Q_s,   target  Out_l = rho(K) E_l
# where a content is a W-tuple of d x d matrices (stored d x dW) and E_l has the identity in slot l.
# Correctness for every number of digit columns = correctness in every rep; a search in one rep rho tests a
# NECESSARY condition: no (border) solution in rho  =>  none in G.  Theorem R with a certificate inside rho is
# valid for schemes correct in rho, so a rep that holds the best certificate is "calibrated": the search must
# find nothing below that bound (B1).
# Loss = sum_l ||Out_l - rho(K) E_l||_F^2 / (W d).  Optimiser: L-BFGS on real/imag parts, analytic gradient.
import sys, itertools, time, json
import numpy as np, warnings
warnings.filterwarnings("ignore")
from scipy.optimize import minimize

I4 = np.array([1, 1j, -1, -1j])

def popc(x): return bin(x).count('1')

def perm_mat(n, p):              # (P v)(x) = v(p(x))
    M = np.zeros((n, n), complex)
    for x in range(n): M[x, p[x]] = 1
    return M

def letters(m):
    n = 1 << m
    free = []
    for j in range(m): free.append(perm_mat(n, [x ^ (1 << j) for x in range(n)]))          # shifts
    # GL(m,2) generators: swap of bits 0,j and transvection b1 += b0
    for j in range(1, m):
        free.append(perm_mat(n, [(x & ~((1 << 0) | (1 << j))) | (((x >> j) & 1) << 0) | (((x >> 0) & 1) << j)
                                  for x in range(n)]))
    if m >= 2: free.append(perm_mat(n, [x ^ ((x & 1) << 1) for x in range(n)]))
    if m >= 3:  # a cyclic shift of bits, so that swaps + one transvection generate GL
        free.append(perm_mat(n, [((x << 1) & (n - 1)) | (x >> (m - 1)) for x in range(n)]))
    for z in range(1, n): free.append(np.diag([I4[popc(z & x) % 4] for x in range(n)]))     # phaseMat z 0
    free.append(1j * np.eye(n))                                                               # scalar i
    ca, cb = (1 + 1j) / 2, (1 - 1j) / 2
    def dirm(z): return ca * np.eye(n) + cb * perm_mat(n, [x ^ z for x in range(n)])
    D = dirm(1)
    K = np.eye(n, dtype=complex)
    for j in range(m): K = dirm(1 << j) @ K
    return free, D, K

def ext_power(g, k):
    n = g.shape[0]
    subs = list(itertools.combinations(range(n), k))
    M = np.zeros((len(subs), len(subs)), complex)
    for a, S in enumerate(subs):
        for b, T in enumerate(subs):
            M[a, b] = np.linalg.det(g[np.ix_(S, T)])
    return M

def rep_fn(name):
    # name: 'V', 'VV', 'VVV', 'L2', 'VL2', 'VL3', 'VL4', 'S2' ...
    def f(g):
        if name == 'V': return g
        if name == 'VV': return np.kron(g, g)
        if name == 'VVV': return np.kron(np.kron(g, g), g)
        if name.startswith('VL'): return np.kron(g, ext_power(g, int(name[2:])))
        if name.startswith('L'): return ext_power(g, int(name[1:]))
        raise ValueError(name)
    return f

def algebra_basis(gens, tol=1e-9, maxdim=None, chunk=256, cache=None):
    # orthonormal (Frobenius) basis of the algebra spanned by the group generated by gens (finite group):
    # closure of span{I} under left multiplication by the generators, in chunks (memory ~ chunk * d^2).
    import os
    if cache and os.path.exists(cache): return np.load(cache)
    d = gens[0].shape[0]
    B = (np.eye(d, dtype=complex) / np.sqrt(d)).reshape(1, -1)
    frontier = B.copy()
    while frontier.shape[0]:
        newrows = []
        for g in gens:
            for c0 in range(0, frontier.shape[0], chunk):
                cand = (g @ frontier[c0:c0 + chunk].reshape(-1, d, d)).reshape(-1, d * d)
                for _ in range(2):
                    cand = cand - (cand @ B.conj().T) @ B
                u, sv, vh = np.linalg.svd(cand, full_matrices=False)
                keep = sv > tol * max(1.0, np.sqrt(d))
                if keep.any():
                    nb = vh[keep]
                    nb = nb - (nb @ B.conj().T) @ B
                    qq, _ = np.linalg.qr(nb.T); nb = qq.T
                    B = np.concatenate([B, nb], 0); newrows.append(nb)
        frontier = np.concatenate(newrows, 0) if newrows else np.zeros((0, d * d), complex)
        if maxdim and B.shape[0] >= maxdim: break
    A = B.reshape(-1, d, d)
    if cache: np.save(cache, A)
    return A

class Problem:
    def __init__(self, m, rep, W, T, mats=None):
        if mats is None:
            free, D, K = letters(m)
            f = rep_fn(rep)
            self.F = [f(g) for g in free]; self.D = f(D); self.K = f(K)
        else:
            self.F, self.D, self.K = mats          # explicit representation matrices
        self.d = d = self.D.shape[0]; self.W = W; self.T = T
        self.A = algebra_basis(self.F, cache=(f'algcache_m{m}_{rep}.npy' if mats is None else None))
        self.s = self.A.shape[0]
        # slots: moves t = 0..T-1 have W + t slots (inputs, earlier outputs); outputs l have W + T slots
        self.nslot = sum(W + t for t in range(T)) + W * (W + T)
        self.npar = 2 * self.nslot * self.s
    def E(self, l):
        X = np.zeros((self.d, self.d * self.W), complex); X[:, l * self.d:(l + 1) * self.d] = np.eye(self.d); return X
    def coeffs(self, x):
        c = x[:self.npar // 2] + 1j * x[self.npar // 2:]
        return c.reshape(self.nslot, self.s)
    def mats(self, c):   # slot coefficient -> d x d matrix in rho(S)
        return np.tensordot(c, self.A, axes=(1, 0))
    def loss_grad(self, x):
        W, T, d = self.W, self.T, self.d
        c = self.coeffs(x); Mt = self.mats(c)
        Es = [self.E(l) for l in range(W)]
        gens = list(Es); R = []; Q = []
        k = 0; slots_move = []
        for t in range(T):
            Rt = np.zeros((d, d * W), complex)
            idx = []
            for j, G in enumerate(gens):
                Rt += Mt[k] @ G; idx.append((k, j)); k += 1
            R.append(Rt); slots_move.append(idx)
            Qt = self.D @ Rt; Q.append(Qt); gens.append(Qt)
        res = []; slots_out = []
        for l in range(W):
            Ol = np.zeros((d, d * W), complex); idx = []
            for j, G in enumerate(gens):
                Ol += Mt[k] @ G; idx.append((k, j)); k += 1
            Ol -= self.K @ Es[l]; res.append(Ol); slots_out.append(idx)
        norm = W * d
        L = sum(np.vdot(r, r).real for r in res) / norm
        # reverse mode
        gM = np.zeros_like(Mt)
        gbar = [np.zeros((d, d * W), complex) for _ in gens]
        for l in range(W):
            Rb = res[l]
            for (kk, j) in slots_out[l]:
                gM[kk] += Rb @ gens[j].conj().T
                if j >= W: gbar[j] += Mt[kk].conj().T @ Rb
        for t in range(T - 1, -1, -1):
            Qb = gbar[W + t]
            Rb = self.D.conj().T @ Qb
            for (kk, j) in slots_move[t]:
                gM[kk] += Rb @ gens[j].conj().T
                if j >= W: gbar[j] += Mt[kk].conj().T @ Rb
        # project onto the basis: dL/dc_bar = <A_i, gM> ; real gradient = 2 * that (Re, Im)
        gc = np.tensordot(gM, self.A.conj(), axes=([1, 2], [1, 2])) * (2.0 / norm)
        g = np.concatenate([gc.real.ravel(), gc.imag.ravel()])
        return L, g

def run(m, rep, W, T, restarts=4, iters=3000, seed=0, scale=0.3, checkpoints=(300, 1000, 3000)):
    P = Problem(m, rep, W, T)
    rng = np.random.default_rng(seed)
    out = {'m': m, 'rep': rep, 'W': W, 'T': T, 'd': P.d, 'dimS': P.s, 'npar': P.npar, 'runs': []}
    for r in range(restarts):
        x = rng.normal(size=P.npar) * scale
        traj = []; done = 0
        for cp in checkpoints:
            res = minimize(P.loss_grad, x, jac=True, method='L-BFGS-B',
                           options={'maxiter': cp - done, 'maxfun': 4 * (cp - done), 'gtol': 1e-16, 'ftol': 1e-30})
            x = res.x; done = cp
            traj.append((cp, float(res.fun), float(np.max(np.abs(x)))))
            if res.fun < 1e-24: break
        out['runs'].append(traj)
    return out

if __name__ == '__main__':
    m = int(sys.argv[1]); rep = sys.argv[2]; W = int(sys.argv[3]); T = int(sys.argv[4])
    restarts = int(sys.argv[5]) if len(sys.argv) > 5 else 4
    cps = tuple(int(v) for v in sys.argv[6].split(',')) if len(sys.argv) > 6 else (300, 1000, 3000)
    t0 = time.time()
    o = run(m, rep, W, T, restarts=restarts, checkpoints=cps)
    o['seconds'] = round(time.time() - t0, 1)
    print(json.dumps(o))
