# dpg.py -- the frame graph Gamma_m = dual polar graph DSp(2m,2): Lagrangian subspaces of F_2^(2m),
# adjacent when they meet in dimension m-1, opposite when they meet in 0. Exact (integers, bit vectors).
# Vector (a|b) in F_2^(2m) is the int a | (b << m); form w(u,v) = a.b' + b.a' (mod 2).
import itertools, collections

def form(u, v, m):
    M = (1 << m) - 1
    a, b = u & M, u >> m
    a2, b2 = v & M, v >> m
    return (bin(a & b2).count('1') + bin(b & a2).count('1')) & 1

def span(vecs):
    s = {0}
    for v in vecs:
        s |= {x ^ v for x in s}
    return frozenset(s)

def build(m):
    """returns (verts: list of frozensets, index dict, adjacency lists, dist matrix as list of lists)"""
    L0 = span([1 << (m + i) for i in range(m)])      # raw frame {(0|b)}
    verts = [L0]; idx = {L0: 0}; adj = [[]]
    q = collections.deque([0])
    while q:
        i = q.popleft(); L = verts[i]
        basis = basis_of(L)
        # hyperplanes H of L: kernels of nonzero functionals on L, given by H = {x in L: <c, coords(x)> = 0}
        nb = set()
        for H in hyperplanes(L, basis, m):
            # H-perp / H: vectors v with w(v,h)=0 for all h in H; Lagrangians containing H are H + <v>, v isotropic in H-perp
            Hb = basis_of(H)
            perp = [v for v in range(1 << (2 * m)) if all(form(v, h, m) == 0 for h in Hb)]
            seen = set()
            for v in perp:
                if v in H: continue
                N = frozenset(H | {x ^ v for x in H})
                if N in seen or N == L: continue
                seen.add(N)
                nb.add(N)
        for N in nb:
            if N not in idx:
                idx[N] = len(verts); verts.append(N); adj.append([]); q.append(idx[N])
            adj[i].append(idx[N])
    n = len(verts)
    for i in range(n): adj[i] = sorted(set(adj[i]))
    # distances: d(E,F) = m - dim(E cap F)
    def dim(S): return len(S).bit_length() - 1
    dist = [[m - dim(verts[i] & verts[j]) for j in range(n)] for i in range(n)]
    return verts, idx, adj, dist

def basis_of(S):
    b = []; cur = {0}
    for v in sorted(S):
        if v not in cur:
            b.append(v); cur |= {x ^ v for x in cur}
    return b

def hyperplanes(L, basis, m):
    k = len(basis); out = []
    for c in range(1, 1 << k):
        H = set()
        for coeffs in range(1 << k):
            if bin(coeffs & c).count('1') % 2 == 0:
                x = 0
                for j in range(k):
                    if coeffs >> j & 1: x ^= basis[j]
                H.add(x)
        out.append(frozenset(H))
    return out

def transvection_perms(verts, idx, m):
    """Sp(2m,2) is generated by transvections x -> x + w(x,v) v; return their permutations of the vertices."""
    perms = []
    for v in range(1, 1 << (2 * m)):
        p = []
        for L in verts:
            img = frozenset(x ^ (v if form(x, v, m) else 0) for x in L)
            p.append(idx[img])
        perms.append(tuple(p))
    return perms

