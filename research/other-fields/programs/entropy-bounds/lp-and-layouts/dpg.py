    import sys
    for m in (1, 2, 3):
        verts, idx, adj, dist = build(m)
        n = len(verts); E = sum(len(a) for a in adj) // 2
        opp = sum(1 for i in range(n) for j in range(n) if dist[i][j] == m)
        deg = set(len(a) for a in adj)
        assert all(dist[i][j] == 1 for i in range(n) for j in adj[i])
        print(f"m={m}: vertices {n}, edges {E}, degrees {deg}, ordered opposite pairs {opp}, "
              f"distance distribution {collections.Counter(dist[0])}")
