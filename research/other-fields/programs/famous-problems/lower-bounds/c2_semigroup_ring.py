"""c2: why a unit is a statement in the semigroup ring C[S], not about one matrix (iso-lower, 14 Oct 2026).

A column-uniform word on W arrays, correct for every f, gives identities  sum_p c_p P_p^{(x)f} = delta K^{(x)f}
(P_p = 2^m x 2^m products of letters along the paths of the word).  Distinct matrices P give linearly
independent functions f -> P^{(x)f} [derived: entries of P^{(x)f} are the degree-f monomials in the entries
of P; distinct points are separated by polynomials].  So "correct for every f" means: the formal sum
sum_p c_p [P_p] equals delta [K] in the semigroup ring C[S].  At one fixed f the evaluation map
[P] -> P^{(x)f} is NOT injective on C[S]; at f = 1 it collapses [H] onto ([X] + [Z])/sqrt2, so one move
becomes free.  Rigidity (a property of one matrix, i.e. one f) only sees an evaluation.

Checks:
 (1) evaluation rank of f -> P_i^{(x)f}, f = 1..F, for a list of distinct 2x2 and 4x4 matrices
     (Paulis, phases, H, products, random): full rank = independent.
 (2) the element [H] - ([X] + [Z])/sqrt2 of C[S] evaluates to 0 at f = 1 and to nonzero at f = 2, 3.
"""
import itertools
import numpy as np

rng = np.random.default_rng(1)

def kpow(P, f):
    out = np.array([[1.0 + 0j]])
    for _ in range(f):
        out = np.kron(out, P)
    return out

I2 = np.eye(2); X = np.array([[0, 1], [1, 0]]); Z = np.diag([1, -1]); S = np.diag([1, 1j])
H = np.array([[1, 1], [1, -1]]) / np.sqrt(2)

def features(P, F, probes):
    """Evaluate f -> P^{(x)f} on a few random linear functionals per f (to keep sizes small)."""
    v = []
    for f in range(1, F + 1):
        M = kpow(P, f).ravel()
        for w in probes[f]:
            v.append(w @ M)
    return np.array(v)

def check_independence(mats, F, nprobe=8):
    q = mats[0].shape[0]
    probes = {f: [rng.standard_normal(q ** (2 * f)) + 1j * rng.standard_normal(q ** (2 * f)) for _ in range(nprobe)]
              for f in range(1, F + 1)}
    Phi = np.array([features(P, F, probes) for P in mats]).T
    s = np.linalg.svd(Phi, compute_uv=False)
    return np.linalg.matrix_rank(Phi, tol=1e-8 * s[0]), len(mats), s[-1] / s[0]

# 2x2: the Clifford-ish monoid elements generated by a few letters, all distinct
gens = [I2, X, Z, S, H, X @ Z, S @ H, H @ S, H @ X, Z @ H, H @ S @ H, (X + Z) / np.sqrt(2) @ S]
uniq = []
for P in gens:
    if not any(np.allclose(P, Q) for Q in uniq):
        uniq.append(P.astype(complex))
r, k, cond = check_independence(uniq, F=6)
print(f"(1) 2x2: {k} distinct matrices, evaluation rank over f=1..6 = {r} (independent: {r == k}), "
      f"smallest/largest singular value {cond:.2e}")

# 4x4 (block m = 2): H_j, CZ, swaps, phases, random
H1 = np.kron(H, I2); H2 = np.kron(I2, H); CZ = np.diag([1, 1, 1, -1]).astype(complex)
SW = np.eye(4)[[0, 2, 1, 3]]
mats4 = [np.eye(4), H1, H2, H1 @ H2, CZ, SW, H1 @ CZ @ H2, CZ @ H1, SW @ H1, H1 @ SW]
mats4 += [rng.standard_normal((4, 4)) for _ in range(4)]
r, k, cond = check_independence([M.astype(complex) for M in mats4], F=3, nprobe=12)
print(f"(1) 4x4: {k} distinct matrices, evaluation rank over f=1..3 = {r} (independent: {r == k}), "
      f"smallest/largest singular value {cond:.2e}")

# (2) the collapse at f = 1
for f in (1, 2, 3):
    D = kpow(np.sqrt(2) * H, f) - (kpow(X, f) + kpow(Z, f))
    print(f"(2) f={f}: || (sqrt2 H)^(x)f - (X^(x)f + Z^(x)f) || = {np.linalg.norm(D):.3f}")
