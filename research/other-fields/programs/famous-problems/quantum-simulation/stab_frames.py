"""iso-quantum check 1: the frame / stabiliser-state dictionary at m = 2, 3 (exact enough in floats; seconds).

Claims checked:
 (a) stabiliser states on m qubits: 60 (m=2), 1080 (m=3); their stabiliser groups mod sign give 15 / 135
     Lagrangians ("frames").
 (b) for any two stabiliser states with Lagrangians L, L': |<psi|phi>|^2 is 0 or 2^-(m - dim(L ∩ L')),
     i.e. the frame distance is -log2 of the stabiliser overlap (when nonzero).
 (c) the Hadamard-free ("monomial") Cliffords generated by X, Z, S, CZ, CNOT fix L_0 = <Z_1..Z_m>, and their
     orbits on frames are exactly the distance classes from L_0 (sizes 1,6,8 at m=2; 1,14,56,64 at m=3):
     P-double cosets <-> distance (Bruhat for the Siegel parabolic).
 (d) one Hadamard on one qubit moves any frame by distance <= 1 (a paid move is an edge of the dual polar graph),
     so a single register needs >= m Hadamards to reach H^{(x)m} L_0 (distance m): the W = 1 game is the
     Bruhat / Maslov-Roetteler Hadamard count.
"""
import itertools, sys
import numpy as np

def kron(*ms):
    out = np.array([[1.0+0j]])
    for M in ms:
        out = np.kron(out, M)
    return out

I2 = np.eye(2, dtype=complex)
X = np.array([[0,1],[1,0]], dtype=complex)
Z = np.array([[1,0],[0,-1]], dtype=complex)
Y = 1j*X@Z
S = np.diag([1,1j]).astype(complex)
H = np.array([[1,1],[1,-1]], dtype=complex)/np.sqrt(2)

def one(m, j, g):
    return kron(*[g if k == j else I2 for k in range(m)])

def cnot(m, c, t):
    d = 2**m
    M = np.zeros((d,d), dtype=complex)
    for x in range(d):
        bits = [(x >> (m-1-k)) & 1 for k in range(m)]
        if bits[c]:
            bits[t] ^= 1
        y = sum(b << (m-1-k) for k, b in enumerate(bits))
        M[y, x] = 1
    return M

def cz(m, a, b):
    d = 2**m
    v = np.ones(d, dtype=complex)
    for x in range(d):
        if (x >> (m-1-a)) & 1 and (x >> (m-1-b)) & 1:
            v[x] = -1
    return np.diag(v)

def canon(v):
    # normalise global phase: first entry of largest modulus made real positive
    k = np.argmax(np.abs(v) > 1e-9)
    ph = v[k]/abs(v[k])
    w = v/ph
    return tuple(np.round(w.real, 6)) + tuple(np.round(w.imag, 6))

def paulis(m):
    # (x|z) bit vectors -> matrix X^x Z^z
    out = {}
    for xs in itertools.product([0,1], repeat=m):
        for zs in itertools.product([0,1], repeat=m):
            M = kron(*[(X if a else I2) @ (Z if b else I2) for a, b in zip(xs, zs)])
            out[xs+zs] = M
    return out

def lagrangian(v, P):
    L = []
    for key, M in P.items():
        w = M @ v
        ov = np.vdot(v, w)
        # stabilises up to a phase (for X^x Z^z the phase can be +-1 or +-i)
        if abs(abs(ov) - 1) < 1e-9 and np.linalg.norm(w - ov*v) < 1e-9:
            L.append(key)
    return frozenset(L)

def rank2(vecs):
    rows = [int(''.join(map(str, v)), 2) for v in vecs]
    r = 0
    basis = []
    for x in rows:
        for b in basis:
            x = min(x, x ^ b)
        if x:
            basis.append(x)
            r += 1
    return r

def run(m):
    d = 2**m
    gens = []
    for j in range(m):
        gens += [one(m, j, H), one(m, j, S)]
    for a in range(m):
        for b in range(m):
            if a != b:
                gens.append(cnot(m, a, b))
    v0 = np.zeros(d, dtype=complex); v0[0] = 1
    seen = {canon(v0): v0}
    frontier = [v0]
    while frontier:
        nf = []
        for v in frontier:
            for g in gens:
                w = g @ v
                c = canon(w)
                if c not in seen:
                    seen[c] = w
                    nf.append(w)
        frontier = nf
    states = list(seen.values())
    P = paulis(m)
    lags = [lagrangian(v, P) for v in states]
    frames = sorted(set(lags), key=lambda L: sorted(L))
    print(f"m={m}: stabiliser states {len(states)}, frames {len(frames)}, |L| = {set(len(L) for L in frames)}")
    # (b) overlaps vs frame distance
    bad = 0; tested = 0
    for i in range(len(states)):
        for j in range(i, len(states)):
            Li, Lj = lags[i], lags[j]
            inter = Li & Lj
            dim_int = rank2([k for k in inter if any(k)]) if len(inter) > 1 else 0
            dist = m - dim_int
            ov2 = abs(np.vdot(states[i], states[j]))**2
            ok = (abs(ov2) < 1e-9) or (abs(ov2 - 2.0**(-dist)) < 1e-9)
            tested += 1
            if not ok:
                bad += 1
    print(f"  (b) overlap^2 in {{0, 2^-d}}: {tested - bad}/{tested} pairs pass")
    # frame index and distance function
    fidx = {L: k for k, L in enumerate(frames)}
    def fdist(La, Lb):
        inter = La & Lb
        return m - (rank2([k for k in inter if any(k)]) if len(inter) > 1 else 0)
    L0 = lagrangian(v0, P)
    # (c) Hadamard-free group: X, Z, S, CZ, CNOT. Act on frames via a representative state.
    free = []
    for j in range(m):
        free += [one(m, j, X), one(m, j, Z), one(m, j, S)]
    for a in range(m):
        for b in range(m):
            if a != b:
                free.append(cnot(m, a, b))
                if a < b:
                    free.append(cz(m, a, b))
    rep = {}
    for v, L in zip(states, lags):
        rep.setdefault(L, v)
    def act(g, L):
        return lagrangian(g @ rep[L], P)
    fixes = all(act(g, L0) == L0 for g in free)
    # orbits of the free group on frames
    unvisited = set(frames); orbits = []
    while unvisited:
        L = unvisited.pop(); orb = {L}; fr = [L]
        while fr:
            nf = []
            for A in fr:
                for g in free:
                    B = act(g, A)
                    if B not in orb:
                        orb.add(B); nf.append(B)
            fr = nf
        unvisited -= orb
        orbits.append(orb)
    orb_info = sorted((min(fdist(L0, L) for L in o), max(fdist(L0, L) for L in o), len(o)) for o in orbits)
    print(f"  (c) free group fixes L_0: {fixes}; orbits (min dist, max dist, size): {orb_info}")
    # (d) one Hadamard moves a frame by <= 1
    hs = [one(m, j, H) for j in range(m)]
    maxjump = max(fdist(L, act(h, L)) for L in frames for h in hs)
    Kfr = lagrangian(kron(*[H]*m) @ v0, P)
    print(f"  (d) max frame distance moved by one Hadamard: {maxjump}; d(L_0, H^m L_0) = {fdist(L0, Kfr)}")
    return len(states), len(frames), bad, fixes, orb_info, maxjump

if __name__ == "__main__":
    for m in (2, 3):
        run(m)
