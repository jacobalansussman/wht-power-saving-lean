"""zx2_slot.py -- a2-zx (meta2, 14 Oct 2026).  Predictions P0, P3, P4(b).

(A) P0, over-count: a circuit of FREE letters only (CZ ladder, CNOTs, S, X) has paid count 0 and invariant d = 0,
    but its PyZX graph-like form after full_reduce carries Hadamard edges.
(B) P4(b), under-count: the direct-sum (slot register) encoding of W = 2 arrays.  Qubit 0 = slot s; data qubits
    1..mf.  A paid move on array k is a slot-controlled sqrt-X on f data wires (control value k).  Plain schedule:
    m directions x 2 arrays = 2m paid moves.  PyZX sees: T-count before / after full_reduce, extracted H-count.
    Our cost stays 2m: the folded data gadget has slot weight R = E00 + E11 = I (two odd eigenvalues).
    Also: a redundant pair (the same move twice on array 1) folds to X (free) -- legitimate removal, cost -2.
(C) P3: fixed-f degeneracy.  Block 2, G1 = the engine's column-uniform letters at f = 1 (affine maps of F2^2 and
    Z4 phases incl. CZ), as 4x4 monomial matrices.  K1 = sqrtX (x) sqrtX lies in span(G1) (0 paid moves at f = 1).
    At f = 2: is K1 (x) K1 in span{g (x) g : g in G1}?  At f = 2 and 3 jointly with the SAME coefficients?
"""
import sys, itertools
import numpy as np
import pyzx as zx
from pyzx.circuit import Circuit
from fractions import Fraction


def hedges(g):
    from pyzx.utils import EdgeType
    return sum(1 for e in g.edges() if g.edge_type(e) == EdgeType.HADAMARD)


def part_A():
    print("== (A) free-only circuits: paid 0, but Hadamard edges in graph-like form")
    for n in (3, 4, 6):
        c = Circuit(n)
        for q in range(n - 1): c.add_gate("CZ", q, q + 1)
        for q in range(n - 1): c.add_gate("CNOT", q + 1, q)
        for q in range(n): c.add_gate("ZPhase", q, Fraction(1, 2))
        c.add_gate("NOT", 0)
        g = c.to_graph(); zx.simplify.full_reduce(g)
        print("  n=%d: gates %d, H-edges after full_reduce %d, spiders %d (paid count 0, d = 0)"
              % (n, len(c.gates), hedges(g), g.num_vertices()))


def csqrtx(c, s, t, ctrl_val):
    """slot-controlled sqrt-X on data qubit t: sqrtX = H S H, CS = T_s T_t CNOT T^dag_t CNOT."""
    if ctrl_val == 0: c.add_gate("NOT", s)
    c.add_gate("HAD", t)
    c.add_gate("ZPhase", s, Fraction(1, 4)); c.add_gate("ZPhase", t, Fraction(1, 4))
    c.add_gate("CNOT", s, t); c.add_gate("ZPhase", t, Fraction(7, 4)); c.add_gate("CNOT", s, t)
    c.add_gate("HAD", t)
    if ctrl_val == 0: c.add_gate("NOT", s)


def target_slot(m, f):
    n = 1 + m * f
    c = Circuit(n)
    for q in range(1, n): c.add_gate("XPhase", q, Fraction(1, 2))
    return c


def part_B():
    print("== (B) slot encoding, W = 2: plain schedule = 2m slot-controlled transversal sqrt-X moves")
    for m in (2, 3, 4):
        for f in (1, 2):
            n = 1 + m * f
            c = Circuit(n)
            for k in (0, 1):
                for j in range(m):
                    for col in range(f):
                        csqrtx(c, 0, 1 + col * m + j, k)
            t0 = zx.tcount(c)
            g = c.to_graph(); zx.simplify.full_reduce(g)
            t1 = zx.tcount(g)
            c2 = zx.optimize.basic_optimization(zx.extract_circuit(g.copy()).to_basic_gates())
            h2 = sum(1 for x in c2.gates if x.name == "HAD")
            sx2 = sum(1 for x in c2.gates if x.name == "XPhase" and Fraction(x.phase) % 1 == Fraction(1, 2))
            ok = zx.compare_tensors(c, target_slot(m, f), preserve_scalar=False) if n <= 11 else "skip"
            ok2 = zx.compare_tensors(c, c2, preserve_scalar=False) if n <= 11 else "skip"
            print("  m=%d f=%d: our paid count 2m = %d moves (%d gadgets); PyZX T-count %d -> %d; extracted "
                  "HAD+sqrtX = %d (= m f = %d: 'one array'); equals I_2 (x) K: %s; extraction exact: %s"
                  % (m, f, 2 * m, 2 * m * f, t0, t1, h2 + sx2, m * f, ok, ok2))
    # one paid move alone (array 1, direction 1, f = 1, m = 2): non-Clifford, PyZX cannot remove it
    c = Circuit(3); csqrtx(c, 0, 1, 1)
    g = c.to_graph(); zx.simplify.full_reduce(g)
    print("  single slot-controlled move: T-count %d -> %d after full_reduce" % (zx.tcount(c), zx.tcount(g)))
    # redundant pair: plain + the same move twice more on array 1: folds to X (free); cost 2m + 2 -> 2m legitimately
    m, f = 2, 1; n = 1 + m * f
    c = Circuit(n)
    for k in (0, 1):
        for j in range(m): csqrtx(c, 0, 1 + j, k)
    csqrtx(c, 0, 1, 1); csqrtx(c, 0, 1, 1)
    # expected: I_2 (x) K followed by controlled-X on array 1 (free: slot-controlled Pauli)
    ref = target_slot(m, f); ref.add_gate("CNOT", 0, 1)
    print("  plain + redundant pair on array 1 = (I_2 (x) K) then slot-controlled X (free): %s"
          % zx.compare_tensors(c, ref, preserve_scalar=False))


def group_G1():
    """column-uniform engine letters at block 2, f = 1: generated by X1, X2, S1, S2, CZ, CNOT12, CNOT21."""
    I = np.eye(4, dtype=complex)
    def basis(b): return b  # index = x0 + 2 x1
    def perm(fn):
        M = np.zeros((4, 4), dtype=complex)
        for a in range(4): M[fn(a), a] = 1
        return M
    def diag(fn):
        return np.diag([fn(a) for a in range(4)]).astype(complex)
    X1 = perm(lambda a: a ^ 1); X2 = perm(lambda a: a ^ 2)
    S1 = diag(lambda a: 1j if a & 1 else 1); S2 = diag(lambda a: 1j if a & 2 else 1)
    CZ = diag(lambda a: -1 if a == 3 else 1)
    C12 = perm(lambda a: a ^ 2 if a & 1 else a); C21 = perm(lambda a: a ^ 1 if a & 2 else a)
    gens = [X1, X2, S1, S2, CZ, C12, C21]
    def key(M): return tuple(np.round(M.flatten(), 6))
    seen = {key(I): I}; frontier = [I]
    while frontier:
        nf = []
        for A in frontier:
            for G in gens:
                B = G @ A; k = key(B)
                if k not in seen: seen[k] = B; nf.append(B)
        frontier = nf
    return list(seen.values())


def part_C():
    print("== (C) fixed-f degeneracy (block 2)")
    G = group_G1()
    print("  |G1| = %d (with Z4 scalars)" % len(G))
    a, b = (1 + 1j) / 2, (1 - 1j) / 2
    D = np.array([[a, b], [b, a]])
    K1 = np.kron(D, D)
    A1 = np.array([g.flatten() for g in G]).T
    res1 = np.linalg.lstsq(A1, K1.flatten(), rcond=None)
    r1 = np.linalg.norm(A1 @ res1[0] - K1.flatten()) / np.linalg.norm(K1)
    print("  f = 1: K in span(G1)? rank span = %d / 16, relative residual %.2e  (0 paid moves at f = 1)"
          % (np.linalg.matrix_rank(A1), r1))
    # f = 2: span{g (x) g}
    K2 = np.kron(K1, K1)   # columns ordered (col0, col1); kron of per-column maps
    A2 = np.array([np.kron(g, g).flatten() for g in G]).T
    res2 = np.linalg.lstsq(A2, K2.flatten(), rcond=None)
    r2 = np.linalg.norm(A2 @ res2[0] - K2.flatten()) / np.linalg.norm(K2)
    print("  f = 2: rank span{g(x)g} = %d / 256, relative residual of K(x)K: %.4f" % (np.linalg.matrix_rank(A2), r2))
    # f = 2 and 3 jointly with shared coefficients
    K3 = np.kron(K2, K1)
    A3 = np.array([np.kron(np.kron(g, g), g).flatten() for g in G]).T
    A = np.vstack([A2, A3]); y = np.concatenate([K2.flatten(), K3.flatten()])
    res = np.linalg.lstsq(A, y, rcond=None)
    r = np.linalg.norm(A @ res[0] - y) / np.linalg.norm(y)
    print("  f = 2, 3 jointly: relative residual %.4f" % r)


if __name__ == "__main__":
    part_A(); part_B(); part_C()
