"""engine_group_exact.py -- v-ml-logic (skeptic of meta3/ml-logic), 14 Oct 2026.
Independent re-derivation of ml-logic's Corollary F1 numbers, in EXACT arithmetic (no floating point anywhere).

Matrices over Z[i, 1/2] are stored as (integer Gaussian matrix N, exponent k) meaning N / 2^k, kept reduced.
Gaussian integers are Python complex-free pairs (re, im) packed into one int-tuple; we use Python ints only.

A. Engine group at block m = 1, 2: generated by D_j = a I + b X_j (a = (1+i)/2, b = (1-i)/2), X_j, Z_j, S_j, CZ_jk,
   CNOT_jk, iI (the generators ml-logic used) -- AND, as a cross-check that the menu is complete, also by
   H-free "all Clifford Z4 diagonal phases i^q(x)" and all affine maps (redundant generators must not change |G|).
   Prints |G|, the exact set of traces, r' = number of distinct nonzero traces.
B. m = 1: exact rank over Q(i) of Gram_F = sum_{f<=F} [tr(g^-1 h)^f]_{g,h} for F = 1..10 (fraction-free elimination
   over Q(i), exact), giving the smallest F* with full rank |G|.
Usage: python3 -I engine_group_exact.py      (pure Python; m = 2 BFS ~ 46080 4x4 matrices; < 300 MB, ~1-2 min)
"""
import itertools, sys
from fractions import Fraction as Fr

# ---------- Gaussian integers as (re, im) ----------
def gmul(x, y): return (x[0]*y[0] - x[1]*y[1], x[0]*y[1] + x[1]*y[0])
def gadd(x, y): return (x[0]+y[0], x[1]+y[1])
ZERO = (0, 0)

def matmul(A, B):
    (NA, kA), (NB, kB) = A, B
    n = len(NA)
    C = [[ZERO]*n for _ in range(n)]
    for r in range(n):
        for c in range(n):
            s0 = s1 = 0
            for t in range(n):
                x = NA[r][t]; y = NB[t][c]
                if x == ZERO or y == ZERO: continue
                s0 += x[0]*y[0] - x[1]*y[1]; s1 += x[0]*y[1] + x[1]*y[0]
            C[r][c] = (s0, s1)
    return reduce_((C, kA + kB))

def reduce_(M):
    N, k = M
    while k > 0 and all(e[0] % 2 == 0 and e[1] % 2 == 0 for row in N for e in row):
        N = [[(e[0]//2, e[1]//2) for e in row] for row in N]; k -= 1
    return (N, k)

def key(M):
    N, k = M
    return (k, tuple(e for row in N for e in row))

def trace(M):
    N, k = M
    s0 = sum(N[i][i][0] for i in range(len(N))); s1 = sum(N[i][i][1] for i in range(len(N)))
    return (Fr(s0, 2**k), Fr(s1, 2**k))

def ident(n): return [[(1, 0) if r == c else ZERO for c in range(n)] for r in range(n)]

def gens(m, extra=False):
    n = 1 << m; L = {}
    def perm(p):    # p: x -> p(x)
        N = [[ZERO]*n for _ in range(n)]
        for x in range(n): N[p(x)][x] = (1, 0)
        return (N, 0)
    def diag(ph):   # ph: x -> exponent of i
        N = [[ZERO]*n for _ in range(n)]
        for x in range(n): N[x][x] = [(1, 0), (0, 1), (-1, 0), (0, -1)][ph(x) % 4]
        return (N, 0)
    for j in range(m):
        z = 1 << j
        # D_z = ((1+i) I + (1-i) X^z) / 2
        N = [[ZERO]*n for _ in range(n)]
        for x in range(n): N[x][x] = (1, 1); N[x ^ z][x] = (1, -1)
        L[f"D{j}"] = reduce_((N, 1))
        L[f"X{j}"] = perm(lambda x, z=z: x ^ z)
        L[f"Z{j}"] = diag(lambda x, j=j: 2 * ((x >> j) & 1))
        L[f"S{j}"] = diag(lambda x, j=j: (x >> j) & 1)
    for j, k in itertools.permutations(range(m), 2):
        if j < k: L[f"CZ{j}{k}"] = diag(lambda x, j=j, k=k: 2 * (((x >> j) & 1) * ((x >> k) & 1)))
        L[f"CX{j}{k}"] = perm(lambda x, j=j, k=k: x ^ (((x >> j) & 1) << k))
    L["iI"] = diag(lambda x: 1)
    if extra:   # redundant: every affine map and every Z4 quadratic phase i^(sum a_j x_j + 2 sum b_jk x_j x_k)
        import random
        rng = random.Random(7)
        for t in range(6):
            while True:
                Mx = [[rng.randrange(2) for _ in range(m)] for _ in range(m)]
                img = {sum(((sum(Mx[r][c] * ((x >> c) & 1) for c in range(m)) % 2) << r) for r in range(m)) for x in range(n)}
                if len(img) == n: break
            sh = rng.randrange(n)
            L[f"aff{t}"] = perm(lambda x, Mx=Mx, sh=sh: sh ^ sum(((sum(Mx[r][c] * ((x >> c) & 1) for c in range(m)) % 2) << r) for r in range(m)))
            a = [rng.randrange(4) for _ in range(m)]; b = [[rng.randrange(2) for _ in range(m)] for _ in range(m)]
            L[f"q{t}"] = diag(lambda x, a=a, b=b: sum(a[j] * ((x >> j) & 1) for j in range(m))
                              + 2 * sum(b[j][k] * ((x >> j) & 1) * ((x >> k) & 1) for j in range(m) for k in range(j + 1, m)))
    return L

def bfs(m, extra=False, cap=10**6):
    G = list(gens(m, extra).values()); n = 1 << m
    I = (ident(n), 0)
    elems = [I]; seen = {key(I): 0}; frontier = [I]
    while frontier:
        nxt = []
        for g in frontier:
            for s in G:
                h = matmul(s, g); kk = key(h)
                if kk not in seen:
                    seen[kk] = len(elems); elems.append(h); nxt.append(h)
                    if len(elems) > cap: return None, None
        frontier = nxt
    return elems, seen

def inv_unitary(M):   # inverse of a unitary = conjugate transpose
    N, k = M; n = len(N)
    return (tuple(tuple((N[c][r][0], -N[c][r][1]) for c in range(n)) for r in range(n)), k)

# ---------- exact rank over Q(i) ----------
class Q:   # Gaussian rational
    __slots__ = ("a", "b")
    def __init__(s, a, b=0): s.a = Fr(a); s.b = Fr(b)
    def __add__(s, o): return Q(s.a + o.a, s.b + o.b)
    def __sub__(s, o): return Q(s.a - o.a, s.b - o.b)
    def __mul__(s, o): return Q(s.a*o.a - s.b*o.b, s.a*o.b + s.b*o.a)
    def inv(s):
        d = s.a*s.a + s.b*s.b; return Q(s.a/d, -s.b/d)
    def z(s): return s.a == 0 and s.b == 0

def rank_exact(rows):
    A = [r[:] for r in rows]; R = 0; ncol = len(A[0])
    for c in range(ncol):
        p = None
        for r in range(R, len(A)):
            if not A[r][c].z(): p = r; break
        if p is None: continue
        A[R], A[p] = A[p], A[R]
        iv = A[R][c].inv()
        A[R] = [x * iv for x in A[R]]
        for r in range(len(A)):
            if r != R and not A[r][c].z():
                f = A[r][c]
                A[r] = [x - f * y for x, y in zip(A[r], A[R])]
        R += 1
    return R

