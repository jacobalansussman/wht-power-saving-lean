# sp6.py -- Sp(2m,2) on labels (x|z), form B((x|z),(x'|z')) = x.z' + x'.z; frames (Lagrangians); the elements of the brief.
# Vectors are ints: bits 0..m-1 = x, bits m..2m-1 = z.   Matrices act on columns; a transvection t_w(v) = v + B(v,w) w.
import itertools, json, sys
def B(u, v, m):
    M = (1 << m) - 1
    return (bin((u & M) & (v >> m)).count('1') + bin((v & M) & (u >> m)).count('1')) & 1
def span(vs):
    S = {0}
    for v in vs: S |= {x ^ v for x in S}
    return frozenset(S)
def frames(m):
    out = set()
    for vs in itertools.combinations(range(1, 1 << (2*m)), m):
        S = span(vs)
        if len(S) == 1 << m and all(B(a, b, m) == 0 for a in S for b in S): out.add(S)
    return sorted(out, key=lambda S: sorted(S))
def trans(w, m):           # as a function on vectors
    return lambda v: v ^ (w if B(v, w, m) else 0)
def mat_of(f, m):          # 2m x 2m matrix over F_2 (columns = images of basis vectors)
    cols = [f(1 << i) for i in range(2*m)]
    return [[(cols[j] >> i) & 1 for j in range(2*m)] for i in range(2*m)]
def compose(*fs):          # compose(f, g)(v) = f(g(v))
    def h(v):
        for f in reversed(fs): v = f(v)
        return v
    return h
def e(i, m, part):         # (e_i|0) or (0|e_i), i = 1..m
    return 1 << (i - 1) if part == 'x' else 1 << (m + i - 1)
def ee(i, m): return e(i, m, 'x') | e(i, m, 'z')   # (e_i|e_i)
def perm_on(f, F, IDX):
    return [IDX[frozenset(f(v) for v in S)] for S in F]
def setup(m):
    F = frames(m); IDX = {S: i for i, S in enumerate(F)}
    L0 = IDX[span([e(i, m, 'z') for i in range(1, m+1)])]
    M0 = IDX[span([e(i, m, 'x') for i in range(1, m+1)])]
    h = trans(ee(1, m), m)
    hs = [compose(*[trans(ee(i, m), m) for i in range(1, j+1)]) for j in range(1, m+1)]   # h_j = t_(e1|e1)...t_(ej|ej)
    # generators of Sp(2m,2): transvections by basis vectors and (e_i|e_j)+... ; use all t_w for w in a generating set
    gens_w = [e(i, m, 'x') for i in range(1, m+1)] + [e(i, m, 'z') for i in range(1, m+1)] + [e(i, m, 'x') | e(i+1, m, 'x') for i in range(1, m)] + [e(i, m, 'z') | e(i+1, m, 'z') for i in range(1, m)] + [ee(1, m)]
    gens = [trans(w, m) for w in gens_w]
    # P_0 = Stab(L0): unipotent part (x|z) -> (x | z + Cx), C symmetric: generated by t_(0|e_i) and t_(0|e_i+e_j)
    A_w = [e(i, m, 'z') for i in range(1, m+1)] + [e(i, m, 'z') | e(j, m, 'z') for i in range(1, m+1) for j in range(i+1, m+1)]
    A_gens = [trans(w, m) for w in A_w]
    # Levi GL(m,2): (x|z) -> (a x | a^{-T} z); generators: elementary a = I + E_{ij} (i != j) and a permutation cycle
    def levi(a):            # a: function on x-ints (linear); need a^{-T} on z
        cols = [a(1 << i) for i in range(m)]
        A = [[(cols[j] >> i) & 1 for j in range(m)] for i in range(m)]
        # inverse transpose over F_2
        import copy
        n = m; Mx = [row[:] + [1 if i == j else 0 for j in range(n)] for i, row in enumerate(A)]
        for c in range(n):
            p = next(r for r in range(c, n) if Mx[r][c]); Mx[c], Mx[p] = Mx[p], Mx[c]
            for r in range(n):
                if r != c and Mx[r][c]: Mx[r] = [x ^ y for x, y in zip(Mx[r], Mx[c])]
        Ainv = [row[n:] for row in Mx]
        AinvT = [[Ainv[j][i] for j in range(n)] for i in range(n)]
        def apply(Mt, x):
            return sum(((sum(Mt[i][j] & ((x >> j) & 1) for j in range(n)) & 1) << i) for i in range(n))
        Mm = (1 << m) - 1
        return lambda v: apply(A, v & Mm) | (apply(AinvT, v >> m) << m)
    def el(i, j): return lambda x: x ^ ((1 << (i)) if (x >> j) & 1 else 0)     # x_i += x_j (0-based)
    def cyc(x): return ((x << 1) | (x >> (m - 1))) & ((1 << m) - 1)
    L_gens = [levi(el(0, 1)), levi(cyc)]
    return dict(F=F, IDX=IDX, L0=L0, M0=M0, h=h, hs=hs, gens=gens, gens_w=gens_w, A_gens=A_gens, A_w=A_w, L_gens=L_gens, levi=levi)

if __name__ == "__main__":
    m = int(sys.argv[1]) if len(sys.argv) > 1 else 3
    S = setup(m); F, IDX = S['F'], S['IDX']
    print("m", m, "frames", len(F), "L0", S['L0'], "M0", S['M0'])
    def dist(i, j): return m - (len(F[i] & F[j]).bit_length() - 1)
    for j, g in enumerate(S['hs'], 1):
        p = perm_on(g, F, IDX)
        print(f"h_{j}: matrix", mat_of(g, m), " image of L0 at distance", dist(p[S['L0']], S['L0']), " fixed frames", sum(1 for i in range(len(F)) if p[i] == i),
              " rank(g-1)", sum(1 for _ in [0]) and None)
    for g in S['A_gens'] + S['L_gens']:
        p = perm_on(g, F, IDX); assert p[S['L0']] == S['L0']
    pk = perm_on(S['hs'][-1], F, IDX); print("k maps L0 to M0:", pk[S['L0']] == S['M0'])
    out = dict(m=m, nframes=len(F), L0=S['L0'], M0=S['M0'],
               gens=[perm_on(g, F, IDX) for g in S['gens']],
               A_gens=[perm_on(g, F, IDX) for g in S['A_gens']], L_gens=[perm_on(g, F, IDX) for g in S['L_gens']],
               hs=[perm_on(g, F, IDX) for g in S['hs']])
    json.dump(out, open(f"sp{2*m}_frames.json", "w"))
    # GAP file: permutations on frames (1-based)
    def gp(p): return "PermList([" + ",".join(str(x + 1) for x in p) + "])"
    with open(f"gap/sp{2*m}_perms.g", "w") as fh:
        fh.write("gens := [" + ",\n".join(gp(p) for p in out['gens']) + "];\n")
        fh.write("Agens := [" + ",\n".join(gp(p) for p in out['A_gens']) + "];\n")
        fh.write("Lgens := [" + ",\n".join(gp(p) for p in out['L_gens']) + "];\n")
        fh.write("hs := [" + ",\n".join(gp(p) for p in out['hs']) + "];\n")
        fh.write(f"L0 := {out['L0']+1};; M0 := {out['M0']+1};;\n")
