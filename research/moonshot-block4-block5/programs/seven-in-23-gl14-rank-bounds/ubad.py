"""ubad.py -- e3-bpexact: an UPPER bound on the top-alone kernel-block rank that holds for EVERY kappa in C[B'_m] and every
top content (rows free).  Derivation (NOTE s.4.4): the image algebra of C[B'_m] in R_sigma is semisimple; the top's rows are
w' = w R(e_a), and {w' R(kappa)} can only have components in the isotypic parts tau where p has an a-eigenvector.  So the
target T = [Z on d0 | 0 on the constrained slots | F on the free slots] must vanish on U_bad, the orthogonal complement of
U_good = the B'_m-submodule generated by the a-eigenvectors of R(p) (R unitary).  Hence
      r_a <= r_a^up = 14 - rank( E_d0 U_bad  modulo the rows E_s U_bad, s free ).
This uses only the multiplicity-zero part of the exact rank criterion rank(T_tau) <= n_(tau,a), so it is a necessary
condition.  sigma = trivial: it is the frame-level structural obstruction (calibration).  argv: seed psi sigmas"""
import sys, os, time, random
import numpy as np
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from d4gen import *
t0 = time.time()
seed, psi, names = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3].split(',')
L = Lift(seed=seed, psi=psi)
rng = random.Random(seed + 5)
base = [b for (b, s) in L.Bm]; Bm = list(base); seen = set(key(b) for b in Bm)
while len(Bm) < 400:
    w = mm(rng.choice(base), rng.choice(Bm))
    if key(w) not in seen: seen.add(key(w)); Bm.append(w)
mi = minv(L.m); ks = [mm(L.m, b, mi) for b in Bm]
D = D4(L); P = L.P
Rt = [D.R(k, sig_triv, 1).real for k in ks]
fixed = [d for d in range(30) if all(R[d, d] == 1 for R in Rt)]
Fr = sorted(set([d for d in range(30) if P.D[D.slot[d], L.lam1] == 1]) | set(fixed))
modes = {'all30': (Fr, [d for d in range(30) if d != D.d0 and d not in Fr]),
         'd4': ([d for d in range(30) if d not in D.S], list(D.Sx))}
gens = ks[:80] + L.p[1:2]
def orth(M, tol=1e-9):
    U, s, Vh = np.linalg.svd(M, full_matrices=False)
    return U[:, :int((s > tol * max(1, s[0])).sum())]
for name in names:
    sig, ds = (sig_triv, 1) if name == 'trivial' else ((sig_nat, 16) if name == 'V' else make_sig(name))
    n = 30 * ds
    Rg = [D.R(k, sig, ds) for k in gens]
    assert all(np.allclose(R @ R.conj().T, np.eye(n), atol=1e-9) for R in Rg[:5]), 'R not unitary'
    Rp = [D.R(p, sig, ds) for p in L.p]
    line = []
    for a in range(7):
        Ea = sum(L.chars[a][j] * Rp[j] for j in range(7)) / 7
        S = orth(Ea)
        while True:
            S2 = orth(np.hstack([S] + [R @ S for R in Rg]))
            if S2.shape[1] == S.shape[1]: break
            S = S2
        Pg = S @ S.conj().T
        Ub = orth(np.eye(n) - Pg)
        out = {}
        for mode, (free, cons) in modes.items():
            if Ub.shape[1] == 0:
                out[mode] = ds; continue
            G0 = Ub.conj().T[:, D.d0 * ds:(D.d0 + 1) * ds].T      # rows: E_d0 U_bad  (ds x nbad)
            Fm = np.vstack([Ub.conj().T[:, s * ds:(s + 1) * ds].T for s in free]) if free else np.zeros((0, Ub.shape[1]))
            if Fm.shape[0]:
                Qf = orth(Fm.conj().T)                              # basis of the row space of Fm (as columns)
                G0p = G0 - (G0 @ Qf) @ Qf.conj().T
            else:
                G0p = G0
            sv = np.linalg.svd(G0p, compute_uv=False)
            out[mode] = ds - int((sv > 1e-8).sum())
        line.append((a, S.shape[1], out['all30'], out['d4']))
    print(f'[ubad] {name} (dim {ds}): per a (dim U_good, r^up all30, r^up d4): ' +
          ', '.join(f'a={a}: {g}/{u1}/{u2}' for a, g, u1, u2 in line), f'  {time.time() - t0:.0f}s', flush=True)
print('done %.0fs' % (time.time() - t0))
