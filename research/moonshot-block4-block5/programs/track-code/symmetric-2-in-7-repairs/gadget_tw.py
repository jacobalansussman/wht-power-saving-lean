"""gadget_tw.py -- mw2-absorb4 (resumed run): mw-sym4's symmetric TWO-LAYER GADGET (STATUS E3) with a TWISTED
(absorbed) shared first move.

E3 (mw-sym4): v = delta * sum_k chi^k tau^k(b0 x0) (tau-fixed shared move on the inputs), then one free orbit
u^(j) = tau^j(D1 a v).  When every cross term coincides with an 'own' term up to a free letter, u^(j) = sum_l M_jl own_l
x_l with M_jl in C[F]; if M is invertible over C[B], the orbit holds every array's input advanced two steps at cost
1 + W, and plain completion gives (m-1)W + 1 (block 4: 3W + 1, e.g. 2 in 7).  E3: never invertible, because under Z2 the
Schur complement is 1 - beta beta', which is 0 in the trivial representation (chi^2 = 1).
TWIST: v = delta * sum_k mu^-k g_k tau^k(b0 x0) with g_0 = 1, g_(k+1) = beta^-1 c g_k c^-1 and g_W = lambda (scalar),
mu^W = lambda (twist.py).  If lambda = -1 (W = 2), mu = +-i and the trivial-representation determinant becomes
1 - mu^-2 = 2 instead of 0: the v-ms-fano shape (x0 + x1, x0 - sigma x1) becomes possible.  This script enumerates
(delta, beta, b0, a) with beta from Paulis, address maps of GL(m,2) and their products with Pauli-Z, keeps the
coincidences, and tests M for invertibility in the trivial representation, at f = 1 and f = 2, and exactly in the
regular representation of the group generated by M's letters (when small).
Usage: gadget_tw.py m W H nb0 na [regcap] [maxtwists] [dirs]"""
import sys, time, itertools
from odd_twist import *
from gadget_inv import group_closure_mats

def twist_list(G, R, m):
    n = 1 << m
    c = R.Hc[1][0]; ci = np.conj(c).T
    S = Sym(m)
    cands = []
    for a in range(n):
        for b in range(n):
            cands.append(G.mono([x ^ a for x in range(n)], [2 * (bin(x & b).count('1') & 1) for x in range(n)]))
    for P in gl_all(m):
        sig = [gl_apply(P, x, m) for x in range(n)]
        A = G.mono(sig, [0] * n)
        cands.append(A)
        for b in range(1, n, 3):
            cands.append(G.mul(G.mono(list(range(n)), [2 * (bin(x & b).count('1') & 1) for x in range(n)]), A))
    out = []
    W = len(R.Hc)
    for bt in cands:
        if is_scalar(bt):
            continue
        bi = np.conj(bt).T
        gs = [np.eye(n, dtype=complex)]
        for j in range(W):
            gs.append(G.mul(bi, c, gs[-1], ci))
        if not is_scalar(gs[-1]):
            continue
        lam = gs[-1][0, 0]
        out.append((bt, lam, gs[:W]))
    return out

def main():
    m, W, Hn = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
    nb0, na = int(sys.argv[4]), int(sys.argv[5]); regcap = int(sys.argv[6]) if len(sys.argv) > 6 else 1500
    R = Run(m, W, Hn, 1); G = R.G; rng = random.Random(5)
    Hc = R.Hc
    hpow = {h[1][0]: h for h in Hc}
    t0 = time.time()
    tws = twist_list(G, R, m)
    lams = {}
    for (bt, lam, gs) in tws:
        k = complex(np.round(lam, 6)); lams[k] = lams.get(k, 0) + 1
    print(f"twists with scalar norm: {len(tws)}; norm values {lams} ({time.time()-t0:.0f}s)", flush=True)
    fd = fixed_dirs(R, rng)
    print("fixed directions", len(fd), flush=True)
    stats = {}; n_inv = 0; n_coinc = 0
    only = [int(x) for x in sys.argv[8].split(',')] if len(sys.argv) > 8 else None
    for di, d in enumerate(fd):
        if only is not None and di not in only:
            continue
        di_ = np.conj(d).T
        adm = [(bt, lam, gs) for (bt, lam, gs) in tws if G.is_monomial(G.mul(d, bt, di_))]
        rng.shuffle(adm)
        adm.sort(key=lambda t: abs(t[1] - 1) < 1e-9)       # non-trivial norms (lambda != 1, e.g. -1) first
        adm = adm[:int(sys.argv[7]) if len(sys.argv) > 7 else 200]
        adm.append((np.eye(G.n, dtype=complex), 1.0, [np.eye(G.n, dtype=complex)] * W))      # untwisted (E3) control
        b0s = G.progress_letters(G.ID, rng, want=nb0, Dmat=d, steps=1)
        for (bt, lam, gs) in adm:
            mu = complex(lam) ** (1.0 / W)
            for rr in range(W):                      # the W choices of the root mu (characters)
                muk = mu * np.exp(2j * np.pi * rr / W)
                for b0 in b0s:
                    comps = []
                    for k, h in enumerate(Hc):
                        base = {(0, G.intern(b0)): 1}
                        img = R.tau(h, base) if k else base
                        (l, gb), _ = next(iter(img.items()))
                        comps.append((muk ** (-k), l, G.intern(G.mul(d, gs[k], G.MATS[gb]))))
                    g0 = [g for (s, l, g) in comps if l == 0][0]
                    if G.dist(g0) != m - 1:
                        continue
                    for a in G.progress_letters(g0, rng, want=na, Dmat=G.D1, steps=1):
                        u0 = [(s, l, G.intern(G.mul(G.D1, a, G.MATS[g]))) for (s, l, g) in comps]
                        own0 = [g for (s, l, g) in u0 if l == 0][0]
                        if G.dist(own0) != m - 2:
                            continue
                        own = {0: own0}
                        for l in range(1, W):
                            own[l] = R.tau_term_cached(hpow[l], 0, own0)[1]
                        M = [[None] * W for _ in range(W)]
                        ok = True
                        for j in range(W):
                            hj = hpow[j]
                            for (s, l, g) in u0:
                                lj, gj = R.tau_term_cached(hj, l, g) if j else (l, g)
                                b = G.mul(G.MATS[gj], np.conj(G.MATS[own[lj]]).T)
                                if not G.is_monomial(b) or M[j][lj] is not None:
                                    ok = False; break
                                M[j][lj] = (s, b)
                            if not ok:
                                break
                        if not ok or any(M[j][l] is None for j in range(W) for l in range(W)):
                            continue
                        n_coinc += 1
                        triv = np.array([[M[j][l][0] for l in range(W)] for j in range(W)])
                        inv_t = abs(np.linalg.det(triv)) > 1e-9
                        Mat1 = np.block([[M[j][l][0] * M[j][l][1] for l in range(W)] for j in range(W)])
                        inv1 = np.linalg.matrix_rank(Mat1, tol=1e-8) == Mat1.shape[0]
                        Mat2 = np.block([[M[j][l][0] * np.kron(M[j][l][1], M[j][l][1]) for l in range(W)] for j in range(W)])
                        inv2 = np.linalg.matrix_rank(Mat2, tol=1e-8) == Mat2.shape[0]
                        inv_reg = None
                        if inv_t and inv1 and inv2:
                            Bp = group_closure_mats(G, [M[j][l][1] for j in range(W) for l in range(W)], regcap)
                            if Bp is not None:
                                keys = list(Bp.keys()); idx = {k: i for i, k in enumerate(keys)}; N = len(keys)
                                def regmat(b):
                                    P = np.zeros((N, N), dtype=complex)
                                    for i, k in enumerate(keys):
                                        P[idx[G.key(G.mul(b, Bp[k]))], i] = 1
                                    return P
                                Mat = np.block([[M[j][l][0] * regmat(M[j][l][1]) for l in range(W)] for j in range(W)])
                                inv_reg = np.linalg.matrix_rank(Mat, tol=1e-8) == Mat.shape[0]
                        key = ('untwisted' if is_scalar(bt) else f"lam={complex(np.round(lam, 3))}", inv_t, inv1, inv2, inv_reg)
                        if W == 2 and abs(lam + 1) < 1e-9 and stats.get(key, 0) < 3:
                            P = G.mul(M[0][1][1], M[1][0][1]); s2 = M[0][1][0] * M[1][0][0]
                            ev = np.round(np.linalg.eigvals(s2 * P), 3)
                            print(f"  diag lam=-1: scalar product s01*s10 = {np.round(s2, 3)}; order(B01 B10) {order_of(G, P)}; "
                                  f"eigenvalues of s01 s10 B01 B10 at f=1: {sorted(set(map(complex, ev)), key=lambda z: (z.real, z.imag))}; "
                                  f"order(beta) {order_of(G, bt)}", flush=True)
                        stats[key] = stats.get(key, 0) + 1
                        if inv_t and inv1 and inv2 and inv_reg:
                            n_inv += 1
                            np.save(f"GADGETTW_{m}_{W}_{Hn}_{n_inv}.npy", np.array([d, bt, b0, a]))
                            print(f"*** INVERTIBLE twisted gadget #{n_inv}: lambda {lam}, mu {muk}, order(beta) {order_of(G, bt)}, |B'| {N}", flush=True)
        print(f"dir {di}: coincidences so far {n_coinc}; stats {stats} ({time.time()-t0:.0f}s)", flush=True)
    print(f"m={m} W={W} H={Hn}: coincidences {n_coinc}; fully invertible {n_inv}; stats {stats}", flush=True)

if __name__ == "__main__":
    main()
