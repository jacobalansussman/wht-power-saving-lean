"""symlib.py -- mw-sym4: the symmetry group of the unit problem and H-equivariant programs (engine game, formal sums).

THEORY (derived here; see NOTE at the end of STATUS.txt):
  A unit is a program in the register form of GAME.md section 5: generators u_t = D_t c_t, c_t in sum_s C[B] u_s,
  end K x_l in sum_s C[B] u_s for every live l.  For c in B and a permutation pi of the arrays define the C-linear map
      tau_c([g] x_l) = [c g c'] x_{pi l},   c' = K^-1 c^-1 K.
  tau_c(a u) = (c a c^-1) tau_c(u) for a in C[B], tau_c(D u) = (c D c^-1) tau_c(u), tau_c(K x_l) = K x_{pi l}.
  The inputs go to free images of inputs iff c' is free, i.e. c in H_max = B cap K B K^-1 (stabiliser of the opposite
  pair L0, K L0; its symplectic part is the Levi GL(m,2): P -> [[P,0],[P+P^-T,P^-T]]).  So H_max x S_W acts on the set
  of units of every cost profile, fixing the targets exactly.  An H-invariant unit = a union of tau-orbits of moves.
  (Pure array permutations, c = 1, split any invariant program into isotypic pieces that each compute K alone: no
  saving; so the symmetry must act through H_max.)"""
import sys, os, os, itertools, random, time, json
