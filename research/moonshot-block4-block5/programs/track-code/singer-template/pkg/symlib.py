def bits(x, m):
    return [(x >> j) & 1 for j in range(m)]

def dot(a, b):
    return bin(a & b).count('1') & 1

def gl_apply(P, x, m):
    """P as list of column images P[j] = P e_j (ints)"""
    y = 0
    for j in range(m):
        if (x >> j) & 1:
            y ^= P[j]
    return y

def gl_mul(P, Q, m):
    return [gl_apply(P, Q[j], m) for j in range(m)]

def gl_inv(P, m):
    n = 1 << m
    inv = [0] * m
    img = {gl_apply(P, x, m): x for x in range(n)}
    return [img[1 << j] for j in range(m)]

class Sym:
    def __init__(self, m):
        self.m = m; self.n = 1 << m
        self.G = G = Game(m)
        self.K = G.K; self.Ki = np.conj(G.K).T
        self._hcache = {}

    # ------------------------------------------------------------ H_max elements
    def addr(self, P):
        n, m = self.n, self.m
        sig = [gl_apply(P, x, m) for x in range(n)]
        return self.G.mono(sig, [0] * n)

    def phase(self, a, C):
        n, m = self.n, self.m
        q = []
        for x in range(n):
            b = bits(x, m)
            v = sum(a[j] * b[j] for j in range(m)) + 2 * sum(C[j][k] * b[j] * b[k] for j in range(m) for k in range(j + 1, m))
            q.append(v % 4)
        return self.G.mono(list(range(n)), q)

    def hmax_elem(self, P):
        """c = phase * addr(P) with K^-1 c^-1 K monomial; returns (c, c') or None.  Phase solved from the symplectic
        condition Sigma = I + (P P^T)^-1 (diagonal -> odd a_j, off-diagonal -> C), then the 2^m Pauli-Z corrections."""
        key = tuple(P)
        if key in self._hcache:
            return self._hcache[key]
        G, m, n = self.G, self.m, self.n
        A = self.addr(P)
        res = None
        # brute force over a in Z4^m and C (small m); cheap enough at m <= 4 for a few generators
        Cs = list(itertools.product([0, 1], repeat=m * (m - 1) // 2))
        pairs = [(j, k) for j in range(m) for k in range(j + 1, m)]
        for cbits in Cs:
            C = [[0] * m for _ in range(m)]
            for (j, k), v in zip(pairs, cbits):
                C[j][k] = v
            for a in itertools.product(range(4), repeat=m):
                c = G.mul(self.phase(a, C), A)
                cp = G.mul(self.Ki, np.conj(c).T, self.K)
                if G.is_monomial(cp):
                    res = (c, cp); break
            if res:
                break
        self._hcache[key] = res
        return res

    def group_closure(self, gens, cap=2000):
        """enumerate the group generated by pairs (c, pi) (pi a tuple permutation of arrays); c's as exact matrices.
        Elements are compared exactly (c and i c are different: tau differs by nothing on terms? no: tau_{ic} = tau_c
        since c' scales by -i; we keep them distinct but dedupe tau-equal ones by the key of c mod scalars)."""
        G = self.G
        def nkey(c, pi):
            # normalise global phase: first nonzero entry -> 1
            nz = np.argwhere(np.abs(c) > 1e-9)[0]
            v = c[nz[0], nz[1]]
            return (G.key(G.snap(c / v)), tuple(pi))
        W = len(gens[0][1])
        e = (np.eye(self.n, dtype=complex), tuple(range(W)))
        els = {nkey(*e): e}
        frontier = [e]
        while frontier:
            nf = []
            for (c, pi) in frontier:
                for (g, sg) in gens:
                    c2 = G.mul(g, c)
                    pi2 = tuple(sg[pi[l]] for l in range(W))
                    k = nkey(c2, pi2)
                    if k not in els:
                        els[k] = (c2, pi2); nf.append((c2, pi2))
                        if len(els) > cap:
                            raise RuntimeError("group too big")
            frontier = nf
        return list(els.values())

    # ------------------------------------------------------------ tau
    def tau(self, c, pi, gen):
        G = self.G
        cp = G.mul(self.Ki, np.conj(c).T, self.K)
        out = {}
        for (l, gid), co in gen.items():
            t = (pi[l], G.intern(G.mul(c, G.MATS[gid], cp)))
            out[t] = out.get(t, 0) + co
        return {t: v for t, v in out.items() if v != 0}

    def tau_term(self, c, pi, l, gid):
        G = self.G
        cp = G.mul(self.Ki, np.conj(c).T, self.K)
        return pi[l], G.intern(G.mul(c, G.MATS[gid], cp))

    # ------------------------------------------------------------ generator equivalence up to a free left factor
    def same_up_to_free(self, u, v):
        if len(u) != len(v):
            return False
        G = self.G
        (l0, g0), c0 = next(iter(u.items()))
        for (l1, g1), c1 in v.items():
            if l1 != l0:
                continue
            b = G.mul(G.MATS[g1], np.conj(G.MATS[g0]).T)
            if not G.is_monomial(b):
                continue
            ratio = c1 / c0
            bu = G.lmul(b, u)
            if all((t in v) and abs(v[t] - ratio * cc) <= 1e-9 * (abs(v[t]) + 1e-12) for t, cc in bu.items()):
                return True
        return False

    def frames_of(self, u):
        G = self.G
        return sorted(set(G.frm(g) for (l, g) in u))

def plain_program(S, W, orders=None):
    """plain schedule: array l gets D(z1) ... D(zm) with the direction order orders[l] (list of bit vectors)"""
    G = S.G; m = S.m
    gens = [G.inp(l) for l in range(W)]
    for l in range(W):
        cur = gens[l]
        for z in (orders[l] if orders else [1 << j for j in range(m)]):
            cur = G.lmul(G.D[z], cur)
            gens.append(cur)
    return gens

def final_all(S, gens, W, cap=1500):
    res = []
    for l in range(W):
        st, sol = S.G.span_test(gens, l, cap)
        res.append(st)
    return res
