"""gadget_inv.py -- for each coincidence of gadget.py, build the W x W matrix M over C[B] (u^(j) = sum_l M_jl own_l x_l,
M_jl in C[B] acting on the left), for each character chi, and decide invertibility:
 (1) in the defining representation (f = 1) and its 2-fold tensor power (f = 2);
 (2) EXACTLY in the regular representation of the finite group B' generated by the entries (if |B'| <= cap).
If M is invertible, the C[B]-span of the layer-1 orbit holds own_0 x_0 alone: array 0's input advanced by two steps
on a geodesic, for every array, at the cost 1 + W; then plain completion gives (m-1)W + 1 moves."""
import sys, time, itertools
from symsolve import *

def group_closure_mats(G, gens, cap=20000):
    I = np.eye(G.n, dtype=complex)
    els = {G.key(I): I}
    frontier = [I]
    while frontier:
        nf = []
        for x in frontier:
            for g in gens:
                y = G.mul(g, x)
                k = G.key(y)
                if k not in els:
                    els[k] = y; nf.append(y)
                    if len(els) > cap:
                        return None
        frontier = nf
    return els

def main():
    m, W, Hn = int(sys.argv[1]), int(sys.argv[2]), sys.argv[3]
    samples = int(sys.argv[4]) if len(sys.argv) > 4 else 4000
    cap = int(sys.argv[5]) if len(sys.argv) > 5 else 6000
    R = Run(m, W, Hn, 1); G = R.G; rng = random.Random(5)
    Hc = R.Hc
    hpow = {}
    for h in Hc:
        hpow[h[1][0]] = h                                   # element sending array 0 to array h[1][0]
    fd = fixed_dirs(R, rng, samples)
    n_coinc = 0; n_inv = 0
    for d in fd:
        for b0 in G.progress_letters(G.ID, rng, want=24, Dmat=d, steps=1):
            base = {(0, G.intern(b0)): 1}
            comps = []                                      # (k, l, gid) : tau^k(b0 x0) after delta
            for k, h in enumerate(Hc):
                img = R.tau(h, base) if k else base
                (l, gb), _ = next(iter(img.items()))
                comps.append((k, l, G.intern(G.mul(d, G.MATS[gb]))))
            g0 = [g for (k, l, g) in comps if l == 0][0]
            for a in G.progress_letters(g0, rng, want=24, Dmat=G.D1, steps=1):
                u0 = [(k, l, G.intern(G.mul(G.D1, a, G.MATS[g]))) for (k, l, g) in comps]
                own0 = [g for (k, l, g) in u0 if l == 0][0]
                if G.dist(own0) != m - 2:
                    continue
                own = {0: own0}
                for l in range(1, W):
                    own[l] = R.tau_term_cached(hpow[l], 0, own0)[1]
                # u^(j) = tau_{h_j}(u0); entries M[j][l] = (k, free matrix) with term = free * own_l
                M = [[None] * W for _ in range(W)]
                ok = True
                for j in range(W):
                    hj = hpow[j]
                    for (k, l, g) in u0:
                        lj, gj = R.tau_term_cached(hj, l, g) if j else (l, g)
                        b = G.mul(G.MATS[gj], np.conj(G.MATS[own[lj]]).T)
                        if not G.is_monomial(b):
                            ok = False; break
                        M[j][lj] = (k, b)
                    if not ok:
                        break
                if not ok:
                    continue
                n_coinc += 1
                # group generated by the entries
                ents = [M[j][l][1] for j in range(W) for l in range(W)]
                Bp = group_closure_mats(G, ents, cap)
                order = len(Bp) if Bp else None
                res = []
                for r in range(W):                          # character chi = exp(2 pi i r / W) on the tau^k components
                    chi = np.exp(2j * np.pi * r / W)
                    # f = 1 and f = 2 representations
                    inv_f = []
                    for f in (1, 2):
                        blocks = [[(chi ** M[j][l][0]) * (M[j][l][1] if f == 1 else np.kron(M[j][l][1], M[j][l][1])) for l in range(W)] for j in range(W)]
                        Mat = np.block(blocks)
                        inv_f.append(np.linalg.matrix_rank(Mat, tol=1e-8) == Mat.shape[0])
                    # trivial representation
                    triv = np.array([[chi ** M[j][l][0] for l in range(W)] for j in range(W)])
                    inv_t = abs(np.linalg.det(triv)) > 1e-9
                    inv_reg = None
                    if Bp is not None:
                        keys = list(Bp.keys()); idx = {k: i for i, k in enumerate(keys)}
                        N = len(keys)
                        # left regular representation of an element b: e_x -> e_{b x}
                        def regmat(b):
                            P = np.zeros((N, N), dtype=complex)
                            for i, k in enumerate(keys):
                                y = G.mul(b, Bp[k])
                                P[idx[G.key(y)], i] = 1
                            return P
                        if N * W <= 4000:
                            blocks = [[(chi ** M[j][l][0]) * regmat(M[j][l][1]) for l in range(W)] for j in range(W)]
                            Mat = np.block(blocks)
                            inv_reg = np.linalg.matrix_rank(Mat, tol=1e-8) == Mat.shape[0]
                    res.append((r, inv_t, inv_f[0], inv_f[1], inv_reg))
                    if inv_t and inv_f[0] and inv_f[1] and inv_reg:
                        n_inv += 1
                        np.save(f"GADGET_{m}_{W}_{Hn}_{n_coinc}_r{r}.npy", np.array([d, b0, a]))
                print(f"coincidence {n_coinc}: |B'| = {order}; per character r (trivial, f=1, f=2, regular B'): {res}", flush=True)
    print(f"m={m} W={W} H={Hn}: coincidences {n_coinc}, invertible (all tests) {n_inv}", flush=True)

if __name__ == "__main__":
    main()
