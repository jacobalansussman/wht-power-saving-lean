"""t15_subalg.py (session 2) -- how small can the group-algebra element be?  Reduced problem (t9) with Y restricted to the
span of the permutation matrices of a SUBGROUP Gamma of G: the stabiliser of the kernel slot, the normaliser of <pt>,
a Sylow 2-subgroup, <pt> itself, and the subgroup generated by pt and the kernel-slot stabiliser.  Z7, content cell 16,
O1 cell 1, all six nontrivial characters."""
import sys, os, random, time
here = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.dirname(here))
from sp8 import *
t0 = time.time()
P = Polar(); D = P.D; iZ = P.idx[LZ]
iK = P.idx[img_mask(table(inv(sigma(G.K))), LZ)]
rng = random.Random(3); nrng = np.random.default_rng(11)
gensM = [sigma(G.D[z]) for z in range(1, 16)] + [sigma(G.rand_engine(rng)) for _ in range(30)]
trans = {iZ: IDM}; fr = [iZ]
while fr:
    nf = []
    for i in fr:
        for g in gensM:
            s2 = mul(g, trans[i]); j = P.idx[span_mask([app(s2, 1 << (4 + k)) for k in range(4)])]
            if j not in trans: trans[j] = s2; nf.append(j)
    fr = nf
letters = [sigma(G.rand_engine(rng)) for _ in range(4000)]
F = [j for j in P.nb[iK] if P.dZ[j] == 3][0]
nbF = P.nb[F]; ni = {Y: k for k, Y in enumerate(nbF)}
T = [Y for Y in nbF if P.dZ[Y] == 2 and D[Y, iK] == 2]
t1 = T[0]
def pm(a, b): return tuple(a[b[i]] for i in range(len(b)))
def pinv(a):
    r = [0] * len(a)
    for x, y in enumerate(a): r[y] = x
    return tuple(r)
s0 = trans[t1]; s0i = inv(s0)
Fp = P.idx[img_mask(table(s0i), P.L[F])]
gens = []
for b in letters:
    if P.idx[img_mask(table(b), P.L[Fp])] == Fp:
        g = mul(s0, mul(b, s0i)); Tg = table(g)
        gens.append(tuple(ni[P.idx[img_mask(Tg, P.L[Y])]] for Y in nbF))
    if len(gens) >= 60: break
idp = tuple(range(30)); grp = {idp}; fr = [idp]
while fr:
    nf = []
    for g in fr:
        for s in gens:
            h = pm(s, g)
            if h not in grp: grp.add(h); nf.append(h)
    fr = nf
grpl = sorted(grp)
k0 = ni[iK]
sev = []
for g in grpl:
    h = g; k = 1
    while h != idp and k < 8: h = pm(g, h); k += 1
    if k == 7: sev.append(g)
pt = sev[0]
def closure(gs):
    S = {idp}; fr = [idp]
    while fr:
        nf = []
        for g in fr:
            for s in gs:
                h = pm(s, g)
                if h not in S: S.add(h); nf.append(h)
        fr = nf
    return S
def pmat(g):
    M = np.zeros((30, 30)); M[list(g), list(range(30))] = 1; return M
w7 = np.exp(2j * np.pi / 7)
def ovecs(g, a):
    gi = pinv(g); seen = set(); vs = []
    for N in range(30):
        if N in seen: continue
        orb = [N]; cur = N
        for _ in range(6): cur = gi[cur]; orb.append(cur)
        seen |= set(orb)
        if len(set(orb)) == 1: continue
        v = np.zeros(30, dtype=complex)
        for h, c in enumerate(orb): v[c] += w7 ** (a * h)
        vs.append(v)
    return np.array(vs).T
fixed = [s for s in range(30) if all(g[s] == s for g in gens)]
lam1 = [Y for Y in P.nb[t1] if P.dZ[Y] == 1][0]
Fr_slots = sorted(set([ni[c] for c in nbF if D[c, lam1] == 1]) | set(fixed)); nF = len(Fr_slots)
e = np.zeros(30, dtype=complex); e[k0] = 1
def test(Gam, label):
    keys = list(Gam); Q = np.zeros((0, 900)); basis = []
    for g in keys:
        v = pmat(g).reshape(-1); r = v - Q.T @ (Q @ v)
        if np.linalg.norm(r) > 1e-8: Q = np.vstack([Q, r / np.linalg.norm(r)]); basis.append(g)
    Bm = np.array([pmat(g) for g in basis]); dA = len(basis)
    best = 9e9
    for trial in range(3):
        Mbig = np.zeros((180, dA + nF * 6), dtype=complex); bb = np.zeros(180, dtype=complex)
        for ia, a in enumerate(range(1, 7)):
            S = ovecs(pt, a); wa = S @ (nrng.standard_normal(S.shape[1]) + 1j * nrng.standard_normal(S.shape[1]))
            Mbig[30 * ia:30 * ia + 30, :dA] = (Bm @ wa).T
            for j, s_ in enumerate(Fr_slots): Mbig[30 * ia + s_, dA + nF * ia + j] = 1
            bb[30 * ia:30 * ia + 30] = e
        x, *_ = np.linalg.lstsq(Mbig, bb, rcond=None); best = min(best, float(np.linalg.norm(Mbig @ x - bb)))
    print(f'  {label}: |Gamma| = {len(Gam)}, dim of its span = {dA}, reduced residual {best:.2e}', flush=True)
stab = [g for g in grpl if g[k0] == k0]
norm = [g for g in grpl if pm(g, pm(pt, pinv(g))) in {pt, pm(pt, pt), pm(pt, pm(pt, pt)), pm(pt, pm(pt, pm(pt, pt)))} or pm(g, pm(pt, pinv(g))) in closure([pt])]
test(set(grpl), 'G itself')
test(closure([pt]), '<pt>')
test(set(norm), 'normaliser of <pt>')
test(set(stab), 'stabiliser of the kernel slot')
test(closure([pt] + stab[:20]), '<pt, stabiliser of the kernel slot>')
# a Sylow 2-subgroup: grow from random 2-elements
rs = random.Random(5); S2 = {idp}
for _ in range(4000):
    g = rs.choice(grpl); h = g; k = 1
    while h != idp and k < 64: h = pm(g, h); k += 1
    if k & (k - 1) == 0:
        C = closure(list(S2 - {idp})[:8] + [g]) if len(S2) > 1 else closure([g])
        if len(C) & (len(C) - 1) == 0 and len(C) > len(S2): S2 = C
    if len(S2) == 512: break
test(S2, 'a 2-subgroup')
# random small subgroups generated by pt and one more element
for j in range(4):
    test(closure([pt, rs.choice(grpl)]), f'<pt, random element {j}>')
print('done %.0fs' % (time.time() - t0))
