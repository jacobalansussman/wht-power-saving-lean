def frames(nf, seed=1):
    rng = np.random.default_rng(seed)
    F = []
    F.append((np.full(N, 32767), np.zeros(N, int)))
    F.append((np.full(N, -32768), np.full(N, -32768)))
    F.append((np.where(np.arange(N) % 2 == 0, 32767, -32768), np.where(np.arange(N) % 2 == 0, -32768, 32767)))
    t = np.arange(N)
    F.append((np.round(32767 * np.cos(2 * np.pi * 17 * t / N)).astype(int), np.round(32767 * np.sin(2 * np.pi * 17 * t / N)).astype(int)))
    imp = np.zeros(N, int); imp[0] = 32767; F.append((imp, np.zeros(N, int)))
    F.append((rng.choice([-32768, 32767, -1, 0, 1], N), rng.choice([-32768, 32767, -1, 0, 1], N)))
    F.append((np.round(32767 * np.cos(2 * np.pi * 2047.5 * t / N)).astype(int), np.zeros(N, int)))
    while len(F) < nf:
        if len(F) % 2:
            F.append((rng.integers(-32768, 32768, N), rng.integers(-32768, 32768, N)))
        else:
            g = np.clip(np.round(rng.normal(0, 8192, (2, N))), -32768, 32767).astype(int)
            F.append((g[0], g[1]))
    return F[:nf]


def sim(design, var, nf, work, top='ffold', netlist=False, broken=None, skip=0):
    work = os.path.abspath(work); os.makedirs(work, exist_ok=True)
    F = frames(nf + skip)[skip:]
    with open(os.path.join(work, 'in.hex'), 'w') as f:
        for xr, xi in F:
            for a, b in zip(xr, xi):
                f.write('%04x%04x\n' % (int(a) & 0xFFFF, int(b) & 0xFFFF))
    write_rom(os.path.join(work, 'rom.hex'))
    with open(os.path.join(work, 'tb.v'), 'w') as f:
        f.write(TB % dict(top=top, nw=nf * 4096 - 1, nf=nf))
    exe = os.path.join(work, 'a.out')
    srcs = [os.path.abspath(design), os.path.join(work, 'tb.v'), CELLS]
    r = subprocess.run(['/usr/sbin/taskpolicy', '-b', BIN + '/iverilog', '-g2012', '-o', exe, '-DNO_ICE40_DEFAULT_ASSIGNMENTS'] + srcs,
                       capture_output=True, text=True, cwd=work)
    if r.returncode:
        print(r.stderr[-3000:]); return False
    r = subprocess.run(['/usr/sbin/taskpolicy', '-b', BIN + '/vvp', '-n', exe], capture_output=True, text=True, cwd=work)
    lines = open(os.path.join(work, 'out.txt')).read().split('\n')
    bad = 0; badfr = 0; pos = 0; cyc = []
    for fi, (xr, xi) in enumerate(F):
        cyc.append(int(lines[pos].split()[1])); pos += 1
        mr, mi = model(xr, xi, broken=broken)
        got = lines[pos:pos + N]; pos += N
        nb = 0
        for u in range(N):
            v = got[u]
            if 'x' in v or 'X' in v or 'z' in v:
                nb += 1; continue
            gr = int(v[:4], 16); gi = int(v[4:], 16)
            if gr != (int(mr[u]) & 0xFFFF) or gi != (int(mi[u]) & 0xFFFF):
                nb += 1
        bad += nb; badfr += (nb > 0)
        if nb and badfr <= 3:
            print('frame %d: %d mismatches' % (fi, nb))
    print('frames %d (skip %d) samples %d mismatching samples %d frames with errors %d clocks per frame %s' % (nf, skip, nf * N, bad, badfr, sorted(set(cyc))))
    print('RESULT', 'PASS' if bad == 0 else 'FAIL')
    return bad == 0


def precision(nfr=8):
    rng = np.random.default_rng(7)
    out = []
    for kind in ('complex noise -12 dBFS', 'real noise -12 dBFS', 'real tone bin 333 -1 dBFS'):
        es = 0.0; ss = 0.0; me = []; spur = []
        for f in range(nfr):
            if kind.startswith('complex'):
                x = np.clip(np.round(rng.normal(0, 32768 * 10 ** (-12 / 20), (2, N))), -32768, 32767).astype(int)
            elif kind.startswith('real noise'):
                x = np.vstack([np.clip(np.round(rng.normal(0, 32768 * 10 ** (-12 / 20), N)), -32768, 32767).astype(int), np.zeros(N, int)])
            else:
                t = np.arange(N); ph = rng.uniform(0, 2 * np.pi)
                x = np.vstack([np.round(32767 * 10 ** (-1 / 20) * np.cos(2 * np.pi * 333 * t / N + ph)).astype(int), np.zeros(N, int)])
            mr, mi = model(x[0], x[1])
            br = np.array([bitrev(u) for u in range(N)])
            Y = np.zeros(N, complex); Y[br] = mr + 1j * mi
            R = np.fft.fft(x[0] + 1j * x[1]) / N
            e = Y - R
            es += np.sum(np.abs(e) ** 2); ss += np.sum(np.abs(R) ** 2); me.append(np.mean(e.real))
            if 'tone' in kind:
                m = np.abs(Y); mask = np.ones(N, bool)
                for c in (333, N - 333):
                    mask[c - 3:c + 4] = False
                spur.append(20 * np.log10(m[mask].max() / m[333]))
        out.append('%-28s SQNR %.1f dB  mean err %.3f LSB%s' % (kind, 10 * np.log10(ss / es), np.mean(me),
                                                                  ('  worst spur %.1f dBc' % max(spur)) if spur else ''))
    return '\n'.join(out)


