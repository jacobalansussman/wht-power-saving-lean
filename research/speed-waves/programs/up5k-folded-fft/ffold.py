        " .PIPELINE_16x16_MULT_REG1(1'b0), .PIPELINE_16x16_MULT_REG2(1'b0), .TOPOUTPUT_SELECT(2'd%(tos)s), .TOPADDSUB_LOWERINPUT(2'd%(low)s),"
        " .TOPADDSUB_UPPERINPUT(1'b1), .TOPADDSUB_CARRYSELECT(2'd%(tcs)s), .BOTOUTPUT_SELECT(2'd%(bos)s), .BOTADDSUB_LOWERINPUT(2'd%(low)s),"
        " .BOTADDSUB_UPPERINPUT(1'b1), .BOTADDSUB_CARRYSELECT(2'd%(bcs)s), .MODE_8x8(1'b%(m8)s), .A_SIGNED(1'b1), .B_SIGNED(1'b1))\n"
        "   %(name)s (.CLK(clk), .CE(1'b1), .C(%(C)s), .A(%(A)s), .B(%(B)s), .D(%(D)s), .AHOLD(1'b0), .BHOLD(1'b0), .CHOLD(%(ch)s), .DHOLD(%(ch)s),"
