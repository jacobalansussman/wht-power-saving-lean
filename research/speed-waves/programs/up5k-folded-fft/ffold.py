#!/usr/bin/env python3
"""ffold.py -- as-6 (wave 14): a FOLDED 4,096-point complex FFT for the iCE40-UP5K.

In-place radix-2 decimation in frequency, one butterfly per 4-clock slot, data in 2 SPRAMs (re, im) used as one
single-port 16K x 32 memory (only 4K words used).  Slot: ph0 read a, ph1 read b, ph2 write a' = sum (computed from
the register holding a and the SPRAM output b), ph3 write the PREVIOUS butterfly's rotated difference at its b address.
Arithmetic (bit-true model below):
  butterfly, V6 rounding: s = (a>>1) + (b>>1) + (b & 1);  d = (a>>1) - (b>>1)        (16-bit, cannot overflow)
  twiddle: W = exp(-i pi k / 2048), k = (j << stage) mod 2048, Q14 cos table ROM[k] = round(16384 cos(pi k/2048)),
           C = ROM[k], S = sin = (k[10] ? +1 : -1) * ROM[k ^ 1024]
  Y_re = (2^13 + d_re*C + d_im*S) >> 14,  Y_im = (2^13 + d_im*C - d_re*S) >> 14, wrapped to 16 bits.
Every stage halves, so the output is X / 4096 in bit-reversed order (address u holds X[bitrev12(u)]).
4 clocks per butterfly: 12 * 2048 * 4 = 98,304 clocks per frame (+ 4 drain) = 24 clocks per sample.

Variants (gen --var):
  dsp   twiddle multiply in 2 SB_MAC16 (one per output component, OLOAD the rounding constant, then 2 products)
  dspbf dsp + the four butterfly add/subtracts in 2 more SB_MAC16 (am-5: top adder = difference, bottom = sum + CI)
  lc2   the same schedule with the two multiply-accumulates in logic cells (behavioural *, synthesised without -dsp)
  lc1   logic-only, ONE multiply-accumulate in logic cells doing the 4 products of a slot (1 product per clock)
  lcs   logic-only, a 2-bit-per-clock (radix-4 Booth-free, shift-add) serial multiplier: 8 clocks per product,
        32 clocks per complex product -> 32-clock slots (192 clocks per sample)
Usage:  ffold.py gen --var dsp -o fold_dsp.v ;  ffold.py sim fold_dsp.v --var dsp --frames 27 --work DIR
"""
import sys, os, argparse, subprocess, math
import numpy as np

N = 4096; LOG = 12
ROM = [int(round(16384 * math.cos(math.pi * k / 2048))) for k in range(2048)]


def wrap16(x):
    return ((x + 32768) & 0xFFFF) - 32768


def model(xr, xi, broken=None):
    """bit-true in-place DIF; returns arrays in memory order (address u holds X[bitrev(u)] / 4096)."""
    re = np.array(xr, dtype=np.int64).copy(); im = np.array(xi, dtype=np.int64).copy()
    rom = np.array(ROM, dtype=np.int64)
    if broken == 'tw':
        rom = rom.copy(); rom[300] ^= 1
    j = np.arange(2048, dtype=np.int64)
    for s in range(LOG):
        q = 11 - s; h = 1 << q
        a = ((j >> q) << (q + 1)) | (j & (h - 1)); b = a | h
        k = (j << s) & 2047
        ar, ai, br, bi = re[a], im[a], re[b], im[b]
        cr = (br & 1); ci = (bi & 1)
        if broken == 'carry' and s == 6:
            cr = cr * 0
        sr = (ar >> 1) + (br >> 1) + cr; si = (ai >> 1) + (bi >> 1) + ci
        dr = (ar >> 1) - (br >> 1); di = (ai >> 1) - (bi >> 1)
        C = rom[k]; sg = np.where((k >> 10) & 1 == 1, 1, -1); S = sg * rom[k ^ 1024]
        yr = (8192 + dr * C + di * S) >> 14; yi = (8192 + di * C - dr * S) >> 14
        yr = ((yr + 32768) & 0xFFFF) - 32768; yi = ((yi + 32768) & 0xFFFF) - 32768
        re[a] = sr; im[a] = si; re[b] = yr; im[b] = yi
    return re, im


def bitrev(n, bits=12):
    r = 0
    for i in range(bits):
        r = (r << 1) | ((n >> i) & 1)
    return r


# ----------------------------------------------------------------------------------------------- Verilog
HEAD = r"""// as-6 (wave 14) folded 4,096-point complex FFT, variant %(var)s. Generated by ffold.py. See its header.
// Protocol (as ao-f's whtmem): while idle, we_in writes din at addr_in, and dout shows the word at addr_in one clock
// later; a pulse on start runs the FFT in place (busy high); afterwards address u holds X[bitrev12(u)] / 4096.
module ffold (
  input clk, input start, input we_in, input [11:0] addr_in, input [15:0] din_re, input [15:0] din_im,
  output [15:0] dout_re, output [15:0] dout_im, output reg busy);
"""

CTRL = r"""
  reg [1:0] ph; reg [10:0] j; reg [11:0] th;      // th[x] = (x < q), q = bit of the butterfly span (11 .. 0)
  reg primed, drain; reg [11:0] bprev;
  reg [10:0] k, step;                               // twiddle index (lags j by one slot, see ffold.py) and 2^stage
  // address of a: j with a 0 inserted at bit q; b = a with bit q set
  wire [11:0] a, oh; genvar x;
  generate for (x = 0; x < 12; x = x + 1) begin : ga
    if (x == 0) begin
      assign a[0] = th[0] ? j[0] : 1'b0;  assign oh[0] = ~th[0];
    end else if (x == 11) begin
      assign a[11] = th[10] ? 1'b0 : j[10]; assign oh[11] = th[10];
    end else begin
      assign a[x] = th[x] ? j[x] : (th[x-1] ? 1'b0 : j[x-1]); assign oh[x] = ~th[x] & th[x-1];
    end
  end endgenerate
  wire [11:0] b = a | oh;
  wire [11:0] caddr = ph == 2'd1 ? b : ph == 2'd3 ? bprev : a;
  wire [13:0] maddr = {2'b00, busy ? caddr : addr_in};
  wire mwe = busy ? ((ph == 2'd2 && !drain) || (ph == 2'd3 && primed)) : we_in;
  wire [15:0] dr_o, di_o;   // SPRAM outputs
  assign dout_re = dr_o; assign dout_im = di_o;
  reg [15:0] ra, ia;        // a, captured at the end of ph1
  reg [15:0] romq; reg [10:0] radr;
"""

MEM = r"""
  SB_SPRAM256KA spr (.ADDRESS(maddr), .DATAIN(mdin_re), .MASKWREN(4'b1111), .WREN(mwe), .CHIPSELECT(1'b1),
                     .CLOCK(clk), .STANDBY(1'b0), .SLEEP(1'b0), .POWEROFF(1'b1), .DATAOUT(dr_o));
  SB_SPRAM256KA spi (.ADDRESS(maddr), .DATAIN(mdin_im), .MASKWREN(4'b1111), .WREN(mwe), .CHIPSELECT(1'b1),
                     .CLOCK(clk), .STANDBY(1'b0), .SLEEP(1'b0), .POWEROFF(1'b1), .DATAOUT(di_o));
  // twiddle ROM: Q14 cosine over half a turn (2,048 x 16 bits; block RAM)
  reg [15:0] rom [0:2047];
%(rominit)s  always @(posedge clk) romq <= rom[radr];
"""

SEQ = r"""
  initial busy = 0;
  always @(posedge clk) begin
    if (!busy) begin
      if (start) begin busy <= 1; ph <= 0; j <= 0; th <= 12'h7ff; primed <= 0; drain <= 0; k <= 0; step <= 11'd1; end
    end else begin
      ph <= ph + 2'd1;
      if (ph == 2'd1) begin ra <= dr_o; ia <= di_o; end
      if (ph == 2'd1 && primed) k <= (j == 11'd0) ? 11'd0 : k + step;   // k of butterfly j (step = 2^stage)
      if (ph == 2'd3) begin
        bprev <= b; primed <= 1; j <= j + 11'd1;
        if (&j) begin th <= {1'b0, th[11:1]}; step <= {step[9:0], 1'b0}; end
        if (&j && th == 12'd0) drain <= 1;
        if (drain) busy <= 0;
      end
    end
  end
"""


