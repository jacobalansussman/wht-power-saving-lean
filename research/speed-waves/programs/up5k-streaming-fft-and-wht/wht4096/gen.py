#!/usr/bin/env python3
"""gen.py -- streaming radix-2 single-path delay-feedback (R2SDF) Walsh-Hadamard transform for the
iCE40-UP5K, one 16-bit sample per clock, with a choice per stage of
  butterfly : 'beh'  behavioural Verilog (Yosys maps it to logic cells)
              'lc'   hand-mapped SB_LUT4 + SB_CARRY, phase multiplexers merged into the adder LUTs
              'mac'  one SB_MAC16 with the multiplier bypassed (top = C - A or load C, bottom = D + B or load D)
  delay     : 'ff'   flip-flop chain
              'ebr'  inferred block RAM (SB_RAM40_4K), circular buffer, addresses from the global counter
              'spram' two SB_SPRAM256KA banks ping-ponged every clock (even samples in bank A, odd in B)

Arithmetic (identical in every variant): each stage takes its input stream x, uses b = x >>> 1, stores
a = (earlier x) >>> 1, and emits the SWAPPED butterfly (a - b, a + b): first output a - b, second a + b.
Swapping the two outputs of every 2-point step turns the output order into reversed order, so
y_hw[j] = WHT_trunc[N-1-j]; this is what lets one SB_MAC16 absorb both phase multiplexers (OLOAD).
Usage: gen.py LOGN SPEC -o file.v     SPEC per stage, e.g. "mac:spram,mac:spram,mac:ebr,...,lc:ff"
       or a shorthand: B0 (all beh), B1 (all lc), M8 (8 mac then lc), M8S (M8 + spram for stages 0,1)
"""
import argparse, sys

W = 16

def lut_init(fn):
    v = 0
    for idx in range(16):
        i0, i1, i2, i3 = idx & 1, (idx >> 1) & 1, (idx >> 2) & 1, (idx >> 3) & 1
        if fn(i0, i1, i2, i3):
            v |= 1 << idx
    return "16'h%04X" % v

# Q = ph ? (a + b) : b        I0=ph I1=a I2=b I3=carry
INIT_Q = lut_init(lambda ph, a, b, c: (a ^ b ^ c) if ph else b)
# P = ph ? (a + ~b + 1) : a   I0=ph I1=a I2=nb I3=carry
INIT_P = lut_init(lambda ph, a, nb, c: (a ^ nb ^ c) if ph else a)
INIT_NOT = lut_init(lambda i0, i1, i2, i3: 1 - i0)

def default_delay(D, i, kind):
    if D <= 2:
        return 'ff'
    return 'ebr'

def parse_spec(logn, spec):
    S = logn
    if spec == 'T8n':
        return [(('macn' if i >= S - 8 else 'behs'), default_delay(1 << (S - 1 - i), i, '')) for i in range(S)]
    if spec == 'B0n':
        return [('behs', default_delay(1 << (S - 1 - i), i, '')) for i in range(S)]
    if spec in ('T8r', 'T8Sr'):   # T8b / T8Sb with every DSP output registered (no reliance on OLOAD reaching the combinational output)
        st = parse_spec(logn, spec.replace('r', 'b'))
        return [(bf, 'ebrr' if (bf == 'mac' and dl == 'ebr') else dl) for bf, dl in st]
    if spec in ('T8', 'T8S', 'T8b', 'T8Sb', 'B0S'):
        if spec == 'B0S':
            return [('beh', 'spram' if i < 2 else default_delay(1 << (S - 1 - i), i, 'beh')) for i in range(S)]
        lck = 'beh' if spec.endswith('b') else 'lc'
        spec = spec.rstrip('b')
        st = []
        for i in range(S):
            D = 1 << (S - 1 - i)
            bf = 'mac' if i >= S - 8 else lck
            dl = default_delay(D, i, bf)
            if bf == 'mac' and D == 1: dl = 'mreg1'
            if bf == 'mac' and D == 2: dl = 'mreg2'
            if spec == 'T8S' and i < 2: dl = 'spram'
            st.append((bf, dl))
        return st
    if spec in ('B0', 'B1', 'M8', 'M8S', 'M8S1', 'B1S'):
        st = []
        nmac = 8 if spec.startswith('M8') else 0
        for i in range(S):
            D = 1 << (S - 1 - i)
            bf = 'beh' if spec == 'B0' else ('mac' if i < nmac else 'lc')
            dl = default_delay(D, i, bf)
            if spec in ('M8S', 'B1S') and i < 2:
                dl = 'spram'
            if spec == 'M8S1' and i < 1:
                dl = 'spram'
            st.append((bf, dl))
        return st
    parts = spec.split(',')
    assert len(parts) == S, 'need %d stages' % S
    return [tuple(p.split(':')) for p in parts]

def gen(logn, stages, name='wht_sdf'):
    N = 1 << logn
    L = []
    w = L.append
    w('// generated by gen.py: N=%d, stages=%s' % (N, ','.join('%s:%s' % s for s in stages)))
    w('module %s (input clk, input rst, input [15:0] x, output [15:0] y, output y_first);' % name)
    w('  reg [%d:0] n;' % (logn - 1))
    w('  wire [%d:0] n1 = n + 1\'b1;' % (logn - 1))
    if any(dl == 'ebrr' for bf, dl in stages):
        w('  reg [%d:0] nd; always @(posedge clk) nd <= n;  // n - 1: write address for delay lines fed by a registered DSP output' % (logn - 1))
    w('  always @(posedge clk) n <= rst ? %d\'d0 : n1;' % logn)
    lats = [2 if dl == 'mreg2' else 1 for bf, dl in stages]
    for bf, dl in stages:
        assert dl not in ('mreg1', 'mreg2') or bf == 'mac'
    w("  assign y_first = (n == %d'd%d);" % (logn, (N - 1 + sum(lats)) % N))
    off = 0
    w('  wire [15:0] s0 = x;')
    for i, (bf, dl) in enumerate(stages):
        k = logn - 1 - i
        D = 1 << k
        w('  // ---- stage %d: D=%d, butterfly %s, delay %s' % (i, D, bf, dl))
        # phase: bit k of (n - i)
        o = off + (1 if dl == 'mreg2' else 0)   # mreg2: the adders work one clock later (input registers)
        off += lats[i]
        init = ((-o) % (2 * D)) >> k & 1
        if k == 0:
            w('  reg ph%d; always @(posedge clk) ph%d <= rst ? 1\'b%d : ~ph%d;' % (i, i, init, i))
        else:
            m = (o - 1) % D
            w("  reg ph%d; always @(posedge clk) ph%d <= rst ? 1'b%d : (ph%d ^ (n[%d:0] == %d'd%d));" % (i, i, init, i, k - 1, k, m))
        w('  wire [15:0] b%d = {s%d[15], s%d[15:1]};' % (i, i, i))
        w('  wire [15:0] a%d, q%d, p%d;' % (i, i, i))
        # delay line q -> a, delay D
        if dl == 'ff':
            w('  reg [15:0] dl%d [0:%d];' % (i, D - 1))
            w('  integer j%d;' % i)
            w('  always @(posedge clk) begin dl%d[0] <= q%d; for (j%d = 1; j%d < %d; j%d = j%d + 1) dl%d[j%d] <= dl%d[j%d-1]; end' % (i, i, i, i, D, i, i, i, i, i, i))
            w('  assign a%d = dl%d[%d];' % (i, i, D - 1))
        elif dl == 'ebr':
            w('  (* ram_style = "block" *) reg [15:0] mem%d [0:%d];' % (i, D - 1))
            w('  reg [15:0] rd%d;' % i)
            w('  always @(posedge clk) begin mem%d[n[%d:0]] <= q%d; rd%d <= mem%d[n1[%d:0]]; end' % (i, k - 1, i, i, i, k - 1))
            w('  assign a%d = rd%d;' % (i, i))
        elif dl == 'ebrr':   # the DSP's bottom output register is the first clock of the delay: memory delay D - 1
            assert bf == 'mac'
            # read and write addresses differ by 2 (mod D >= 4), so no collision logic is needed; Yosys cannot prove it
            w('  (* ram_style = "block", no_rw_check *) reg [15:0] mem%d [0:%d];' % (i, D - 1))
            w('  reg [15:0] rd%d;' % i)
            w('  always @(posedge clk) begin mem%d[nd[%d:0]] <= q%d; rd%d <= mem%d[n1[%d:0]]; end' % (i, k - 1, i, i, i, k - 1))
            w('  assign a%d = rd%d;' % (i, i))
        elif dl == 'spram':
            assert k >= 2
            w('  wire [15:0] da%d, db%d;' % (i, i))
            w('  wire [13:0] aa%d = n1[%d:1];' % (i, k - 1))
            w('  wire [13:0] ab%d = n[%d:1];' % (i, k - 1))
            for bank, addr, wren in (('A', 'aa%d' % i, '~n[0]'), ('B', 'ab%d' % i, 'n[0]')):
                w('  SB_SPRAM256KA sp%s%d (.ADDRESS(%s), .DATAIN(q%d), .MASKWREN(4\'b1111), .WREN(%s), .CHIPSELECT(1\'b1), .CLOCK(clk), .STANDBY(1\'b0), .SLEEP(1\'b0), .POWEROFF(1\'b1), .DATAOUT(d%s%d));'
                  % (bank, i, addr, i, wren, bank.lower(), i))
            w('  assign a%d = n[0] ? db%d : da%d;' % (i, i, i))
        elif dl in ('mreg1', 'mreg2'):
            assert D == (1 if dl == 'mreg1' else 2)
            w('  assign a%d = q%d;  // the SB_MAC16 bottom output register (and input registers for D=2) are the delay line' % (i, i))
        else:
            raise SystemExit('bad delay ' + dl)
        # butterfly: p = ph ? a - b : a (registered -> s{i+1}); q = ph ? a + b : b (combinational)
        if bf == 'beh':
            w('  assign p%d = ph%d ? a%d - b%d : a%d;' % (i, i, i, i, i))
            w('  assign q%d = ph%d ? a%d + b%d : b%d;' % (i, i, i, i, i))
            w('  reg [15:0] r%d; always @(posedge clk) r%d <= p%d;' % (i, i, i))
            w('  wire [15:0] s%d = r%d;' % (i + 1, i))
        elif bf == 'behs':   # standard order: P = ph ? a + b : a, Q = ph ? a - b : b
            w('  assign p%d = ph%d ? a%d + b%d : a%d;' % (i, i, i, i, i))
            w('  assign q%d = ph%d ? a%d - b%d : b%d;' % (i, i, i, i, i))
            w('  reg [15:0] r%d; always @(posedge clk) r%d <= p%d;' % (i, i, i))
            w('  wire [15:0] s%d = r%d;' % (i + 1, i))
        elif bf == 'macn':   # SB_MAC16 without the swap: top C + A (load C = a), bottom D - B = a - b, phase-0 'b' needs a LUT mux
            w('  wire [31:0] o%d;' % i)
            w("  SB_MAC16 #(.C_REG(1'b0), .A_REG(1'b0), .B_REG(1'b0), .D_REG(1'b0), .TOP_8x8_MULT_REG(1'b0), .BOT_8x8_MULT_REG(1'b0),"
              " .PIPELINE_16x16_MULT_REG1(1'b0), .PIPELINE_16x16_MULT_REG2(1'b0), .TOPOUTPUT_SELECT(2'd1), .TOPADDSUB_LOWERINPUT(2'd0),"
              " .TOPADDSUB_UPPERINPUT(1'b1), .TOPADDSUB_CARRYSELECT(2'd0), .BOTOUTPUT_SELECT(2'd0), .BOTADDSUB_LOWERINPUT(2'd0),"
              " .BOTADDSUB_UPPERINPUT(1'b1), .BOTADDSUB_CARRYSELECT(2'd0), .MODE_8x8(1'b1), .A_SIGNED(1'b0), .B_SIGNED(1'b0))")
            w("    u_mac%d (.CLK(clk), .CE(1'b1), .C(a%d), .A(b%d), .B(b%d), .D(a%d), .AHOLD(1'b0), .BHOLD(1'b0), .CHOLD(1'b0), .DHOLD(1'b0),"
              " .IRSTTOP(1'b0), .IRSTBOT(1'b0), .ORSTTOP(1'b0), .ORSTBOT(1'b0), .OLOADTOP(~ph%d), .OLOADBOT(1'b0),"
              " .ADDSUBTOP(1'b0), .ADDSUBBOT(1'b1), .OHOLDTOP(1'b0), .OHOLDBOT(1'b0), .CI(1'b0), .ACCUMCI(1'b0), .SIGNEXTIN(1'b0), .O(o%d),"
              " .CO(), .ACCUMCO(), .SIGNEXTOUT());" % (i, i, i, i, i, i, i))
            w('  assign p%d = o%d[31:16];' % (i, i))
            w('  assign q%d = ph%d ? o%d[15:0] : b%d;  // the multiplexer the swap removes' % (i, i, i, i))
            w('  wire [15:0] s%d = p%d;' % (i + 1, i))
        elif bf == 'lc':
            w('  bfly_lc u_bf%d (.ph(ph%d), .a(a%d), .b(b%d), .P(p%d), .Q(q%d));' % (i, i, i, i, i, i))
            w('  reg [15:0] r%d; always @(posedge clk) r%d <= p%d;' % (i, i, i))
            w('  wire [15:0] s%d = r%d;' % (i + 1, i))
        elif bf == 'mac':
            w('  wire [31:0] o%d;' % i)
            ir = "1'b1" if dl == 'mreg2' else "1'b0"
            bo = "2'd1" if dl in ('mreg1', 'mreg2', 'ebrr') else "2'd0"
            w('  SB_MAC16 #(.C_REG(%s), .A_REG(%s), .B_REG(%s), .D_REG(%s), .TOP_8x8_MULT_REG(1\'b0), .BOT_8x8_MULT_REG(1\'b0),' % (ir, ir, ir, ir) +
              ' .PIPELINE_16x16_MULT_REG1(1\'b0), .PIPELINE_16x16_MULT_REG2(1\'b0), .TOPOUTPUT_SELECT(2\'d1), .TOPADDSUB_LOWERINPUT(2\'d0),'
              ' .TOPADDSUB_UPPERINPUT(1\'b1), .TOPADDSUB_CARRYSELECT(2\'d0), .BOTOUTPUT_SELECT(%s), .BOTADDSUB_LOWERINPUT(2\'d0),' % bo +
              ' .BOTADDSUB_UPPERINPUT(1\'b1), .BOTADDSUB_CARRYSELECT(2\'d0), .MODE_8x8(1\'b1), .A_SIGNED(1\'b0), .B_SIGNED(1\'b0))')
            w('    u_mac%d (.CLK(clk), .CE(1\'b1), .C(a%d), .A(b%d), .B(a%d), .D(b%d), .AHOLD(1\'b0), .BHOLD(1\'b0), .CHOLD(1\'b0), .DHOLD(1\'b0),'
              ' .IRSTTOP(1\'b0), .IRSTBOT(1\'b0), .ORSTTOP(1\'b0), .ORSTBOT(1\'b0), .OLOADTOP(~ph%d), .OLOADBOT(~ph%d),'
              ' .ADDSUBTOP(1\'b1), .ADDSUBBOT(%s), .OHOLDTOP(1\'b0), .OHOLDBOT(1\'b0), .CI(1\'b0), .ACCUMCI(1\'b0), .SIGNEXTIN(1\'b0), .O(o%d),'
              ' .CO(), .ACCUMCO(), .SIGNEXTOUT());' % (i, i, i, i, i, i, i, "1'b0", i))
            w('  assign p%d = o%d[31:16];  // registered inside the MAC16' % (i, i))
            w('  assign q%d = o%d[15:0];   // combinational unless the delay is inside the MAC16' % (i, i))
            w('  wire [15:0] s%d = p%d;' % (i + 1, i))
        else:
            raise SystemExit('bad butterfly ' + bf)
    w('  assign y = s%d;' % logn)
    w('endmodule')
    if any(bf == 'lc' for bf, _ in stages):
        w('')
        w('// hand-mapped swapped butterfly: P = ph ? a - b : a (2 LC/bit), Q = ph ? a + b : b (1 LC/bit)')
        w('module bfly_lc (input ph, input [15:0] a, input [15:0] b, output [15:0] P, output [15:0] Q);')
        w('  wire [16:0] cq, cp; wire [15:0] nb;')
        w("  assign cq[0] = 1'b0; assign cp[0] = 1'b1;")
        w('  genvar g;')
        w('  generate for (g = 0; g < 16; g = g + 1) begin : gb')
        w('    SB_LUT4 #(.LUT_INIT(%s)) lq (.O(Q[g]), .I0(ph), .I1(a[g]), .I2(b[g]), .I3(cq[g]));' % INIT_Q)
        w('    SB_CARRY cqc (.CO(cq[g+1]), .CI(cq[g]), .I0(a[g]), .I1(b[g]));')
        w('    SB_LUT4 #(.LUT_INIT(%s)) ln (.O(nb[g]), .I0(b[g]), .I1(1\'b0), .I2(1\'b0), .I3(1\'b0));' % INIT_NOT)
        w('    SB_LUT4 #(.LUT_INIT(%s)) lp (.O(P[g]), .I0(ph), .I1(a[g]), .I2(nb[g]), .I3(cp[g]));' % INIT_P)
        w('    SB_CARRY cpc (.CO(cp[g+1]), .CI(cp[g]), .I0(a[g]), .I1(nb[g]));')
        w('  end endgenerate')
        w('endmodule')
    return '\n'.join(L) + '\n'

if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('logn', type=int)
    ap.add_argument('spec')
    ap.add_argument('-o', required=True)
    ap.add_argument('--name', default='wht_sdf')
    ap.add_argument('--break-stage', type=int, default=-1, help='deliberately broken copy: flip ADDSUBBOT (mac) or the add (beh/lc) of this stage')
    A = ap.parse_args()
    st = parse_spec(A.logn, A.spec)
    v = gen(A.logn, st, A.name)
    if A.break_stage >= 0:
        i = A.break_stage
        bf = st[i][0]
        if bf == 'mac':
            tag = "u_mac%d (" % i
            pos = v.index(tag)
            j = v.index(".ADDSUBBOT(1'b0)", pos)
            v = v[:j] + ".ADDSUBBOT(1'b1)" + v[j + len(".ADDSUBBOT(1'b0)"):]
        elif bf == 'beh':
            v = v.replace('assign q%d = ph%d ? a%d + b%d' % (i, i, i, i), 'assign q%d = ph%d ? a%d - b%d' % (i, i, i, i))
        else:
            v = v.replace('u_bf%d (.ph(ph%d)' % (i, i), 'u_bf%d (.ph(~ph%d)' % (i, i))
    open(A.o, 'w').write(v)
    print('wrote', A.o, 'stages:', ' '.join('%s:%s' % s for s in st))
