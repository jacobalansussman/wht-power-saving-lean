# straight-line NEON sparse mel for 2 frames, generated from the filterbank dump (same lo/len4/offset rule as lm.c)
import struct, sys
NB = 201
raw = open(sys.argv[1], "rb").read(); NM = len(raw) // (8 * NB)
W = struct.unpack("<%dd" % (NM * NB), raw)
lo, l4, off, o = [], [], [], 0
for m in range(NM):
    nz = [k for k in range(NB) if W[m * NB + k] != 0]
    a, b = (nz[0], nz[-1] + 1) if nz else (0, 1)
    L = (b - a + 3) & ~3
    lo.append(a); l4.append(L); off.append(o); o += L
out = ["/* generated by gen_mel.py from %s: NM=%d */" % (sys.argv[1], NM),
       "static inline void mel_gen2(const float *restrict pa, const float *restrict pb, float *restrict ma, float *restrict mb) {",
       "  float32x4_t w, A0, A1, A2, A3, B0, B1, B2, B3;"]
for g in range(NM // 4):
    for q in range(4):
        m = 4 * g + q
        for j in range(0, l4[m], 4):
            out.append("  w = vld1q_f32(WC + %d);" % (off[m] + j))
            if j == 0:
                out.append("  A%d = vmulq_f32(w, vld1q_f32(pa + %d)); B%d = vmulq_f32(w, vld1q_f32(pb + %d));" % (q, lo[m], q, lo[m]))
            else:
                out.append("  A%d = vfmaq_f32(A%d, w, vld1q_f32(pa + %d)); B%d = vfmaq_f32(B%d, w, vld1q_f32(pb + %d));" % (q, q, lo[m] + j, q, q, lo[m] + j))
    out.append("  vst1q_f32(ma + %d, vpaddq_f32(vpaddq_f32(A0, A1), vpaddq_f32(A2, A3)));" % (4 * g))
    out.append("  vst1q_f32(mb + %d, vpaddq_f32(vpaddq_f32(B0, B1), vpaddq_f32(B2, B3)));" % (4 * g))
out.append("}")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print("wrote", sys.argv[2], "vectors", o // 4)
