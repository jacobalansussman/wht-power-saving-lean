#!/usr/bin/env python3
"""sweep3.py (w8-rmexact): the cell multi-target LP (mtlp.py) at block 3 for EVERY subgroup of GL(3,2)
(all subgroups are generated by at most two elements; deduplicated).  Prints, per subgroup, its order, the number of
distinct virtual targets h h^T, whether it is orthogonal, and the LP bound on M/W (3 = no saving possible)."""
import sys, itertools, numpy as np
sys.path.insert(0, '.')
from forms import setup, pair
from scipy.optimize import linprog
from scipy.sparse import coo_matrix
m = 3; D = setup(m); GL = D['GL']; supp = D['supp']; nf = D['nf']; dirs = D['dirs']; mm, tr = D['matmul'], D['transpose']
I = [1 << i for i in range(m)]
key = lambda g: tuple(g)
def closure(gens):
    grp = {key(I): I}; fr = [I]
    while fr:
        new = []
        for g in fr:
            for s in gens:
                h = mm(s, g)
                if key(h) not in grp: grp[key(h)] = h; new.append(h)
        fr = new
    return grp
subs = {}
for a in GL:
    for b in GL:
        G = closure([a, b]); subs[frozenset(G)] = list(G.values())
print("subgroups of GL(3,2) found:", len(subs), flush=True)
nd = len(dirs); di = {x: i for i, x in enumerate(dirs)}
pairs = [(i, j) for i in range(nd) for j in range(i, nd)]; pk = {p: nd + k for k, p in enumerate(pairs)}
nv = nd + len(pairs); ri, ci, vv, rhs_of = [], [], [], []; r = 0
def addrow(row, which):
    global r
    for k, v in row.items(): ri.append(r); ci.append(k); vv.append(v)
    rhs_of.append(which); r += 1
for F in range(1, nf):
    P = sorted(di[x] for x in supp[F]); row = {}
    for i in P: row[i] = 1; row[pk[(i, i)]] = -1
    for i, j in itertools.combinations(P, 2): row[pk[(i, j)]] = -2
    addrow(row, ('+', F))
for G in range(1, nf):
    P = sorted(di[x] for x in supp[G]); addrow({i: -1 for i in P}, ('-', G))
    for i, j in itertools.combinations_with_replacement(P, 2):
        row = {x: -1 for x in P}; row[pk[(i, j)]] = 1; addrow(row, ('-', G))
for (i, j), k in pk.items():
    addrow({k: 1, i: -1}, ('0', 0))
    if i != j: addrow({k: 1, j: -1}, ('0', 0))
A = coo_matrix((vv, (ri, ci)), shape=(r, nv)).tocsr(); cobj = np.zeros(nv); cobj[:nd] = 1
from collections import Counter
tab = Counter()
Ienc = D['enc_sym'](I)
for S_, gr in sorted(subs.items(), key=lambda kv: len(kv[1])):
    T = [D['enc_sym'](mm(h, tr(h))) for h in gr]; n = len(T)
    a = np.array([sum(pair(F, S) for S in T) / n for F in range(nf)])
    b = np.array([a[F] if s == '+' else (-a[F] if s == '-' else 0.0) for (s, F) in rhs_of])
    res = linprog(cobj, A_ub=A, b_ub=b, bounds=[(0, None)] * nv, method='highs')
    orth = all(t == Ienc for t in T)
    tab[(n, len(set(T)), orth, round(res.fun, 6))] += 1
for k in sorted(tab): print("order %3d  distinct targets %2d  orthogonal %-5s  LP M/W >= %.6f   x %d" % (k[0], k[1], k[2], k[3], tab[k]))
