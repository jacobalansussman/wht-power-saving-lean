# hgroups.py: address groups H for mtlp*.py (exec'd; needs args, D, m)
import itertools as _it
def make_H(args, D):
    m = D['m']; GL = D['GL']; mm, tr = D['matmul'], D['transpose']
    I = [1 << i for i in range(m)]
    def singer():
        p = args.poly; cols = []
        for j in range(m):
            v = 1 << (j + 1)
            if v >> m: v ^= p
            cols.append(v)
        return [sum(((cols[j] >> i) & 1) << j for j in range(m)) for i in range(m)]
    def gen_group(gens):
        grp = {tuple(I)}; frontier = [I]
        while frontier:
            new = []
            for g in frontier:
                for s in gens:
                    h = mm(s, g)
                    if tuple(h) not in grp: grp.add(tuple(h)); new.append(h)
            frontier = new
        return [list(g) for g in grp]
    def mpow(A, k):
        R = I
        for _ in range(k): R = mm(A, R)
        return R
    if args.H == 'trivial': H = [I]
    elif args.H.startswith('singer'):
        k = int(args.H.split(':')[1]) if ':' in args.H else 1
        H = gen_group([mpow(singer(), k)])
    elif args.H == 'GL': H = GL
    elif args.H == 'perm': H = [[1 << p[i] for i in range(m)] for p in _it.permutations(range(m))]
    elif args.H == 'orth':
        e = D['enc_sym'](I); H = [h for h in GL if D['enc_sym'](mm(h, tr(h))) == e]
    elif args.H.startswith('elt:'):     # cyclic group generated by GL[index]
        H = gen_group([GL[int(args.H.split(':')[1])]])
    else: raise SystemExit('unknown H')
    if args.conj >= 0:
        g = GL[args.conj]; gi = next(x for x in GL if mm(x, g) == I)
        H = [mm(mm(g, h), gi) for h in H]
    return H
