#!/usr/bin/env python3
"""lbf.py (rm-singer): L-BFGS exploration for the canonical Singer system (same system and fibres as lma.py).
All fibres are evaluated together in one batched dense solve: X_f = Atil diag(pi_f) (I + Gamma diag(pi_f))^-1 Btil,
which equals Atil_D (I + Gamma_DD)^-1 Btil_D (block elimination over D and its complement).  The cost is the sum of
|X_f - I_W (x) P_J|^2 over the fibres used.  Unknowns: complex circulant blocks A (W x M), B (M x W), Gamma (M x M,
strictly lower).  A fit is "found" when the cost on ALL fibres is below --found; it is then re-checked on all fibres
in float64 and saved (--save).  Evidence only: an exact step is still needed for any claim.
"""
import argparse, json, time, sys, math
import torch
sys.path.insert(0, '.')
from sfield import Singer

ap = argparse.ArgumentParser()
ap.add_argument('--m', type=int, required=True)
ap.add_argument('--p', type=int, default=1)          # address group generated by sigma^p; p = 0: no address maps
ap.add_argument('--coords', default='sd')
ap.add_argument('--W', type=int, required=True)
ap.add_argument('--M', type=int, required=True)
ap.add_argument('--dirs', default='')
ap.add_argument('--alldirs', action='store_true')
ap.add_argument('--plain', action='store_true')
ap.add_argument('--restarts', type=int, default=4)
ap.add_argument('--iters', type=int, default=20000)  # L-BFGS iterations per restart (cap)
ap.add_argument('--chunk', type=int, default=200)
ap.add_argument('--scale', type=float, default=0.5)
ap.add_argument('--gscale', type=float, default=0.2)
ap.add_argument('--seed', type=int, default=1)
ap.add_argument('--nfib', type=int, default=0)
ap.add_argument('--subseed', type=int, default=-1)   # fixed fibre subset for all restarts (>= 0)
ap.add_argument('--found', type=float, default=1e-20)
ap.add_argument('--stall', type=float, default=1e-7)   # stop a restart when a chunk improves the cost by < this fraction
ap.add_argument('--maxtime', type=float, default=1800.0)
ap.add_argument('--save', default='')
ap.add_argument('--trivial', default='')   # file of a 1-in-r program: start = plain for W-1 arrays + it for the last
ap.add_argument('--noise', type=float, default=0.0)
ap.add_argument('--init', default='')    # start exactly at a saved point (same shape)
ap.add_argument('--polish_at', type=float, default=1e-5)
ap.add_argument('--group', type=int, default=1)
ap.add_argument('--polish_maxpc', type=int, default=1300)
ap.add_argument('--checkgroup', action='store_true')
ap.add_argument('--polish_iters', type=int, default=12)
args = ap.parse_args()
torch.set_default_dtype(torch.float64)
CT = torch.complex128

S = Singer(args.m, args.coords); F = S.F; n = S.n
if args.p == 0:
    d = 1; hexp = [0]
else:
    d = n // math.gcd(n, args.p); hexp = [(args.p * k) % n for k in range(d)]
W, M = args.W, args.M
if args.dirs: zexp = [int(x) for x in args.dirs.split(',')]
elif args.alldirs: zexp = [t % n for t in range(M)]
elif args.plain: zexp = [F.log[S.w[t % args.m]] for t in range(M)]
else: zexp = [0] * M
z = [F.a_exp(e) for e in zexp]

seen = set(); fibres = []
for Q in S.forms():
    if not any(Q): continue
    v = tuple(S.Qval(Q, x) for x in range(1, F.q))
    if v in seen: continue
    seen |= {tuple(S.Qval(Q, F.mul(F.a_exp(-e), x)) for x in range(1, F.q)) for e in hexp}
    Kt = [[S.Qval(Q, F.mul(F.a_exp(-hexp[k]), z[t])) for k in range(d)] for t in range(M)]
    J = [k for k in range(d) if S.pair(Q, S.Tk(hexp[k]))]
    fibres.append((Kt, J))
Wd, Md = W * d, M * d
PI = torch.tensor([[Kt[t][k] for t in range(M) for k in range(d)] for Kt, J in fibres], dtype=CT)   # (F, Md)
TT = torch.zeros(len(fibres), Wd, dtype=CT)
for f, (Kt, J) in enumerate(fibres):
    for l in range(W):
        for k in J: TT[f, l * d + k] = 1
nodd = int((TT.abs().sum(1) > 0).sum())
print(f"# lbf m={args.m} coords={args.coords} d={d} W={W} M={M} dirs={zexp[:16]} fibres={len(fibres)} (target-odd {nodd})",
      flush=True)

idx = (torch.arange(d)[:, None] - torch.arange(d)[None, :]) % d
low = [(s, t) for s in range(M) for t in range(s)]
nA, nB, nG = W * M * d, M * W * d, len(low) * d
Pc = nA + nB + nG
ls = torch.tensor([s for s, t in low], dtype=torch.long); lt = torch.tensor([t for s, t in low], dtype=torch.long)

def big(X, r, c):
    return X[:, :, idx].permute(0, 2, 1, 3).reshape(r * d, c * d)

def unpack(x):
    A = x[:nA].reshape(W, M, d); B = x[nA:nA + nB].reshape(M, W, d)
    G = torch.zeros(M, M, d, dtype=CT)
    G = G.index_put((ls, lt), x[nA + nB:].reshape(len(low), d))
    return big(A, W, M), big(B, M, W), big(G, M, M)

def resid(x, sel):
    Ab, Bb, Gb = unpack(x)
    pi = PI[sel]                                                   # (f, Md)
    L = torch.eye(Md, dtype=CT)[None] + Gb[None] * pi[:, None, :]  # I + Gamma diag(pi)
    Y = torch.linalg.solve(L, Bb[None].expand(len(sel), Md, Wd))
    X = (Ab[None] * pi[:, None, :]) @ Y
    return X - torch.diag_embed(TT[sel])

# grouped version: fibres batched by |D|, solving only the |D| x |D| block (same value, cheaper)
GROUPS = {}
def groups_for(sel):
    key = tuple(sel.tolist())
    if key not in GROUPS:
        by = {}
        for f in key:
            Dc = PI[f].real.nonzero().flatten()
            by.setdefault(len(Dc), []).append((f, Dc))
        GROUPS[key] = [(torch.tensor([f for f, _ in v]), torch.stack([D for _, D in v])) for k, v in by.items() if k > 0] \
            + [(torch.tensor([f for f, _ in v]), None) for k, v in by.items() if k == 0]
    return GROUPS[key]

def cost_g(x, sel):
    Ab, Bb, Gb = unpack(x)
    c = 0.0
    for fs, Dc in groups_for(sel):
        T = torch.diag_embed(TT[fs])
        if Dc is None:
            c = c + (T.abs() ** 2).sum(); continue
        k = Dc.shape[1]
        L = torch.eye(k, dtype=CT)[None] + Gb[Dc[:, :, None], Dc[:, None, :]]
        Y = torch.linalg.solve(L, Bb[Dc])                         # (g, k, Wd)
        X = Ab[:, Dc].permute(1, 0, 2) @ Y                         # (g, Wd, Wd)
        c = c + ((X - T).abs() ** 2).sum()
    return c

def cost(x, sel):
    return cost_g(x, sel) if args.group else (resid(x, sel).abs() ** 2).sum()


# ---- LM polish (analytic Jacobian, copied from lma.py; same x layout) ----
kk = torch.arange(d)
def prep(fl):
    out = []
    for Kt, J in fl:
        msk = torch.tensor([Kt[t][k] for t in range(M) for k in range(d)], dtype=torch.bool)
        T = torch.zeros(Wd, Wd, dtype=CT)
        for l in range(W):
            for k in J: T[l * d + k, l * d + k] = 1
        out.append((msk, T))
    return out
LMDAT = prep(fibres)

def fibre_solve(x, dat):
    Ab, Bb, Gb = unpack(x)
    res = []
    for msk, T in dat:
        Dc = msk.nonzero().flatten()
        if len(Dc) == 0:
            res.append((msk, T, None, None, -T)); continue
        L = torch.eye(len(Dc), dtype=CT) + Gb[Dc][:, Dc]
        Y = torch.linalg.solve(L, Bb[Dc])
        Z = torch.linalg.solve(L.T, Ab[:, Dc].T).T
        X = Ab[:, Dc] @ Y - T
        res.append((msk, T, Y, Z, X))
    return res

def jac_fibre(msk, Y, Z):
    Dc = msk.nonzero().flatten()
    Yp = torch.zeros(M, d, Wd, dtype=CT); Zp = torch.zeros(Wd, M, d, dtype=CT)
    if len(Dc):
        Yp.view(Md, Wd)[Dc] = Y; Zp.view(Wd, Md)[:, Dc] = Z
    sh = (kk[:, None] - kk[None, :]) % d
    YA = Yp[:, sh, :]
    JA = torch.zeros(W, d, Wd, W, M, d, dtype=CT)
    for l in range(W):
        JA[l, :, :, l, :, :] = YA.permute(1, 3, 0, 2)
    JA = JA.reshape(Wd * Wd, nA)
    sh2 = (kk[:, None] + kk[None, :]) % d
    ZB = Zp[:, :, sh2]
    JB = torch.zeros(Wd, W, d, M, W, d, dtype=CT)
    for l in range(W):
        JB[:, l, :, :, l, :] = ZB.permute(0, 2, 1, 3)
    JB = JB.reshape(Wd * Wd, nB)
    JG = torch.zeros(Wd, Wd, len(low), d, dtype=CT)
    for r in range(d):
        Zr = Zp[:, :, (kk + r) % d]
        JG[:, :, :, r] = -torch.einsum('aik,ikb->abi', Zr[:, ls, :], Yp[lt])
    JG = JG.reshape(Wd * Wd, nG)
    return torch.cat([JA, JB, JG], dim=1)

def lm_polish(x, iters):
    lam = 1e-6
    c0 = sum(float((X.abs() ** 2).sum()) for *_, X in fibre_solve(x, LMDAT))
    for it in range(iters):
        if c0 < 1e-26: break
        sol = fibre_solve(x, LMDAT)
        JTJ = torch.zeros(Pc, Pc, dtype=CT); g = torch.zeros(Pc, dtype=CT)
        for msk, T, Y, Z, X in sol:
            if Y is None: continue
            Jf = jac_fibre(msk, Y, Z)
            JTJ += Jf.conj().T @ Jf; g += Jf.conj().T @ X.reshape(-1)
        dg = torch.diagonal(JTJ).real.clone() + 1e-12
        ok = False
        while lam < 1e12:
            dx = torch.linalg.solve(JTJ + lam * torch.diag(dg).to(CT), -g)
            cn = sum(float((X.abs() ** 2).sum()) for *_, X in fibre_solve(x + dx, LMDAT))
            if cn < c0:
                if c0 < 1e-20 and cn > 0.5 * c0: c0 = cn; x = x + dx; ok = False; break   # converged to round-off
                x = x + dx; c0 = cn; lam = max(lam / 10, 1e-15); ok = True; break
            lam *= 10
        print(f"  LM polish it {it} cost {c0:.3e}", flush=True)
        if not ok: break
    return x, c0

ALLSEL = torch.arange(len(fibres))
def rand_x(seed):
    gen = torch.Generator().manual_seed(seed)
    re = torch.randn(Pc, generator=gen); im = torch.randn(Pc, generator=gen)
    x = torch.complex(re, im) * (args.scale / math.sqrt(2))
    x[nA + nB:] *= args.gscale / args.scale
    return x

def trivial_x():
    """plain schedule (exact_plain.py convention: A_t = P^r_t, B_t = P^-r_t, Gamma_st = 2 P^(r_t - r_s)) for arrays
    0..W-2 on moves 0..m(W-1)-1, and the saved 1-in-r program for array W-1 on the remaining moves."""
    mm = args.m; r0 = [F.log[w] for w in S.w]
    A = torch.zeros(W, M, d, dtype=CT); B = torch.zeros(M, W, d, dtype=CT); G = torch.zeros(M, M, d, dtype=CT)
    nplain = min(W, M // mm) if args.trivial == 'plain' else W - 1
    for l in range(nplain):
        ts = list(range(l * mm, (l + 1) * mm))
        for i, t in enumerate(ts):
            A[l, t, r0[i] % d] = 1; B[t, l, (-r0[i]) % d] = 1
            for j, s in enumerate(ts):
                if s > t: G[s, t, (r0[i] - r0[j]) % d] = 2
    t0 = mm * (W - 1)
    if args.trivial != 'plain':
        sv = torch.load(args.trivial); a = sv['args']; r = a['M']
        assert a['W'] == 1 and a['m'] == args.m and t0 + r == M
        x1 = sv['x']; nA1, nB1 = r * d, r * d
        A1 = x1[:nA1].reshape(1, r, d); B1 = x1[nA1:nA1 + nB1].reshape(r, 1, d)
        low1 = [(s, t) for s in range(r) for t in range(s)]
        g1 = x1[nA1 + nB1:].reshape(len(low1), d)
        A[W - 1, t0:] = A1[0]; B[t0:, W - 1] = B1[:, 0]
        for i, (s, t) in enumerate(low1): G[t0 + s, t0 + t] = g1[i]
    gl = torch.stack([G[s, t] for s, t in low]) if low else torch.zeros(0, d, dtype=CT)
    return torch.cat([A.reshape(-1), B.reshape(-1), gl.reshape(-1)])

def run(seed):
    if args.nfib and args.nfib < len(fibres):
        g0 = torch.Generator().manual_seed(1000 + (args.subseed if args.subseed >= 0 else seed))
        sel = torch.randperm(len(fibres), generator=g0)[:args.nfib]
    else:
        sel = ALLSEL
    if args.init:
        x0 = torch.load(args.init)['x'].clone()
        print(f"  seed {seed} init start cost {float(cost(x0, ALLSEL)):.6e}", flush=True)
    elif args.trivial:
        gen = torch.Generator().manual_seed(seed)
        x0 = trivial_x()
        x0 = x0 + args.noise * torch.complex(torch.randn(Pc, generator=gen), torch.randn(Pc, generator=gen)) / math.sqrt(2)
        print(f"  seed {seed} trivial start cost {float(cost(x0, ALLSEL)):.6e} (noise {args.noise})", flush=True)
    else:
        x0 = rand_x(seed)
    xr = torch.view_as_real(x0).clone().requires_grad_(True)
    opt = torch.optim.LBFGS([xr], lr=1, max_iter=args.chunk, history_size=100, line_search_fn='strong_wolfe',
                            tolerance_grad=1e-300, tolerance_change=1e-300)
    def closure():
        opt.zero_grad()
        c = cost(torch.view_as_complex(xr), sel); c.backward(); return c
    t0 = time.time(); prev = float('inf'); it = 0; c = prev
    while it < args.iters and time.time() - t0 < args.maxtime:
        opt.step(closure); it += args.chunk
        with torch.no_grad():
            c = float(cost(torch.view_as_complex(xr), sel))
        print(f"  seed {seed} it {it} cost {c:.6e} t {time.time() - t0:.0f}s", flush=True)
        if not math.isfinite(c): break
        if c < args.found: break
        if c < args.polish_at and Pc <= args.polish_maxpc and (args.nfib == 0 or args.nfib >= len(fibres)): break
        if prev < float('inf') and prev - c < args.stall * prev: break
        prev = c
    with torch.no_grad():
        x = torch.view_as_complex(xr).detach().clone()
        call = float(cost(x, ALLSEL))
        if call < args.polish_at and call >= args.found and Pc <= args.polish_maxpc:
            x, _ = lm_polish(x, args.polish_iters); call = float(cost(x, ALLSEL))
    return x, c, call, it, time.time() - t0

if args.checkgroup:
    x = rand_x(5); t0 = time.time(); a = float((resid(x, ALLSEL).abs() ** 2).sum()); t1 = time.time()
    b = float(cost_g(x, ALLSEL)); t2 = time.time()
    print(f"# checkgroup full {a:.12e} ({t1-t0:.2f}s) grouped {b:.12e} ({t2-t1:.2f}s) rel {abs(a-b)/a:.2e}"); sys.exit(0)
best = None
for s in range(args.seed, args.seed + args.restarts):
    x, c, call, its, tt = run(s)
    rec = dict(m=args.m, coords=args.coords, p=args.p, d=d, W=W, M=M, seed=s, cost=c, cost_all=call, iters=its,
               secs=round(tt), Pc=Pc, fibres=len(fibres), found=call < args.found)
    with torch.no_grad():
        R = resid(x, ALLSEL)                                   # (F, Wd, Wd)
        rows = (R.abs() ** 2).sum(2).reshape(len(fibres), W, d).sum((0, 2))
        rec['per_array_rows'] = [round(float(v), 6) for v in rows]
        Xd = torch.diagonal(R + torch.diag_embed(TT), dim1=1, dim2=2).reshape(len(fibres), W, d)
        hit = (((Xd - TT.reshape(len(fibres), W, d)).abs() < 1e-3).all(2)).sum(0)   # fibres served on the diagonal
        rec['fibres_diag_ok_per_array'] = [int(v) for v in hit]
        rec['xnorm_A_B_G'] = [round(float(x[:nA].abs().max()), 3), round(float(x[nA:nA+nB].abs().max()), 3), round(float(x[nA+nB:].abs().max()) if nG else 0.0, 3)]
    print(json.dumps(rec), flush=True)
    if best is None or call < best[1]: best = (x, call, s)
if args.save and best is not None:
    torch.save(dict(x=best[0], cost_all=best[1], seed=best[2], args=vars(args)), args.save)
