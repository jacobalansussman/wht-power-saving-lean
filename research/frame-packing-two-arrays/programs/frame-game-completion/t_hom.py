"""t_hom.py: calibration of complete.py.
(1) conventions: symp(dir z) = T_z, symp(monomial lift of p) = p (fpa's convention);
(2) the even-block data: character orbits under Sp and their sizes (block 0: 1 + (4^m - 1); block 2: N+ and N-);
(3) the cocycle identities eps(gh, v) = eps(g, h.v) eps(h, v) and del(gh, w) = del(g, h.w) del(h, w), and the
    lift-independence rules eps(n, v) = chi_v(n), del(n, w) = value of [n] on e2_w, on random letters;
(4) Lambda is a homomorphism on raw arrays: a random word lambda = q_k T_zk ... T_z1 q_0, lifted letter by letter, equals
    Lambda applied to ONE lift of lambda (the matrix product times a random Pauli and a random scalar), at every f;
    the same comparison WITHOUT the corrections D (plain engine letters) fails at most f;
(5) pi o Lambda = id on the frame-game block is automatic (D_0's trivial-character coefficient is 1): checked.
usage: t_hom.py m fmax [P|H]"""
import sys, random, time
import numpy as np
import warnings; warnings.filterwarnings('ignore')
import os; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from complete import *

m = int(sys.argv[1]); fmax = int(sys.argv[2])
B0 = sys.argv[3] if len(sys.argv) > 3 else 'P'
E = Eng(m, B0); S = E.S; rng = random.Random(100 + m)
t0 = time.time()
# (1)
for z in range(1, E.n): assert E.symp(E.dirm(z)) == S.T(z)
for _ in range(30):
    p = S.rand_P(rng); assert E.symp(E.lift_P(p)) == p
assert E.symp(E.K) == S.K
print(f"m={m}: (1) conventions hold: symp(dir z) = T_z for all z; symp(lift(p)) = p for 30 random p; symp(K) = Kbar")
# (2) orbits of Sp on the characters of the even blocks, generated by the letters' actions
gens = [E.dirm(z) for z in range(1, E.n)] + [E.lift_P(S.rand_P(rng)) for _ in range(6)]
acts0 = [E.eps0(g)[1] for g in gens]; acts2 = [E.del2(g)[1] for g in gens]
def orbits(acts):
    seen = set(); out = []
    for v in range(E.NL):
        if v in seen: continue
        orb = {v}; fr = [v]
        while fr:
            x = fr.pop()
            for a in acts:
                y = int(a[x])
                if y not in orb: orb.add(y); fr.append(y)
        seen |= orb; out.append(len(orb))
    return sorted(out)
o0 = orbits(acts0); o2 = orbits(acts2)
Np = 2 ** (m - 1) * (2 ** m + 1); Nm = 2 ** (m - 1) * (2 ** m - 1)
print(f"m={m}: (2) block-0 character orbits {o0} (expected [1, {4**m - 1}]); block-2 orbits {o2} (expected [{Nm}, {Np}])")
assert o0 == [1, 4 ** m - 1] and o2 == sorted([Nm, Np])
# (3) cocycles
def rand_letter():
    r = rng.random()
    if r < 0.4: return E.dirm(rng.randrange(1, E.n))
    if r < 0.8: return E.lift_P(S.rand_P(rng))
    u = rng.randrange(E.NL); return (1j ** rng.randrange(4)) * E.P[u]
bad = 0
for _ in range(40):
    g, h = rand_letter(), rand_letter()
    eg, ig = E.eps0(g); eh, ih = E.eps0(h); egh, igh = E.eps0(g @ h)
    if not (np.allclose(egh, eg[ih] * eh) and np.all(igh == ig[ih])): bad += 1
    dg, jg = E.del2(g); dh, jh = E.del2(h); dgh, jgh = E.del2(g @ h)
    if not (np.allclose(dgh, dg[jh] * dh) and np.all(jgh == jg[jh])): bad += 1
for u in range(E.NL):
    for j in range(4):
        n_ = (1j ** j) * E.P[u]
        e, im0 = E.eps0(n_); d, im2 = E.del2(n_)
        assert np.all(im0 == np.arange(E.NL)) and np.all(im2 == np.arange(E.NL))
        assert np.allclose(e, E.chi[:, u])                       # eps(n, v) = chi_v(n): block 0 kills scalars
        assert np.allclose(d, ((-1) ** j) * E.chi[:, u])         # [i^j P_u] e2 = (-1)^j chi_w(u)
print(f"m={m}: (3) cocycle identities: {80 - bad}/80 hold; Pauli rules eps(n,v) = chi_v(n), del(n,w) = (-1)^j chi_w(u): all {4 * E.NL} hold")
assert bad == 0
# (5)
assert all(abs(E.eps0(g)[0][0] - 1) < 1e-12 for g in gens)
print(f"m={m}: (5) eps(g, 0) = 1 for every letter, so the frame-game projection of Lambda(lambda) is lambda")
# (4) homomorphism on raw arrays
def rand_word(L):
    w = [('p', S.rand_P(rng))]
    for _ in range(L):
        w.append(('T', rng.randrange(1, E.n))); w.append(('p', S.rand_P(rng)))
    return w
for trial in range(2):
    word = rand_word(3 if m <= 3 else 2)
    mats = [E.dirm(x) if t == 'T' else E.lift_P(x) for t, x in word]
    Dl = [E.D(M) for M in mats]
    G = np.eye(E.n, dtype=complex)
    for M in mats: G = M @ G
    G2 = (1j ** rng.randrange(4)) * E.P[rng.randrange(E.NL)] @ G     # a different lift of the same lambda
    assert E.symp(G2) == E.symp(G)
    DG = E.D(G2)
    naive = lambda M: {(u, 0): c for u, c in enumerate(E.pexp(np.linalg.inv(M))) if abs(c) > 1e-13}
    Dnl = [naive(M) for M in mats]; DGn = naive(G2)      # fp-build's f = 1 lift, not projected to block 1
    errs, errs_naive = {}, {}
    for f in range(1, fmax + 1):
        R = Raw(E, f); rn = np.random.default_rng(f + 10 * trial)
        x = rn.normal(size=R.N) + 1j * rn.normal(size=R.N)
        y = x.copy(); yn = x.copy()
        for M, Dd, Dn in zip(mats, Dl, Dnl):
            y = R.mat(M, R.nfree(Dd, y)); yn = R.mat(M, R.nfree(Dn, yn))
        t = R.mat(G2, R.nfree(DG, x))
        tn = R.mat(G2, R.nfree(DGn, x))
        errs[f] = float("%.1e" % (np.abs(y - t).max() / np.abs(t).max()))
        errs_naive[f] = float("%.1e" % (np.abs(yn - tn).max() / np.abs(tn).max()))
    print(f"m={m}: (4) word {trial} ({sum(1 for t, _ in word if t == 'T')} moves): Lambda letter by letter vs Lambda(one lift):"
          f" errors by f {errs}; the f = 1 lift alone (D = Pexp(g^-1) in every block): {errs_naive}", flush=True)
print(f"m={m}: done in {time.time() - t0:.1f} s")
