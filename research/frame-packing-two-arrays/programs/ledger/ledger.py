#!/usr/bin/env python3
"""ledger.py (sl-combinatorics, 15 Oct 2026): exact engine-game words at small blocks, with the frame ledger.

Model (theory-guide RULES section 0, hb.py): registers hold formal contents sum c_(g,l) g y_l, g in the group G
generated by the engine letters at block m, c Gaussian rationals.  Letters:
    dir z  = ca*1 + cb*X^z  (paid; ca = (1+i)/2, cb = (1-i)/2), K = dir e_1 ... dir e_m
    X z    = address shift x -> x ^ z                  (free)
    A cols = invertible address map, column images     (free)
    P z c  = diag(i^((z.x + c) mod 2))                 (free phase letter)
Steps of a word:
    ("move", r, z)                       c_r := dir z . c_r
    ("free", r, name)                    c_r := letter . c_r
    ("mix", r, [(s, mu, name|None), ..]) c_r := sum mu * letter * c_s   (old values; letter None = identity)
    ("gate", [r1..rk], A)                (c_r1..c_rk) := A (c_r1..c_rk), A a k x k matrix of Gaussian rationals
Group elements are kept exactly: integer complex matrices scaled by 2^m, normalised modulo the scalars {1,i,-1,-i}
(the scalar goes into the coefficient).  Each element also carries its mod-2 image in Sp(2m, 2) (action on Pauli
labels (a|b), columns = images of basis labels, a-bits first).

THE LEDGER (PROOF.md section 2).  A gauge assigns to each input l a symplectic matrix h_l.  The LABEL of a term
(g, l) is lambda = gbar * h_l in Sp(2m,2) (so labels are taken modulo Paulis and scalars); the LEVEL of a label is
delta(lambda) = rank_F2 of its x-block on L0 = frame distance of lambda^-1 L0 from the raw frame L0 = paid length.
Lambda_r(t) = set of labels of register r.  Psi(t) = sum_r sum_{lambda in Lambda_r} delta(lambda).
Per move on r: every label lambda in Lambda_r goes to T_z lambda (T_z = transvection of (z|0)); it is an ASCENT,
LATERAL or DESCENT as delta goes up, stays, goes down (it changes by at most 1).  P += |Lambda_r| - 1 (PACKING),
I0 += 1 if Lambda_r is empty (idle move).  Mixes and gates change Psi; Bmix := - sum of those changes.
Raw identity (every word, every gauge):  M = Psi_end - Psi_0 + Bmix + 2D + Z - P + I0.
Unit form (word is a unit): M = W m - 2N + X + 2D + Z + B - P + I0, N = sum delta(h_a), X = sum (delta(h_a) +
delta(Kbar h_a) - m) >= 0, B = Bmix + (Psi_end - sum over delivering registers of delta(Kbar h_l)).
"""
import itertools, random
from fractions import Fraction as Fr
import numpy as np

# ------------------------------------------------------------------ Gaussian rationals
class GQ:
    __slots__ = ("a", "b")
    def __init__(s, a, b=0):
        s.a = a if isinstance(a, Fr) else Fr(a); s.b = b if isinstance(b, Fr) else Fr(b)
    def __add__(s, o): return GQ(s.a + o.a, s.b + o.b)
    def __sub__(s, o): return GQ(s.a - o.a, s.b - o.b)
    def __mul__(s, o): return GQ(s.a * o.a - s.b * o.b, s.a * o.b + s.b * o.a)
    def __neg__(s): return GQ(-s.a, -s.b)
    def __eq__(s, o):
        o = o if isinstance(o, GQ) else GQ(o)
        return s.a == o.a and s.b == o.b
    def __hash__(s): return hash((s.a, s.b))
    def iszero(s): return s.a == 0 and s.b == 0
    def inv(s):
        n = s.a * s.a + s.b * s.b
        return GQ(s.a / n, -s.b / n)
    def __repr__(s):
        if s.b == 0: return str(s.a)
        if s.a == 0: return "%si" % s.b
        return "(%s%+si)" % (s.a, s.b)
ONE = GQ(1); I_ = GQ(0, 1)
UNITS = [GQ(1), GQ(0, 1), GQ(-1), GQ(0, -1)]   # i^k
def gq(x):
    if isinstance(x, GQ): return x
    if isinstance(x, complex): return GQ(Fr(x.real).limit_denominator(1 << 20), Fr(x.imag).limit_denominator(1 << 20))
    return GQ(x)

# ------------------------------------------------------------------ F_2 helpers
def rank2(A):
    A = (np.array(A, dtype=np.int64) % 2).astype(np.uint8).copy()
    r = 0; rows, cols = A.shape
    for c in range(cols):
        p = None
        for i in range(r, rows):
            if A[i, c]: p = i; break
        if p is None: continue
        if p != r: A[[r, p]] = A[[p, r]]
        for i in range(rows):
            if i != r and A[i, c]: A[i] ^= A[r]
        r += 1
        if r == rows: break
    return r
def inv2(A):
    n = A.shape[0]
    M = np.concatenate([np.array(A, dtype=np.uint8) % 2, np.eye(n, dtype=np.uint8)], axis=1)
    r = 0
    for c in range(n):
        p = None
        for i in range(r, n):
            if M[i, c]: p = i; break
        assert p is not None, "singular"
        if p != r: M[[r, p]] = M[[p, r]]
        for i in range(n):
            if i != r and M[i, c]: M[i] ^= M[r]
        r += 1
    return M[:, n:].astype(np.int64)
def mul2(A, B): return (np.array(A, dtype=np.int64) @ np.array(B, dtype=np.int64)) % 2
def key2(A): return (np.array(A, dtype=np.uint8) % 2).tobytes()

# ------------------------------------------------------------------ the engine at block m
def cmul(A, B):
    """exact product of integer complex matrices given as (re, im) int64 pairs"""
    return (A[0] @ B[0] - A[1] @ B[1], A[0] @ B[1] + A[1] @ B[0])
def cdiv(A, d):
    assert not (A[0] % d).any() and not (A[1] % d).any(), "non-integral after rescaling"
    return (A[0] // d, A[1] // d)
class Engine:
    """group elements as exact integer complex matrices g*2^m, kept as (re, im) int64 pairs, normalised modulo
    the scalars {1, i, -1, -i}; no floating point anywhere"""
    def __init__(s, m):
        s.m = m; s.N = N = 1 << m; s.SC = 1 << m
        s.mats = []; s.syms = []; s.index = {}; s.mulcache = {}
        s.letters = {}
        Z0 = np.zeros((N, N), dtype=np.int64)
        s.ID = s.intern((np.eye(N, dtype=np.int64) * s.SC, Z0.copy()))[0]
        for z in range(1, N): s.add_letter("X%d" % z, s._perm(lambda x, z=z: x ^ z))
        for z in range(N):
            for c in (0, 1):
                re = np.zeros((N, N), dtype=np.int64); im = np.zeros((N, N), dtype=np.int64)
                for x in range(N):
                    if (bin(z & x).count("1") + c) & 1: im[x, x] = s.SC
                    else: re[x, x] = s.SC
                s.add_letter("P%d_%d" % (z, c), (re, im))
        for z in range(1, N):
            # dir z = (1+i)/2 * 1 + (1-i)/2 * X^z, scaled by 2^m
            h = s.SC // 2
            re = np.zeros((N, N), dtype=np.int64); im = np.zeros((N, N), dtype=np.int64)
            for x in range(N):
                re[x, x] += h; im[x, x] += h
                re[x ^ z, x] += h; im[x ^ z, x] -= h
            s.add_letter("D%d" % z, (re, im))
        s.Kid = s.ID
        for j in range(m): s.Kid = s.lmul("D%d" % (1 << j), s.Kid)[0]
        s.Ksym = s.syms[s.Kid]
    def _perm(s, f):
        re = np.zeros((s.N, s.N), dtype=np.int64)
        for x in range(s.N): re[f(x), x] = s.SC
        return (re, np.zeros((s.N, s.N), dtype=np.int64))
    def addr(s, cols):
        """address map letter with column images cols (cols[k] = image of e_k); x -> sum x_k cols[k]"""
        name = "A" + ",".join(map(str, cols))
        if name not in s.letters:
            def f(x):
                y = 0
                for k in range(s.m):
                    if (x >> k) & 1: y ^= cols[k]
                return y
            assert len(set(f(x) for x in range(s.N))) == s.N, "not invertible"
            s.add_letter(name, s._perm(f))
        return name
    def add_letter(s, name, M):
        gid, ph = s.intern(M)
        s.letters[name] = (gid, ph)
    def intern(s, M):
        """normalise modulo {1,i,-1,-i}; return (id, scalar) with M = scalar * mats[id]"""
        re, im = M
        fr, fi = re.flatten(), im.flatten()
        nz = int(np.flatnonzero((fr != 0) | (fi != 0))[0])
        a, b = int(fr[nz]), int(fi[nz])
        # candidates M / u for u in (1, i, -1, -i): (a + bi)/u
        for k, (ur, ui) in enumerate(((1, 0), (0, 1), (-1, 0), (0, -1))):
            # divide by u: multiply by conj(u) (|u| = 1)
            wr, wi = a * ur + b * ui, b * ur - a * ui
            if wr > 0 and wi >= 0:
                Mn = (re * ur + im * ui, im * ur - re * ui); sc = UNITS[k]; break
        kk = Mn[0].tobytes() + Mn[1].tobytes()
        if kk not in s.index:
            s.index[kk] = len(s.mats); s.mats.append(Mn); s.syms.append(s._symp(Mn))
        return s.index[kk], sc
    def _symp(s, Mn):
        m, N = s.m, s.N
        g = Mn; gi = (Mn[0].T.copy(), -Mn[1].T.copy())          # conjugate transpose (unitary letters)
        S = np.zeros((2 * m, 2 * m), dtype=np.int64)
        SC2 = s.SC * s.SC
        for j in range(2 * m):
            a, b = (1 << j, 0) if j < m else (0, 1 << (j - m))
            Pr = np.zeros((N, N), dtype=np.int64)
            for x in range(N): Pr[x ^ a, x] = (-1) ** (bin(b & x).count("1") & 1)
            Q = cmul(cmul(g, (Pr, np.zeros((N, N), dtype=np.int64))), gi)      # = SC^2 * g P g^-1
            col = Q[0][:, 0] ** 2 + Q[1][:, 0] ** 2
            a2 = int(np.argmax(col))
            assert col[a2] == SC2 * SC2 and (col == 0).sum() == N - 1, "not Clifford"
            phr, phi = int(Q[0][a2, 0]), int(Q[1][a2, 0])
            b2 = 0
            for k in range(m):
                xk = 1 << k
                vr, vi = int(Q[0][xk ^ a2, xk]), int(Q[1][xk ^ a2, xk])
                if (vr, vi) == (-phr, -phi): b2 |= xk
                else: assert (vr, vi) == (phr, phi), "not a Pauli image"
            for k in range(m):
                S[k, j] = (a2 >> k) & 1; S[m + k, j] = (b2 >> k) & 1
        return S
    def lmul(s, name, gid):
        """letter . element -> (id, scalar)"""
        kk = (name, gid)
        if kk not in s.mulcache:
            lid, lph = s.letters[name]
            M = cdiv(cmul(s.mats[lid], s.mats[gid]), s.SC)
            nid, ph = s.intern(M)
            s.mulcache[kk] = (nid, lph * ph)
        return s.mulcache[kk]
    def mul(s, a, b):
        """element a . element b -> (id, scalar)"""
        kk = ("*", a, b)
        if kk not in s.mulcache:
            M = cdiv(cmul(s.mats[a], s.mats[b]), s.SC)
            s.mulcache[kk] = s.intern(M)
        return s.mulcache[kk]
    def inv(s, a):
        """inverse (unitary: conjugate transpose), modulo scalars"""
        kk = ("inv", a)
        if kk not in s.mulcache:
            Mi = (s.mats[a][0].T.copy(), -s.mats[a][1].T.copy())
            s.mulcache[kk] = s.intern(Mi)
        return s.mulcache[kk]
    def level(s, sym):
        return rank2(np.array(sym)[0:s.m, s.m:2 * s.m])

# ------------------------------------------------------------------ running a word with the ledger
def gauge_trivial(E, W): return [np.eye(2 * E.m, dtype=np.int64) for _ in range(W)]

def run(E, W, R, word, start=None, deliver=None, gauge=None, record=False, strict=False):
    """returns dict with contents, ledger counts, unit verdict.  start: register -> input (default r -> r for r < W);
    deliver: register -> input whose K y_l it must end with (default = start)."""
    m = E.m
    if start is None: start = {r: r for r in range(W)}
    if deliver is None: deliver = dict(start)
    if gauge is None: gauge = gauge_trivial(E, W)
    C = [dict() for _ in range(R)]
    for r, l in start.items(): C[r] = {(l, E.ID): ONE}
    labcache = {}
    def label(gid, l):
        kk = (gid, l)
        if kk not in labcache:
            if strict:
                # exact labels modulo scalars, trivial gauge only: the label is the group element itself
                labcache[kk] = (("g", gid), E.level(E.syms[gid]))
            else:
                L = mul2(E.syms[gid], gauge[l]); labcache[kk] = (key2(L), E.level(L))
        return labcache[kk]
    def labels(c):
        out = {}
        for (l, gid) in c:
            k, d = label(gid, l); out[k] = d
        return out
    def psi_of(c): return sum(labels(c).values())
    led = dict(M=0, A=0, D=0, Z=0, P=0, I0=0, Bmix=0, maxlab=0)
    psi0 = sum(psi_of(c) for c in C)
    hist = []
    for st in word:
        kind = st[0]
        if kind in ("move", "free"):
            r = st[1]
            name = ("D%d" % st[2]) if kind == "move" else st[2]
            before = labels(C[r])
            new = {}
            for (l, gid), co in C[r].items():
                nid, ph = E.lmul(name, gid)
                kk = (l, nid); new[kk] = new.get(kk, GQ(0)) + co * ph
            C[r] = {kk: c for kk, c in new.items() if not c.iszero()}
            if kind == "move":
                led["M"] += 1
                if not before: led["I0"] += 1
                else:
                    led["P"] += len(before) - 1
                    led["maxlab"] = max(led["maxlab"], len(before))
                    # each label moves in lockstep: compute its image directly from one representative term
                    seen = set()
                    for (l, gid) in list(C[r].keys()) + []:
                        pass
                    # image of each old label: T_z * lambda (mod 2), level change
                    Tz = E.syms[E.letters["D%d" % st[2]][0]]
                    for k, d in before.items():
                        if strict:
                            d2 = E.level(E.syms[E.lmul("D%d" % st[2], k[1])[0]])
                        else:
                            lam = np.frombuffer(k, dtype=np.uint8).reshape(2 * m, 2 * m).astype(np.int64)
                            d2 = E.level(mul2(Tz, lam))
                        assert abs(d2 - d) <= 1
                        if d2 > d: led["A"] += 1
                        elif d2 < d: led["D"] += 1
                        else: led["Z"] += 1
            else:
                after = labels(C[r])
                assert sorted(before.values()) == sorted(after.values()) or not C[r], "free letter changed levels"
        elif kind == "mix":
            r, terms = st[1], st[2]
            p_old = psi_of(C[r])
            new = {}
            for (sreg, mu, name) in terms:
                mu = gq(mu)
                for (l, gid), co in C[sreg].items():
                    if name is None: nid, ph = gid, ONE
                    else: nid, ph = E.lmul(name, gid)
                    kk = (l, nid); new[kk] = new.get(kk, GQ(0)) + mu * co * ph
            C[r] = {kk: c for kk, c in new.items() if not c.iszero()}
            led["Bmix"] -= psi_of(C[r]) - p_old
        elif kind == "gate":
            regs, A = st[1], st[2]
            p_old = sum(psi_of(C[r]) for r in regs)
            old = [C[r] for r in regs]
            for i, r in enumerate(regs):
                new = {}
                for j in range(len(regs)):
                    mu = gq(A[i][j])
                    if mu.iszero(): continue
                    for kk, co in old[j].items(): new[kk] = new.get(kk, GQ(0)) + mu * co
                C[r] = {kk: c for kk, c in new.items() if not c.iszero()}
            led["Bmix"] -= sum(psi_of(C[r]) for r in regs) - p_old
        else:
            raise ValueError(kind)
        if record: hist.append([dict(c) for c in C])
    psi_end = sum(psi_of(c) for c in C)
    raw_rhs = psi_end - psi0 + led["Bmix"] + 2 * led["D"] + led["Z"] - led["P"] + led["I0"]
    out = dict(led); out.update(psi0=psi0, psi_end=psi_end, raw_ok=(raw_rhs == led["M"]), contents=C, hist=hist)
    # unit verdict: delivering register r holds exactly (unit scalar) * K y_l
    unit = True
    for r, l in deliver.items():
        c = C[r]
        if len(c) != 1 or (l, E.Kid) not in c: unit = False; break
        co = c[(l, E.Kid)]
        if not (co.a * co.a + co.b * co.b == 1 and co in UNITS): unit = False; break
    out["unit"] = unit
    if unit:
        N = sum(E.level(gauge[a]) for a in range(W))
        X = sum(E.level(gauge[a]) + E.level(mul2(E.Ksym, gauge[a])) - m for a in range(W))
        deliv_psi = sum(E.level(mul2(E.Ksym, gauge[l])) for r, l in deliver.items())
        B = led["Bmix"] + (psi_end - deliv_psi)
        # inputs not placed at the start (none in our words) would change psi0; we always place all W inputs
        rhs = W * m - 2 * N + X + 2 * led["D"] + led["Z"] + B - led["P"] + led["I0"]
        out.update(N=N, X=X, B=B, unit_ok=(rhs == led["M"]))
    return out

# ------------------------------------------------------------------ coherence: is there a gauge with one label per register?
def find_coherent_gauge(E, W, R, word, start=None):
    """Sp-coherence test over every snapshot.  Returns (gauge or None, reason)."""
    res = run(E, W, R, word, start=start, record=True)
    m = E.m
    cons = []          # (l, l', T) meaning h_l' = T h_l
    for snap in [None] + res["hist"]:
        regs = res["hist"][0] if False else None
    snaps = res["hist"]
    init = [dict() for _ in range(R)]
    if start is None: start = {r: r for r in range(W)}
    for r, l in start.items(): init[r] = {(l, E.ID): ONE}
    for snap in [init] + snaps:
        for c in snap:
            per = {}
            for (l, gid) in c:
                per.setdefault(l, set()).add(key2(E.syms[gid]))
            for l, ks in per.items():
                if len(ks) > 1: return None, "same-input split (input %d carries %d labels in one register)" % (l, len(ks))
            ls = sorted(per)
            for i in range(1, len(ls)):
                l0, l1 = ls[0], ls[i]
                g0 = np.frombuffer(next(iter(per[l0])), dtype=np.uint8).reshape(2 * m, 2 * m).astype(np.int64)
                g1 = np.frombuffer(next(iter(per[l1])), dtype=np.uint8).reshape(2 * m, 2 * m).astype(np.int64)
                cons.append((l0, l1, mul2(inv2(g1), g0)))      # g0 h_l0 = g1 h_l1
    h = [None] * W
    adj = {}
    for (a, b, T) in cons:
        adj.setdefault(a, []).append((b, T)); adj.setdefault(b, []).append((a, inv2(T)))
    for root in range(W):
        if h[root] is not None: continue
        h[root] = np.eye(2 * m, dtype=np.int64); stack = [root]
        while stack:
            a = stack.pop()
            for (b, T) in adj.get(a, []):
                hb = mul2(T, h[a])
                if h[b] is None: h[b] = hb; stack.append(b)
                elif key2(h[b]) != key2(hb): return None, "holonomy (inconsistent relative gauge between inputs %d and %d)" % (a, b)
    return h, "coherent"

# ------------------------------------------------------------------ random symplectic gauges
def random_sp(E, rng, steps=12):
    """random element of Sp(2m,2) as a product of letter images (paid and free)"""
    names = list(E.letters)
    S = np.eye(2 * E.m, dtype=np.int64)
    for _ in range(steps):
        S = mul2(E.syms[E.letters[rng.choice(names)][0]], S)
    return S

def plain_word(m, W, rng=None):
    w = []
    for r in range(W):
        order = list(range(m))
        if rng: rng.shuffle(order)
        for j in order: w.append(("move", r, 1 << j))
    if rng:
        rng.shuffle(w)            # moves on different registers commute, and directions commute
    return w

# ------------------------------------------------------------------ strict coherence (labels exact up to scalars)
def find_strict_gauge(E, W, R, word, start=None):
    """Strict coherence: a gauge h_l in G (exact, modulo scalars) with ONE exact label g h_l per register at every
    time.  This is the hypothesis of the network-flow theorems (PROOF.md section 4)."""
    res = run(E, W, R, word, start=start, record=True)
    if start is None: start = {r: r for r in range(W)}
    init = [dict() for _ in range(R)]
    for r, l in start.items(): init[r] = {(l, E.ID): ONE}
    cons = []
    for snap in [init] + res["hist"]:
        for c in snap:
            per = {}
            for (l, gid) in c: per.setdefault(l, set()).add(gid)
            for l, ks in per.items():
                if len(ks) > 1: return None, "strict same-input split (input %d: %d group elements)" % (l, len(ks))
            ls = sorted(per)
            for i in range(1, len(ls)):
                l0, l1 = ls[0], ls[i]
                g0 = next(iter(per[l0])); g1 = next(iter(per[l1]))
                T = E.mul(E.inv(g1)[0], g0)[0]          # g0 h_l0 = g1 h_l1  =>  h_l1 = g1^-1 g0 h_l0
                cons.append((l0, l1, T))
    h = [None] * W; adj = {}
    for (a, b, T) in cons:
        adj.setdefault(a, []).append((b, T)); adj.setdefault(b, []).append((a, E.inv(T)[0]))
    for root in range(W):
        if h[root] is not None: continue
        h[root] = E.ID; stack = [root]
        while stack:
            a = stack.pop()
            for (b, T) in adj.get(a, []):
                hb = E.mul(T, h[a])[0]
                if h[b] is None: h[b] = hb; stack.append(b)
                elif h[b] != hb: return None, "strict holonomy (inputs %d, %d)" % (a, b)
    return [E.syms[x] for x in h], "strictly coherent"

# ------------------------------------------------------------------ the hypothesis of Theorem 4.3: no frame packing
def find_nopack_gauge(E, W, R, word, start=None):
    """an Sp-gauge in which every paid move acts on a register whose terms share ONE frame label (P_frame = 0), or None.
    Constraints are collected only from the moved register just before each move."""
    if start is None: start = {r: r for r in range(W)}
    C = [dict() for _ in range(R)]
    for r, l in start.items(): C[r] = {(l, E.ID): ONE}
    m = E.m; cons = []
    for st in word:
        if st[0] == "move":
            per = {}
            for (l, gid) in C[st[1]]: per.setdefault(l, set()).add(key2(E.syms[gid]))
            for l, ks in per.items():
                if len(ks) > 1: return None, "frame packing forced (input %d on %d frames in a moved array)" % (l, len(ks))
            ls = sorted(per)
            for i in range(1, len(ls)):
                g0 = np.frombuffer(next(iter(per[ls[0]])), dtype=np.uint8).reshape(2 * m, 2 * m).astype(np.int64)
                g1 = np.frombuffer(next(iter(per[ls[i]])), dtype=np.uint8).reshape(2 * m, 2 * m).astype(np.int64)
                cons.append((ls[0], ls[i], mul2(inv2(g1), g0)))
        res = run(E, W, R, [st], start=None, record=False) if False else None
        # advance the contents by one step (reuse run on a one-step word from the current state)
        C = _step(E, C, st)
    h = [None] * W; adj = {}
    for (a, b, T) in cons:
        adj.setdefault(a, []).append((b, T)); adj.setdefault(b, []).append((a, inv2(T)))
    for root in range(W):
        if h[root] is not None: continue
        h[root] = np.eye(2 * m, dtype=np.int64); stack = [root]
        while stack:
            a = stack.pop()
            for (b, T) in adj.get(a, []):
                hb = mul2(T, h[a])
                if h[b] is None: h[b] = hb; stack.append(b)
                elif key2(h[b]) != key2(hb): return None, "frame packing forced (holonomy between inputs %d, %d)" % (a, b)
    return h, "no frame packing in some gauge"

def _step(E, C, st):
    C = [dict(c) for c in C]
    kind = st[0]
    if kind in ("move", "free"):
        r = st[1]; name = ("D%d" % st[2]) if kind == "move" else st[2]
        new = {}
        for (l, gid), co in C[r].items():
            nid, ph = E.lmul(name, gid); kk = (l, nid); new[kk] = new.get(kk, GQ(0)) + co * ph
        C[r] = {kk: c for kk, c in new.items() if not c.iszero()}
    elif kind == "mix":
        r, terms = st[1], st[2]; new = {}
        for (sreg, mu, name) in terms:
            mu = gq(mu)
            for (l, gid), co in C[sreg].items():
                nid, ph = (gid, ONE) if name is None else E.lmul(name, gid)
                kk = (l, nid); new[kk] = new.get(kk, GQ(0)) + mu * co * ph
        C[r] = {kk: c for kk, c in new.items() if not c.iszero()}
    elif kind == "gate":
        regs, A = st[1], st[2]; old = [C[r] for r in regs]
        for i, r in enumerate(regs):
            new = {}
            for j in range(len(regs)):
                mu = gq(A[i][j])
                if mu.iszero(): continue
                for kk, co in old[j].items(): new[kk] = new.get(kk, GQ(0)) + mu * co
            C[r] = {kk: c for kk, c in new.items() if not c.iszero()}
    return C
