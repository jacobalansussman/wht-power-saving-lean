"""afc-cut (round wht45/afc, 20 Oct 2026): the full-cut rate profile of A-fc (#2979's words, fill u1-2979sep).

Reads A-fc's PROFILE.json (sha-pinned: the unit profile of one gauge copy, paid calls + idle remainders, as the hub's
owner engine and o-eval report it) and writes profile2979Fc.json for mk_rate_mixed.py:
  * the 16,576 literal heads (children 8/10, rank 48) are cut by ALL 48 axes: no remnant, target 73 - 48 = 25;
  * there is no other rank-48 block (FOUND.md: idle 48 = heads only), so nothing is split;
  * every other paid rank stays; the largest is 23 < 25 (separated).
Refuses (exit 2) if the 48-count is not the head count, if any other rank >= 25 is present, or if a rank 24..47 or a
rank > 48 is present (there would be something to split or cut).

usage: python3 -I -B mk_profile2979Fc.py PROFILE.json OUT.json
"""
import sys, json, hashlib

PIN = '5df7941120150492c64e62dc3362095eff3dfac9facff041ebb5c25b2e78f75e'
HEADS, W, M, KC = 16576, 66304, 73, 25


def main():
    src, out = sys.argv[1], sys.argv[2]
    raw = open(src, 'rb').read()
    if hashlib.sha256(raw).hexdigest() != PIN:
        print('REFUSED: PROFILE.json sha256 is not the pinned A-fc profile'); sys.exit(2)
    prof = {int(k): int(v) for k, v in json.loads(raw).items()}
    if prof.get(48) != HEADS:
        print('REFUSED: rank-48 count %s is not the head count %d' % (prof.get(48), HEADS)); sys.exit(2)
    rest = {r: n for r, n in prof.items() if r != 48}
    bad = [r for r in rest if not (1 <= r < KC)]
    if bad:
        print('REFUSED: ranks %s would need a split or are not separated' % bad); sys.exit(2)
    mass = sum(r * n for r, n in prof.items())
    assert mass == 65088 * 74, mass          # FOUND.md mass check: 4,816,512 = 65,088 x 74
    ch = dict(sorted(rest.items()))
    hdr = ("# R5: the mixed rate fact of the FULL cut of A-fc (suffix 2979Fc)\n\n"
           "Generated by fc-rate's tools/mk_rate_mixed.py (e-r45m1's generator; only this header differs); do not edit.\n"
           "Round wht45/afc (20 Oct 2026).  Cut word: the hub's word of PR #2979 (T74 clock) with the re-solved fill\n"
           "u1-2979sep of round wht45/fullcut (A-fc: every child-8/10 bin a literal head, no other idle rank-48 block).\n"
           "Each of its %d literal rank-48 heads is cut by ALL 48 of its axes (no remnant; target rank 25 = 73 - 48 on\n"
           "the head array); nothing is split (the largest other paid rank is %d); the other arrays keep the full\n"
           "target 73.  Every paid rank is at most %d < 25 (separated).  Children (paid blocks of one unit, by rank):\n"
           "`cut2979Fc`.  Arrays: %d full, %d cut.") % (HEADS, max(ch), max(ch), W - HEADS, HEADS)
    js = dict(source="A-fc full cut (wht45/afc BRIEF; fullcut FOUND.md): PROFILE.json of u1-2979sep (sha256 %s) %s; "
                     "the %d literal heads (children 8/10) cut by all 48 axes (target 25); no other rank-48 block, "
                     "nothing split; every paid rank <= %d < 25" % (PIN[:16], json.dumps({str(k): v for k, v in sorted(prof.items())}),
                                                                   HEADS, max(ch)),
              children={str(k): v for k, v in ch.items()}, W=W, H=HEADS, kc=KC, m=M, cut_kind="full cut", header=hdr)
    json.dump(js, open(out, 'w'), indent=1)
    print('written %s: children %s, blocks %d, rmax %d' % (out, ch, sum(ch.values()), max(ch)))


if __name__ == '__main__':
    main()
