"""x-inst (wht45/lever2979, 19 Oct 2026): the WARP variant of p-hfirst's heads-first certificate, by checked text
substitution on p-hfirst's compiled HF files (the same substitutions p-a3's tools/mk_warp.py made to turn TDef/TStage/
TCert into TDefW/TStageW/TCertW).

The #2979 provider words are windowed packages (`KLW.GInvEW .. okW`, p-wgen / x-words), so the real network is p-a3's
`XNetW` (Work/XHostT/T*W.lean), not `XNet`.  p-hfirst's `XNet.heads_first` is stated for `XNet`; this generator writes
Work/XHostT/HFW2979/{Def,Stage,Cert,ToHF,Heads}.lean:
  Def    structure `XNetHW .. Ok` = p-hfirst's `XNetH` with providers `GInvW H T Sl C Ok` and the window facts
         `hok0 .. hok8` (as TDefW);
  Stage  every call route with `gistageW_fwd/bwd` (as TStageW);
  Cert   the sweep and `XNetHW.cert_pre`;
  ToHF   `XNetW.toHF` (the body network of an `XNetW` and head bins) and `XNetW.unit_toHF`; the role-level pieces
         (`hroleT`, `headsL`, `hdHF`, `hdrop`, `sum_hdrop`) are p-hfirst's, imported;
  Heads  `XNetW.heads_first`, `XNetW.heads_first_full` (`headWord_proper`, `headWord_costR` imported).
Namespace `OAI.PowerSaving.XHostTW` (p-a3's warp namespace), module paths with `2979` (round rule: no path collides
with the #3945 round's modules).  The generator refuses if an input's sha256 differs from the version it was written
for, or if a pattern it edits is not found the expected number of times.
usage: python3 -I mk_hfw2979.py P_HFIRST_LEAN_ROOT OUT_LEAN_ROOT
"""
import hashlib, re, sys, os

src, out = sys.argv[1], sys.argv[2]
EXPECT = {
    'Def.lean': None, 'Stage.lean': None, 'Cert.lean': None, 'ToHF.lean': None, 'Heads.lean': None,
}
SHA_FILE = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'hfw2979-inputs.sha256')
pins = {}
if os.path.exists(SHA_FILE):
    for line in open(SHA_FILE):
        h, n = line.split()
        pins[n] = h
OK = "{Ok : ∀ {β : Type} [Fintype β] [DecidableEq β], GWin H β → Prop}"
OKP = "(Ok : ∀ {β : Type} [Fintype β] [DecidableEq β], GWin H β → Prop)"


def die(m):
    sys.exit('REFUSE: ' + m)


def rd(name):
    p = os.path.join(src, 'Work/XHostT/HF', name)
    b = open(p, 'rb').read()
    h = hashlib.sha256(b).hexdigest()
    if name in pins and pins[name] != h:
        die(f'{name} sha256 {h} differs from the pinned {pins[name]}')
    pins.setdefault(name, h)
    return b.decode()


def n_times(s, old, new, n, what):
    k = s.count(old)
    if k != n:
        die(f'pattern for {what} found {k} times (expected {n})')
    return s.replace(old, new)


def once(s, old, new, what):
    return n_times(s, old, new, 1, what)


def cut_block(s, start, end_marker, what):
    """remove the text from `start` up to and including `end_marker` (first occurrence after start)."""
    if s.count(start) != 1:
        die(f'block start for {what} found {s.count(start)} times')
    i = s.index(start)
    j = s.index(end_marker, i) + len(end_marker)
    return s[:i] + s[j:]


def common(s):
    s = n_times(s, 'namespace XHostT\n', 'namespace XHostTW\n', 1, 'namespace')
    s = n_times(s, 'end XHostT\n', 'end XHostTW\n', 1, 'end namespace')
    s = re.sub(r'open (Binary Matrix Finset [^\n]*)', lambda m: 'open ' + m.group(1) + ' XHostT', s)
    s = s.replace('OAI.PowerSaving.XHostT.', 'OAI.PowerSaving.XHostTW.')
    s = re.sub(r'\bXNetH\b', 'XNetHW', s)
    s = re.sub(r'\bXNet\b', 'XNetW', s)
    # every use of the two structures gets the window predicate
    s = re.sub(r'\b(XNetHW|XNetW) H T Sl C α Γ nb nR\b(?! Ok)', r'\1 H T Sl C α Γ nb nR Ok', s)
    # the window predicate as a section variable next to {nb nR}
    s = s.replace('variable {nb nR : ℕ}', 'variable {nb nR : ℕ} ' + OK)
    return s


def stamp(s, what):
    i = s.index('-/\n')
    return (s[:i] + 'WARP variant (' + what + '): generated by x-inst/tools/mk_hfw2979.py (wht45/lever2979, 19 Oct 2026) from\n'
            "p-hfirst's file of the same name (sha256 pinned in tools/hfw2979-inputs.sha256), with p-a3's mk_warp.py\n"
            'substitutions (providers `GInvW .. Ok`, window facts `hok0 .. hok8`, stages `gistageW_fwd/bwd`).\n' + s[i:])


# ---------------------------------------------------------------- Def
d = rd('Def.lean')
d = once(d, 'import Work.XHostT.TDef\n', 'import Work.XHostT.TDefW\n', 'Def import')
d = common(d)
d = once(d, '[Fintype Sl] [DecidableEq Sl] [Fintype C] [DecidableEq C] [Fintype α] [DecidableEq α] where',
         '[Fintype Sl] [DecidableEq Sl] [Fintype C] [DecidableEq C] [Fintype α] [DecidableEq α]\n    ' + OKP + ' where',
         'structure header')
d = once(d, '  I : GInvE H T Sl C\n', '  I : GInvW H T Sl C Ok\n', 'field I')
d = once(d, '  Ic : Fin nR → Fin 9 → GInvE H T Sl C\n', '  Ic : Fin nR → Fin 9 → GInvW H T Sl C Ok\n', 'field Ic')
d = once(d, '  G8 : Γ → GWin H α\n', '  G8 : Γ → GWin H α\n  /-- the provider words\' window condition holds at every window of the network. -/\n' +
         ''.join(f'  hok{l} : ∀ d, Ok (G{l} d)\n' for l in range(9)), 'field G8')
d = once(d, 'def XNetHW.Jc (ρ : Fin nR) (l : Fin 9) : GInvE H T Sl C := XHostD.retagTv (N.Ic ρ l) N.I.tv (N.hIc ρ l)',
         'def XNetHW.Jc (ρ : Fin nR) (l : Fin 9) : GInvW H T Sl C Ok := retagTvW (N.Ic ρ l) N.I.tv (N.hIc ρ l)', 'Jc')
if 'GInvE' in d.split('-/', 1)[1]:
    die('GInvE left in HFW Def')
d = stamp(d, 'Def')

# ---------------------------------------------------------------- Stage
s = rd('Stage.lean')
s = once(s, 'import Work.XHostT.HF.Def\nimport Work.XHostT.TStage\n',
         'import Work.XHostT.HFW2979.Def\nimport Work.XHostT.TStageW\n', 'Stage imports')
s = common(s)
nst = 0
for l in range(9):
    s, k = re.subn(r'gistageE_(fwd|bwd) \(N\.Jc ρ \(' + str(l) + r' : Fin 9\)\) ([^\n]*?) N\.G' + str(l) + ' ',
                   lambda m: f'gistageW_{m.group(1)} (N.Jc ρ ({l} : Fin 9)) {m.group(2)} N.G{l} N.hok{l} ', s)
    nst += k
if 'gistageE' in s:
    die('gistageE left in HFW Stage')
if nst != 9:
    die(f'{nst} stage lemma uses rewritten (expected 9)')
s = s.replace('(bid Γ T)', '(BR.bid Γ T)')
s = stamp(s, 'Stage')

# ---------------------------------------------------------------- Cert
c = rd('Cert.lean')
c = once(c, 'import Work.XHostT.HF.Stage\nimport Work.XHostT.TCert\n',
         'import Work.XHostT.HFW2979.Stage\nimport Work.XHostT.TCertW\n', 'Cert imports')
c = common(c)
c = stamp(c, 'Cert')

# ---------------------------------------------------------------- ToHF
t = rd('ToHF.lean')
t = once(t, 'import Work.XHostT.HF.Cert\n', 'import Work.XHostT.HFW2979.Cert\nimport Work.XHostT.HF.ToHF\n', 'ToHF imports')
# role-level pieces stay p-hfirst's (XHostT namespace, imported)
t = cut_block(t, 'section Role\n', 'end Role\n', 'section Role')
t = cut_block(t, '/-- the head pre-factor of the body network: the head block on head bins, `1` elsewhere. -/\ndef hdHF',
              'else 1\n', 'hdHF')
t = cut_block(t, '/-- the price dropped from the A4 climbs of replica `ρ`: one `φ 48` per head bin of `ρ`. -/\ndef hdrop',
              '(if (ρ, (true, t)) ∈ hb then φ 48 else 0))\n', 'hdrop')
t = cut_block(t, 'lemma sum_hdrop (φ : ℕ → ℝ)', 'Finset.sum_const, nsmul_eq_mul]\n', 'sum_hdrop')
t = common(t)
t = once(t, '  G8 := N.G8\n', '  G8 := N.G8\n' + ''.join(f'  hok{l} := N.hok{l}\n' for l in range(9)), 'toHF G8')
t = t.replace('#print axioms OAI.PowerSaving.XHostTW.headsL_length\n', '')
t = stamp(t, 'ToHF')

# ---------------------------------------------------------------- Heads
h = rd('Heads.lean')
h = once(h, 'import Work.XHostT.HF.ToHF\nimport Work.Mixed.HeadM1\n',
         'import Work.XHostT.HFW2979.ToHF\nimport Work.XHostT.HF.Heads\n', 'Heads imports')
h = cut_block(h, '/-- the head word is proper (`48 < card α`) and costs one `φ 48` per head. -/\nlemma headWord_proper',
              '⟨by norm_num, hα⟩\n', 'headWord_proper')
h = cut_block(h, 'lemma headWord_costR', '    ring\n', 'headWord_costR')
h = common(h)
h = h.replace('#print axioms OAI.PowerSaving.XHostTW.roleProd_heads_hdT\n',
              '#print axioms OAI.PowerSaving.XHostTW.roleProd_heads_hdT\n')
h = stamp(h, 'Heads')

os.makedirs(os.path.join(out, 'Work/XHostT/HFW2979'), exist_ok=True)
for name, txt in (('Def.lean', d), ('Stage.lean', s), ('Cert.lean', c), ('ToHF.lean', t), ('Heads.lean', h)):
    if re.search(r'\bsorry\b', txt.replace('`sorry`', '')):
        die('sorry in ' + name)
    p = os.path.join(out, 'Work/XHostT/HFW2979', name)
    open(p, 'w').write(txt)
    nd = len(re.findall(r'^(?:def|lemma|theorem|structure|abbrev) ', txt, re.M))
    print(f'{p}: {len(txt.splitlines())} lines, {nd} declarations, sha256 {hashlib.sha256(txt.encode()).hexdigest()[:16]}')
if not os.path.exists(SHA_FILE):
    with open(SHA_FILE, 'w') as fh:
        for n in sorted(pins):
            fh.write(f'{pins[n]} {n}\n')
    print('pinned input hashes in', SHA_FILE)
