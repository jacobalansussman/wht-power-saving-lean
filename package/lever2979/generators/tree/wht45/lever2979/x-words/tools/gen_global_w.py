#!/usr/bin/env python3
"""p-wgen (round wht45/lever, 19 Oct 2026): the GLOBAL Lean modules of a warped word (x-words copy for #2979: --expect replaces the #3945 profile) as a standalone word
overlay on the PR #401 unit (72 calls of the word, Bridge377 idle banks, the pad-minimal dedicated bank table):
price of one invocation, rate (block plan at the kernel numerator), bank schedule, unit price, the glue
(invocation package `ginv`, `ginv_cost`, `sched`, `fitsS`, `width`, `price`), the Fourier files (the record's
FourierC401G5 files, Shea's map, as fsp-cc / lg-a1), the challenges at 1 - NUM/10^10 and 1 - (NUM+1)/10^10, the
axioms module and the comparator configurations.

fsp-cc's generate_global_lean_xzs.py (k-combine, k-lower, m-gen, Shea's generate_global_lean.py) with these changes:
R = 408 slots and no local preflight (the warped word has no SPar/E7 batches: its scalar check is p-warpchk's
free-warp-algebra replay); the glue builds the package from p-warpchk's checker (template GLUE below, names from
p-warpchk's INTERFACE.md); the price module is generated here (rank list `rAll` + 8 centre blocks).

REFUSAL: the DFT numerator is A - 1 where A is the LARGEST kernel numerator with a block plan (foldlib.plan_block,
B = 10, s = 40).  With `--dft NUM` the generator refuses unless NUM = A - 1; in particular NUM + 1 (one grid step too
high) is refused, because plan_block(u, NUM + 2) is None (checked and recorded).

usage: gen_global_w.py <price.json> --toolkit <k-combine toolkit dir> --out <dir> --name <NAME> --wgen <wgen-NAME.json>
       [--dft NUM] [--glue <glue template file>]"""
import argparse, gzip, hashlib, json, sys
from collections import Counter
from fractions import Fraction as Q
from pathlib import Path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("price", type=Path)
    ap.add_argument("--toolkit", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--wgen", type=Path, required=True)
    ap.add_argument("--dft", type=int)
    ap.add_argument("--glue", type=Path)
    ap.add_argument("--v2", action="store_true", help="wgen2 data: rAll includes the centre blocks (rank 8)")
    ap.add_argument("--expect", required=True, help="expected local profile (JSON), e.g. #2979's")
    ap.add_argument("--glue-cfg", type=Path, help="JSON: IMPORTS, CTOR, CTOR_APP, COST_PROOF, ENT_PROOF (p-warpchk's names)")
    a = ap.parse_args()
    NAME = a.name
    p = json.loads(a.price.read_text())
    wg = json.loads(a.wgen.read_text())
    sched = json.loads(gzip.decompress(a.price.with_suffix(".schedule.json.gz").read_bytes()))
    sys.path.insert(0, str(a.toolkit / "tools" / "gen"))
    import foldlib as fl
    import foldgen as fg
    u = dict(m=p["m"], W=p["W"], D=p["deficit"], H={int(k): v for k, v in p["profile"].items()})
    R = p["local_residual_count"]
    assert (u["m"], p["v"], R) == (73, 112, 408) and len(sched["widths"]) == R
    A = int(Q(p["exact_rate"]["root_lower"]) * 10 ** 10)
    while fl.plan_block(u, A, 10, 40) is None:
        A -= 1
    assert A == p["kernel_numerator"]
    delta = A - 1
    above = fl.plan_block(u, A + 1, 10, 40)
    if a.dft is not None and a.dft != delta:
        why = ("no block plan at kernel numerator %d (one grid step above the largest, %d)" % (a.dft + 1, A)
               if a.dft > delta else "below the generator's figure %d" % delta)
        print("REFUSED: DFT numerator %d: %s" % (a.dft, why))
        sys.exit(3)
    assert above is None, "plan_block accepts A + 1: the figure is not the largest"
    base = a.out / "Work/GCert/Data"
    (base / "Gen").mkdir(parents=True, exist_ok=True)
    hist = {int(r): n for r, n in p["local_profile"].items()}
    assert hist == {int(r): n for r, n in wg["ranks"].items()} == {int(k): x for k, x in json.loads(a.expect).items()}
    inv = " + ".join(f"{n} * φ {r}" for r, n in sorted(hist.items()))
    # ---- price of one invocation (rank list rAll of the replay segments + the 8 centre blocks)
    nC = 0 if a.v2 else hist[8]
    ranks = dict(hist) if a.v2 else {r: n for r, n in hist.items() if r != 8}
    topr = max(ranks)
    rall = " + ".join(f"{n} * φ {r}" for r, n in sorted(ranks.items()))
    txt = f"""import Work.GCert.Data.Price
import Work.GCert.Data.Gen.{NAME}Hist

/-!
# (key: p-wgen) warped word `{NAME}`: the price of one invocation
Generated by p-wgen's tools/gen_global_w.py.  `rAll_cost`: the price of the block rank list of the whole program
(`GXD.{NAME}.rAll`, counted by the kernel in `Gen.{NAME}Hist`); `inv_cost`: with the {nC} centre blocks of rank 8
the blocks of ONE invocation cost `invPrice φ` = {inv}. -/

namespace GXD.{NAME}
open GXD OAI.PowerSaving.CB

theorem rAll_cost (φ : ℕ → ℝ) : rcost φ rAll = {rall} := by
  rw [GXD.rcost_wsumK φ rAll {topr} rankBound]
  simp only [Finset.sum_range_succ, Finset.sum_range_zero, {", ".join("rank%d_ok" % r for r in range(topr + 1))}]
  norm_num [bcost]

/-- price of the blocks of ONE invocation, by rank -/
def invPrice (φ : ℕ → ℝ) : ℝ := {inv}

theorem inv_cost (φ : ℕ → ℝ) : rcost φ rAll{"" if a.v2 else " + (%d * φ 8)" % nC} = invPrice φ := by
  rw [rAll_cost]
  unfold invPrice
  ring

theorem inv_moves : invPrice (fun r => (r:ℝ)) = {sum(r * n for r, n in hist.items())} := by
  unfold invPrice
  norm_num

end GXD.{NAME}
#print axioms GXD.{NAME}.inv_cost
"""
    (base / f"{NAME}Price.lean").write_text(txt)
    # ---- rate
    body, plan = fg.block_text(NAME + "x", u, A, 10, 40)
    rate = "import Work.BlockAccounting.Moment\nset_option maxRecDepth 4000\nnamespace OAI.PowerSaving.BlockAccounting\nopen Finset\n"
    rate += fg.list_text(NAME + "x", u, "72 copies of the warped #2979 word %s (gcert/1w, p-lower's lowering; 408 helpers, "
                                        "91 zero buffers), #401 dedicated banks, and an explicit %s bank schedule." % (NAME, p["schedule"]))
    rate += "\n" + body + "\nend OAI.PowerSaving.BlockAccounting\n#print axioms OAI.PowerSaving.BlockAccounting.fold_%sx\n" % NAME
    (base / ("Rate%sx.lean" % NAME)).write_text(rate)
    # ---- bank schedule
    rows, pads, widths = sched["rows"], sched["pads"], sched["widths"]
    nb = len(pads)
    top = max(pads)
    counts = Counter(pads)
    assert nb == p["banks"] and p["W"] == 64 * 112 + nb
    imports, parts = [], []
    for i, lo in enumerate(range(0, 72, 4)):
        imports.append("import Work.GCert.Data.Gen.%sRows%d" % (NAME, i))
        parts.append(f"rows{i}")
        t = "namespace GXD.%s\n" % NAME
        t += f"noncomputable def rows{i} : List (List Nat) := {rows[lo:lo + 4]}\nend GXD.{NAME}\n"
        (base / f"Gen/{NAME}Rows{i}.lean").write_text(t)
    t = "\n".join(imports) + "\nimport Work.Bridge401.SchedK\nimport Work.GCert.Data.Count\nset_option maxRecDepth 100000\nnamespace GXD.%s\nopen GXD OAI.PowerSaving\n" % NAME
    t += "noncomputable def schedRows : List (List Nat) := " + " ++ ".join(parts) + "\n"
    t += f"noncomputable def schedPad : List Nat := {pads}\nnoncomputable def schedRes : List Nat := {widths}\n"
    t += f"theorem sched_ok : GX.schedK {nb} {R} schedRows schedPad schedRes = true := by decide +kernel\n"
    t += f"theorem rankBoundP : wsumK (SSC.wGt {top}) schedPad 0 = 0 := by decide +kernel\n"
    t += "\n".join(f"theorem rankP{r}_ok : wsumK (SSC.wEq {r}) schedPad 0 = {counts[r]} := by decide +kernel" for r in range(top + 1))
    t += "\nend GXD.%s\n#print axioms GXD.%s.sched_ok\n" % (NAME, NAME)
    (base / f"Gen/{NAME}Sched.lean").write_text(t)
    pad = " + ".join(f"{n} * bcost φ {r}" for r, n in sorted(counts.items()) if r and n)
    t = f'''import Work.Bridge377.Bank
import Work.FoldRate.Group
import Work.GCert.Data.Rate{NAME}x
namespace OAI.PowerSaving.BridgeRate.{NAME}
open Finset Binary Matrix RAM CB FoldRate
noncomputable section
def invPrice (φ : ℕ → ℝ) : ℝ := {inv}
def padPrice (φ : ℕ → ℝ) : ℝ := {pad}
def unitPrice (φ : ℕ → ℝ) : ℝ := 72 * invPrice φ + ((112:ℕ):ℝ) * GX.bankPrice377 φ + padPrice φ
theorem unit_cost_x (φ : ℕ → ℝ) : unitPrice φ = listCost φ BlockAccounting.blocks{NAME}x := by
  unfold unitPrice invPrice padPrice
  simp only [GX.bankPrice377, listCost, BlockAccounting.blocks{NAME}x, List.map_cons, List.map_nil, List.sum_cons, List.sum_nil]
  norm_num [bcost]
  try ring
theorem unit_tally : unitPrice (fun r => (r:ℝ)) = (({p['W']}:ℕ):ℝ) * 73 - 2560 := by
  rw [unit_cost_x]
  exact BlockAccounting.blocks{NAME}x_tally
end
end OAI.PowerSaving.BridgeRate.{NAME}
#print axioms OAI.PowerSaving.BridgeRate.{NAME}.unit_cost_x
'''
    (base / f"Inst{NAME}.lean").write_text(t)
    # ---- the glue (template with p-warpchk's package constructor)
    rp = ", ".join(f"rankP{r}_ok" for r in range(top + 1))
    if a.glue:
        g = a.glue.read_text()
        fill = dict(json.loads(a.glue_cfg.read_text())) if a.glue_cfg else {}
        fill.update(NAME=NAME, NB=str(nb), W=str(p["W"]), TOP=str(top), RP=rp, R=str(R), NC=str(wg.get("nc", 8)))
        for _ in range(2):          # config values may themselves name @@NAME@@
            for k, v in fill.items():
                g = g.replace("@@%s@@" % k, v)
        assert "@@" not in g, "unfilled glue template field"
        (base / f"{NAME}Glue401.lean").write_text(g)
    # ---- the Fourier seam and transfer (Shea's map, target NAME)
    rec = a.toolkit / "third-party" / "record-templates"
    mapping = {"C401Gg5": NAME, "C401G5": NAME, "GXD.G5": "GXD." + NAME, ".G5": "." + NAME, "/G5": "/" + NAME,
               "10221077": str(A), "10221076": str(delta), "14353": str(p["W"])}
    dst = a.out / ("Work/Fourier%s" % NAME)
    dst.mkdir(parents=True, exist_ok=True)
    provenance = {}
    for source in sorted((rec / "Work/FourierC401G5").glob("*.lean")):
        t = source.read_text().replace("import Submission.", "import ")
        for k, v in mapping.items():
            t = t.replace(k, v)
        if a.v2 and source.name == "Seam.lean":
            # the windowed package (p-warpchk's GInvEW) on the windowed #401 network (p-wgen's Work/PWGen/B401W)
            o1 = "GX.engine_of_ginv_401 GXD.%s.ginv GXD.%s.h9 GXD.%s.sched GXD.%s.fitsS" % (NAME, NAME, NAME, NAME)
            assert t.count(o1) == 1, "seam call not found"
            t = t.replace(o1, "GX.engine_of_ginv_401W GXD.%s.ginvW GXD.%s.h9 GXD.%s.sched GXD.%s.fitsS GXD.%s.okC"
                          % (NAME, NAME, NAME, NAME, NAME))
            o2 = "import Work.Bridge401.End\n"
            assert t.count(o2) == 1
            t = t.replace(o2, o2 + "import Work.PWGen.B401W.EndW\n")
        (dst / source.name).write_text(t)
        provenance[source.name] = hashlib.sha256(source.read_bytes()).hexdigest()
    (a.out / "logs").mkdir(exist_ok=True)
    (a.out / ("logs/global-%s.json" % NAME)).write_text(json.dumps(dict(
        kernel_numerator=A, dft_numerator=delta, denominator=10 ** 10, schedule=p["schedule"], banks=nb, W=p["W"],
        plan_at_kernel_plus_one=above, refuses_dft_plus_one=True,
        pad_hist={str(k): v for k, v in sorted(counts.items())}, rational_slack=plan["slack_rel"],
        fourier_source_sha256=provenance, fourier_substitutions=mapping), indent=2) + "\n")
    print(f"{NAME}: kernel saving {A}/10^10; DFT saving {delta}/10^10; banks {nb}; W {p['W']}; rational slack {plan['slack_rel']}")


if __name__ == "__main__":
    main()
