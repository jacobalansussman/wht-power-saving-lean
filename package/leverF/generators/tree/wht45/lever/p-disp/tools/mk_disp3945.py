"""p-disp (wht45/lever, 19 Oct 2026): #3945's dispatch table as Lean data.

Reads the hub's owner inputs of #3945 (Dugongue; read-only copies on the Mac):
  DISPATCH.json  3,240 entries [stage, replica, tag], in the GLOBAL call order;
  ORDER.json     3,240 entries [stage, replica], the global call order.
Checks (refuses and writes nothing on any failure):
  * both lists have NR * 9 entries; DISPATCH is read as a MAP (stage, replica) -> tag (its list order is not the
    global order: it differs from ORDER.json from entry 62 on), ORDER as the global order;
  * every call (replica rho < NR, stage l < 9) occurs exactly once; the stages of every replica occur in increasing
    global time (the order condition of p-a3's XNet: htm_inj, htm_mono);
  * every tag is 'extra' (provider 0) or 'gauge44' (provider 1);
  * the counts are exactly the expected ones given on the command line (the hub's 1,672 / 1,568); a count one off
    is refused.
Writes Work/XHostT/Data/D3945/Disp.lean:
  dispKB  : Nat   bit k = provider of call k = 9 rho + l (the key of p-a3's kernel host check, field dp of its CT)
  dispGB  : Nat   bit tau = provider of the call at global time tau (ORDER.json order)
  disp, dispG, disp8 (the first 8 replicas) and their counts by `decide +kernel` (XHostD.nCalls);
  and, next to the Lean file, D3945-disp.json (dispK, dispG, tm lists) for the other tracks.
usage: python3 -I mk_disp3945.py DISPATCH.json ORDER.json NR N_EXTRA N_GAUGE OUT.lean"""
import hashlib
import json
import sys

disp_f, ord_f, nr_s, ne_s, ng_s, out = sys.argv[1:7]
NR, NE, NG = int(nr_s), int(ne_s), int(ng_s)
D = json.load(open(disp_f))
O = json.load(open(ord_f))
NC = 9 * NR
fail = []
if len(D) != NC or len(O) != NC:
    fail.append('lengths %d %d, expected %d' % (len(D), len(O), NC))
TAG = {'extra': 0, 'gauge44': 1}
tm = [None] * NC
dK = [None] * NC
dG = []
# DISPATCH.json: the provider of every call (a map; its list order is not the global order)
for i, d in enumerate(D):
    l, rho, tag = d
    if not (0 <= rho < NR and 0 <= l < 9):
        fail.append('DISPATCH call out of range at %d: %r' % (i, d))
        continue
    if tag not in TAG:
        fail.append('unknown tag at %d: %r' % (i, tag))
        continue
    k = 9 * rho + l
    if dK[k] is not None:
        fail.append('DISPATCH: call (rho %d, stage %d) twice' % (rho, l))
        continue
    dK[k] = TAG[tag]
same_order = [list(d[:2]) for d in D] == [list(o) for o in O]
# ORDER.json: the global order
for tau, o in enumerate(O):
    l, rho = o
    if not (0 <= rho < NR and 0 <= l < 9):
        fail.append('ORDER call out of range at %d: %r' % (tau, o))
        continue
    k = 9 * rho + l
    if tm[k] is not None:
        fail.append('ORDER: call (rho %d, stage %d) twice: times %d and %d' % (rho, l, tm[k], tau))
        continue
    tm[k] = tau
    dG.append(dK[k] if dK[k] is not None else -1)
if not fail:
    for k in range(NC):
        if tm[k] is None or dK[k] is None:
            fail.append('call k=%d missing (ORDER %s, DISPATCH %s)' % (k, tm[k], dK[k]))
    for rho in range(NR):
        for l in range(8):
            if not tm[9 * rho + l] < tm[9 * rho + l + 1]:
                fail.append('replica %d: stage %d at %d not before stage %d at %d' % (
                    rho, l, tm[9 * rho + l], l + 1, tm[9 * rho + l + 1]))
if not fail:
    ne, ng = dK.count(0), dK.count(1)
    if (ne, ng) != (NE, NG):
        fail.append('counts extra %d gauge44 %d, expected %d %d' % (ne, ng, NE, NG))
    if (dG.count(0), dG.count(1)) != (ne, ng):
        fail.append('global-order counts differ')
    for k in range(NC):
        if dG[tm[k]] != dK[k]:
            fail.append('dispK[%d] != dispG[tm[%d]]' % (k, k))
            break
if fail:
    sys.stderr.write('REFUSED (nothing written):\n  ' + '\n  '.join(fail[:20]) + '\n')
    sys.exit(3)

sha = lambda f: hashlib.sha256(open(f, 'rb').read()).hexdigest()
n8e = dK[:72].count(0)
n8g = dK[:72].count(1)
L = []
A = L.append
A('''import Work.XHostD.Prov

/-! #3945's dispatch table (Dugongue's owner layer, `owner/inputs/DISPATCH.json` sha256 %s and `ORDER.json`
sha256 %s on the PR branch, read-only copies): %d calls (%d replicas x 9 stages), provider 0 = `extra` (%d calls),
provider 1 = `gauge44` (%d calls).  `dispKB`: bit `k` = provider of call `k = 9 ρ + l`; `dispGB`: bit `τ` = provider of
the call at global time `τ` (bit tables: the kernel reads a bit in one step).  Generated by p-disp/tools/mk_disp3945.py (wht45/lever, 19 Oct 2026), which
checks the order (every call once, stages increasing in time per replica), the tags and the counts, and refuses a count
one off; prepared with assistance from Claude.  No `sorry`. -/

set_option maxRecDepth 100000
namespace OAI.PowerSaving.XHostT.D3945
open OAI.PowerSaving.XHostD Finset
''' % (sha(disp_f), sha(ord_f), NC, NR, NE, NG))
KB = sum(b << k for k, b in enumerate(dK))
GB = sum(b << t for t, b in enumerate(dG))
A('/-- the table by call: bit `k` is the provider of call `k = 9 ρ + l` (0 = extra, 1 = gauge44). -/')
A('def dispKB : Nat := 0x%x' % KB)
A('/-- the table by global call: bit `τ` is the provider of the call at global time `τ` (ORDER.json). -/')
A('def dispGB : Nat := 0x%x' % GB)
A('''
/-- the provider (0 or 1) at bit `k` of a table. -/
def bitP (B k : Nat) : Fin 2 := if (B >>> k) &&& 1 = 1 then 1 else 0

/-- **the dispatch of the network**: call `(ρ, l)` runs provider `bitP dispKB (9 ρ + l)`. -/
def disp : Fin %d × Fin 9 → Fin 2 := fun c => bitP dispKB (9 * c.1.val + c.2.val)

/-- **the counts of the real table** (the hub's %d extra and %d gauge44 calls). -/
theorem nExtra : nCalls disp 0 = %d := by decide +kernel
theorem nGauge : nCalls disp 1 = %d := by decide +kernel

/-- negative control: one call more is false (the count is computed, not assumed). -/
theorem nExtra_ne_succ : nCalls disp 0 ≠ %d + 1 := by decide +kernel
theorem nGauge_ne_succ : nCalls disp 1 ≠ %d + 1 := by decide +kernel

/-- the table by global call (the hub's order). -/
def dispG : Fin (9 * %d) → Fin 2 := fun τ => bitP dispGB τ.val
theorem nExtraG : nCalls dispG 0 = %d := by decide +kernel
theorem nGaugeG : nCalls dispG 1 = %d := by decide +kernel

/-- the first 8 replicas of the table (calls `k < 72`), for the 8-replica controls: %d extra, %d gauge44. -/
def disp8 : Fin 8 × Fin 9 → Fin 2 := fun c => bitP dispKB (9 * c.1.val + c.2.val)
theorem n8Extra : nCalls disp8 0 = %d := by decide +kernel
theorem n8Gauge : nCalls disp8 1 = %d := by decide +kernel

end OAI.PowerSaving.XHostT.D3945
#print axioms OAI.PowerSaving.XHostT.D3945.nExtra
#print axioms OAI.PowerSaving.XHostT.D3945.nGauge
#print axioms OAI.PowerSaving.XHostT.D3945.nExtraG
#print axioms OAI.PowerSaving.XHostT.D3945.nGaugeG
#print axioms OAI.PowerSaving.XHostT.D3945.n8Extra
#print axioms OAI.PowerSaving.XHostT.D3945.nExtra_ne_succ''' % (NR, NE, NG, NE, NG, NE, NG, NR, NE, NG, n8e, n8g, n8e, n8g))
json.dump({'NR': NR, 'provider': {'0': 'extra', '1': 'gauge44'}, 'dispK': dK, 'dispG': dG, 'tm': tm,
           'sha256': {'DISPATCH.json': sha(disp_f), 'ORDER.json': sha(ord_f)}},
          open(out.rsplit('/', 1)[0] + '/D3945-disp.json', 'w'))
open(out, 'w').write('\n'.join(L) + '\n')
print('wrote %s: %d calls, extra %d, gauge44 %d; first 8 replicas extra %d gauge44 %d; DISPATCH list order = ORDER: %s' % (out, NC, NE, NG, n8e, n8g, same_order))
